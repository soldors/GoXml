// TestTasksSemRowStatePoolShrinks 键生命周期：删行后行状态池收缩（For 列表契约 §4）。
func TestTasksSemRowStatePoolShrinks(t *testing.T) {
	vm := NewViewModel()
	v, err := NewGoxmlTasksView(vm)
	if err != nil {
		t.Fatal(err)
	}
	var r input.Router
	gtx := layout.Context{
		Ops:         new(op.Ops),
		Constraints: layout.Exact(image.Pt(560, 400)),
		Metric:      unit.Metric{PxPerDp: 1, PxPerSp: 1},
		Source:      r.Source(),
	}
	frame := func() {
		gtx.Reset()
		v.Layout(gtx, sharedTheme)
		r.Frame(gtx.Ops)
	}
	frame()
	if len(v.rowClicks1) != 3 {
		t.Fatalf("3 行应建 3 个删除状态，实际 %d", len(v.rowClicks1))
	}
	vm.Items = vm.Items[:1]
	frame()
	if len(v.rowClicks1) != 1 {
		t.Fatalf("删到 1 行后池应收缩到 1，实际 %d", len(v.rowClicks1))
	}
	t.Log("行状态池随删除收缩（无界增长被关闭）")
}
