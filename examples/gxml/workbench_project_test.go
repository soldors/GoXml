// TestWorkbenchSemDirtyFlagLifecycle 脏标记的全生命周期。
//
// 关键点：Dirty 是**派生量**（草稿 ≠ 选中行标题），不是需要手动维护的变量。
// 因此"输入 → 脏 / 保存 → 不脏 / 删除选中项 → 不脏"全部由同一处重算得出，
// 不存在"某条路径忘了清空标记"的失效模式。
func TestWorkbenchSemDirtyFlagLifecycle(t *testing.T) {
	sx, sy, ok := posOf(t, "select:2")
	if !ok {
		t.Fatal("未扫到「选择」按钮（第 2 行）")
	}
	h := newHarness(t, nil)
	h.frame()
	// 1) 未选择：没有参照行，不脏。
	if h.vm.Dirty {
		t.Fatalf("未选择时不应判脏: Draft=%q SelectedID=%d", h.vm.Draft, h.vm.SelectedID)
	}
	// 同上：锚到"无未保存"而不是"未保存"，否则两态都会通过。
	if !strings.Contains(h.vm.DirtyText, "无未保存") {
		t.Fatalf("未选择时脏标记文本应说明无未保存修改，实际 %q", h.vm.DirtyText)
	}
	if strings.Contains(h.vm.DirtyText, "有未保存") {
		t.Fatalf("不脏时不应出现「有未保存」字样，实际 %q", h.vm.DirtyText)
	}
	// 2) 刚选中：草稿 == 该行标题，不脏。
	h.click(float32(sx), float32(sy))
	if h.vm.SelectedID != 2 {
		t.Fatalf("选择未生效: %d", h.vm.SelectedID)
	}
	if h.vm.Dirty {
		t.Fatalf("刚选中不应判脏: Draft=%q", h.vm.Draft)
	}
	// 3) 真实输入 → 脏（这一步证明 OnDraftChanged 也走了重算）。
	focusEditor(t, h)
	h.r.Queue(key.EditEvent{Range: key.Range{}, Text: "!"})
	h.frame()
	if !h.vm.Dirty {
		t.Fatalf("输入后应判脏: Draft=%q 该行标题=%q", h.vm.Draft, h.vm.titleOf(2))
	}
	// 判据必须能区分两态：两态文本是「（草稿**有**未保存的修改）」与
	// 「（**无**未保存修改）」，"未保存" 三个字在两态里都出现，
	// 拿它做 Contains 是**空判据**（不脏时也通过）。必须锚到"有"。
	if !strings.Contains(h.vm.DirtyText, "有未保存") {
		t.Fatalf("脏时应提示未保存，实际 %q", h.vm.DirtyText)
	}
	if strings.Contains(h.vm.DirtyText, "无未保存") {
		t.Fatalf("脏时不应出现「无未保存」字样，实际 %q", h.vm.DirtyText)
	}
	// 4) 回车保存 → 草稿与列表一致，回到不脏。
	h.r.Queue(key.Event{Name: key.NameReturn, State: key.Press})
	h.r.Queue(key.Event{Name: key.NameReturn, State: key.Release})
	h.frame()
	if h.vm.Saves != 1 {
		t.Fatalf("回车应保存 1 次，实际 %d", h.vm.Saves)
	}
	if h.vm.Dirty {
		t.Fatalf("保存后不应判脏: Draft=%q 该行标题=%q", h.vm.Draft, h.vm.titleOf(2))
	}
	// 5) 删除选中项：选择清空后没有参照行，仍是不脏。
	rx, ry, ok := posOf(t, "remove:2")
	if !ok {
		t.Fatal("未扫到「删除」按钮（第 2 行）")
	}
	h.click(float32(rx), float32(ry))
	if h.vm.SelectedID != 0 {
		t.Fatalf("删除选中项应清空选择: %d", h.vm.SelectedID)
	}
	if h.vm.Dirty {
		t.Fatal("删除选中项后不应判脏")
	}
	t.Log("OBS 脏标记：未选择不脏 → 选中不脏 → 输入脏 → 保存不脏 → 删除选中项不脏")
}

