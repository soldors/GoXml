package examples

import (
	"bytes"
	"context"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
	"time"

	"github.com/goxml/goxml/internal/cli"
)

// TestStarterProject exercises the same source files and CLI used in the guide.
// The final child command compiles main but never runs a window.
func TestStarterProject(t *testing.T) {
	repo, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	write := func(name string, data []byte) {
		t.Helper()
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	read := func(path string) []byte {
		t.Helper()
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		return data
	}
	// Reuse the repository's pinned dependencies without a network or go mod tidy.
	mod := strings.Replace(string(read(filepath.Join(repo, "go.mod"))),
		"module github.com/goxml/goxml", "module example.com/goxml-starter", 1)
	mod += "\nrequire github.com/goxml/goxml v0.0.0\nreplace github.com/goxml/goxml => " + strconv.Quote(filepath.ToSlash(repo)) + "\n"
	write("go.mod", []byte(mod))
	write("go.sum", read(filepath.Join(repo, "go.sum")))
	for _, name := range []string{"home.gxml", "vm.go"} {
		write(name, read(filepath.Join("testdata", "starter", name)))
	}
	generate := func(want int) {
		t.Helper()
		var out, errs bytes.Buffer
		rc := cli.Run([]string{"generate", filepath.Join(dir, "home.gxml"), "--no-cache"}, &out, &errs)
		if rc != want {
			t.Fatalf("generate rc=%d want=%d\nstdout=%s\nstderr=%s", rc, want, out.String(), errs.String())
		}
		if rc != cli.ExitOK && !strings.Contains(errs.String(), "GXML-BIND-001") {
			t.Fatalf("expected missing-field diagnostic, got %s", errs.String())
		}
	}
	generate(cli.ExitOK)
	genPath := filepath.Join(dir, "home_gen.go")
	first := read(genPath)
	if !bytes.HasPrefix(first, []byte("// Code generated by goxml. DO NOT EDIT.")) || bytes.Contains(first, []byte(repo)) {
		t.Fatal("generated header is missing or leaks the checkout path")
	}
	generate(cli.ExitOK)
	if !bytes.Equal(first, read(genPath)) {
		t.Fatal("identical source generated different bytes")
	}
	manifestPath := filepath.Join(dir, ".goxml", "generate-manifest.json")
	manifest := read(manifestPath)
	validSource := read(filepath.Join(dir, "home.gxml"))
	write("home.gxml", bytes.Replace(validSource, []byte("{Title}"), []byte("{Missing}"), 1))
	generate(cli.ExitFailure)
	if !bytes.Equal(first, read(genPath)) || !bytes.Equal(manifest, read(manifestPath)) {
		t.Fatal("invalid source overwrote generated code or manifest")
	}
	write("home.gxml", validSource)
	// Install the application only after generation: the generator's package
	// context must not depend on a constructor which does not exist yet.
	write(filepath.Join("cmd", "starter", "main.go"), read(filepath.Join("testdata", "starter", "main.go.txt")))
	write("starter_test.go", []byte(`package starter
import "testing"
func TestGeneratedConstructor(t *testing.T) {
    if _, err := NewGoxmlHomeView(nil); err == nil { t.Fatal("nil VM accepted") }
    vm := NewViewModel()
    if _, err := NewGoxmlHomeView(vm); err != nil { t.Fatal(err) }
    vm.Increment()
    if vm.Count != 1 || vm.Title != "Clicked 1 times" { t.Fatalf("bad model: %+v", vm) }
}
`))
	goExe, err := exec.LookPath("go")
	if err != nil {
		t.Fatal("starter compilation requires Go on PATH:", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, goExe, "test", "-mod=readonly", "-p", "2", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOMAXPROCS=2", "GOPROXY=off", "GOSUMDB=off", "GOTOOLCHAIN=local", "GOFLAGS=")
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("starter code did not compile/test: %v\n%s", err, output)
	}
}
