package examples

// R15-C 同源验收：跨包任务板（crosspackage-taskboard）。
//
// 「同源」的意思是：本用例读的材料与教程 README 指向的是**同一份**目录
// （examples/gxml/testprojects/crosspackage-taskboard），没有第二份 fixture、
// 没有另抄的常量表。判据是**同一次运行内**的 before/after 模板指纹：
// 常量表会随材料漂移，before/after 直接抓「有没有写回仓库」。
//
// 与 crosspackage-preferences 的区别（也是本工程存在的理由）：
//   - 列表页用 <For Key="{task.ID}"> 生成**行状态池**（rowClicks0/1 按业务键索引），
//     重排/删除之后点同一坐标必须命中**当前**那一行，删除的键必须被回收；
//   - 摘要页只读，但读的是**同一份** *model.Board；列表里切换之后摘要下一帧就变；
//   - 因此「行身份」与「共享实例」是两件可以各自证伪的事，各有独立的可编译变异。
//
// 窗口入口只构建、从不执行；原生窗口是人工验收项。

import (
	"bytes"
	"context"
	"maps"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"github.com/goxml/goxml/internal/cli"
)

// taskboardModule 是临时 module 的模块路径。模板里的 __MODULE__ 会被替换成它。
const taskboardModule = "example.com/r15taskboard"

// taskboardViews 是本工程的两个生成视图。顺序即生成顺序（同一批）。
var taskboardViews = []struct {
	name   string // 视图名（日志用）
	out    string // 产物相对工程目录
	symbol string // 生成的视图类型名
}{
	{name: "list", out: "view/list/list_gen.go", symbol: "GoxmlListView"},
	{name: "summary", out: "view/summary/summary_gen.go", symbol: "GoxmlSummaryView"},
}

// taskboardSemTests 是模板自带的离屏语义用例。它们和模板一起复制，
// 所以教程、一键脚本、本用例读的是同一批断言。
var taskboardSemTests = []string{
	"TestTaskboardListReorderHitsCurrentRow",
	"TestTaskboardListDeleteKeepsIdentity",
	"TestTaskboardListSummaryFollowsSharedModel",
	"TestTaskboardListInstancesIsolated",
	"TestTaskboardSummaryRendersCounts",
	"TestTaskboardSummaryInstancesIsolated",
}

// taskboardTemplateFiles 是本用例逐个记账的模板材料。
var taskboardTemplateFiles = []string{
	"model/board.go.txt",
	"view/list/list.gxml",
	"view/summary/summary.gxml",
	"view/list/sem_test.go.txt",
	"view/summary/sem_test.go.txt",
	"cmd/taskboard/main.go.txt",
	"go.mod.txt",
}

// taskboardBoardCreations 数入口里创建了几份共享模型。
//
// 这是「入口只创建一次 ViewModel」的**静态**判据：它不能证明运行期共享，
// 但能一刀切断「各建一份」这个最常见的退化写法；运行期共享由
// view/summary 的 h.s.vm == h.m 断言负责。两者互补，缺一不可。
//
// 只数**代码行**：main.go 的注释里就写着「model.NewBoard() 只调用一次」，
// 按字节 Count 会把注释也数进去，判据当场假红——那样它测的是措辞不是行为。
func taskboardBoardCreations(src []byte) int {
	n := 0
	for _, line := range strings.Split(string(src), "\n") {
		code := strings.TrimSpace(line)
		if code == "" || strings.HasPrefix(code, "//") {
			continue
		}
		n += strings.Count(code, "model.NewBoard()")
	}
	return n
}

// TestTaskboardProject 用与教程相同的源材料跑完整工程流程：
// 复制 → 改名 → 填占位符 → **一次目录 generate --check**（覆盖两个 View）→
// 缓存命中 → 坏绑定保旧 → 离线构建入口 → 离屏 Router 交互 → 可编译变异。
func TestTaskboardProject(t *testing.T) {
	repo, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	// 临时目录**故意**带空格与中文：Windows 上很多路径拼接缺陷只在这种路径下暴露。
	root := filepath.Join(t.TempDir(), "跨包 任务板")
	if err := os.MkdirAll(root, 0o755); err != nil {
		t.Fatal(err)
	}

	material := filepath.Join(repo, "examples", "gxml", "testprojects", "crosspackage-taskboard")
	before := map[string]string{}
	for _, rel := range taskboardTemplateFiles {
		before[rel] = sha256Hex(readFile(t, filepath.Join(material, filepath.FromSlash(rel))))
	}
	mustCopyTemplate(t, material, root, taskboardModule, repo)

	if b, err := os.ReadFile(filepath.Join(root, "go.sum")); err != nil || len(b) == 0 {
		t.Fatalf("go.sum 缺失，离线构建会失败: %v", err)
	}

	// 一次目录 generate 覆盖两个 View：发现根 = 输出根 = <root>/view。
	// 这正是 scripts/verify-projects.py 的批次形状（argv: generate view --out-dir view），
	// 也是 R13-C 定下的「一次 generate 覆盖全批」口径——不是每个视图各跑一次。
	viewRoot := filepath.Join(root, "view")
	batch := func(extra ...string) (string, string, int) {
		t.Helper()
		var out, errs bytes.Buffer
		argv := append([]string{"generate", viewRoot, "--out-dir", viewRoot}, extra...)
		rc := cli.Run(argv, &out, &errs)
		return out.String(), errs.String(), rc
	}

	// G1 真实批次生成（带 --check）：两个包一起过提交前检查，一起落盘。
	stdout1, stderr1, rc1 := batch("--check")
	if rc1 != cli.ExitOK {
		t.Fatalf("批次 generate --check rc=%d want=%d\nstdout=%s\nstderr=%s",
			rc1, cli.ExitOK, stdout1, stderr1)
	}
	if !strings.Contains(stdout1, "提交前检查通过：2 个目标包") {
		t.Fatalf("--check 没覆盖两个目标包：%s", stdout1)
	}
	if n := strings.Count(stdout1, "已生成"); n != 2 {
		t.Fatalf("一批应生成 2 个文件，实得 %d：%s", n, stdout1)
	}
	for _, v := range taskboardViews {
		if !strings.Contains(stdout1, filepath.Base(v.out)) {
			t.Fatalf("批次输出未提及 %s：%s", v.out, stdout1)
		}
	}

	first := map[string][]byte{}
	for _, v := range taskboardViews {
		gen := readFile(t, filepath.Join(root, v.out))
		if len(gen) == 0 {
			t.Fatalf("%s 产物为空", v.out)
		}
		if !bytes.HasPrefix(gen, []byte("// Code generated by goxml. DO NOT EDIT.")) {
			t.Fatalf("%s 缺少生成头", v.out)
		}
		if bytes.Contains(gen, []byte(repo)) {
			t.Fatalf("%s 泄漏了 checkout 绝对路径", v.out)
		}
		// 跨包的结构证据：产物必须 import 另一个包里的 ViewModel。
		if !bytes.Contains(gen, []byte(`"`+taskboardModule+`/model"`)) {
			t.Fatalf("%s 未跨包 import model 包：\n%s", v.out, headOf(gen, 20))
		}
		if !bytes.Contains(gen, []byte("type "+v.symbol+" struct")) {
			t.Fatalf("%s 未声明类型 %s", v.out, v.symbol)
		}
		dirPkg := packageClauseOf(t, filepath.Join(root, filepath.Dir(v.out), "doc.go"))
		if !bytes.Contains(gen, []byte("package "+dirPkg+"\n")) {
			t.Fatalf("%s 的 package 子句应为 %q:\n%s", v.out, dirPkg, headOf(gen, 6))
		}
		if dirPkg == "model" {
			t.Fatalf("%s 的包名不该是 model（那就不叫跨包了）", v.out)
		}
		first[v.name] = gen
		t.Logf("OBS %s %d 字节 sha256=%s", v.out, len(gen), sha256Hex(gen))
	}

	// 行状态池是**生成产物**里的字段：断言它们的声明与回收逻辑，才能区分
	// 「按 Key 复用」和「按位置复用」——后者在重排后键集合不变但语义已经串位。
	//
	// 注意不要写死 gofmt 的字段对齐空格（rowClicks0    map[...] 中间是多空格），
	// 那是格式化结果不是契约；判据落在「类型是 map[int]*Clickable」与「按行键查询」上。
	listGen := string(first["list"])
	for _, want := range []string{
		"rowClicks0", "rowClicks1",
		"map[int]*widget.Clickable",
		"if c := v.rowClicks0[rowItem.ID]; c != nil {",
		"if c := v.rowClicks1[rowItem.ID]; c != nil {",
		// 删除行之后池必须按 id 收缩，否则被删行的键会一直留着，
		// 下一次插入同 id 的行会继承旧 Clickable 的点击状态。
		"delete(v.rowClicks0, k)",
		"delete(v.rowClicks1, k)",
	} {
		if !strings.Contains(listGen, want) {
			t.Fatalf("列表产物缺少 %q（行状态池没有按稳定键索引/回收）", want)
		}
	}
	if !strings.Contains(listGen, "v.vm.Toggle(rowItem.ID)") ||
		!strings.Contains(listGen, "v.vm.Remove(rowItem.ID)") {
		t.Fatal("列表产物的事件实参不是行业务键（{task.ID}）")
	}

	// G2 真缓存命中：字节相同、mtime 不动、Manifest 不动。
	manifestPath := filepath.Join(root, ".goxml", "generate-manifest.json")
	manifest := readFile(t, manifestPath)
	for _, v := range taskboardViews {
		if !bytes.Contains(manifest, []byte(filepath.ToSlash(v.out))) {
			t.Fatalf("Manifest 缺少 %s 这一条：\n%s", v.out, manifest)
		}
	}
	sentinel := time.Date(2001, time.January, 1, 0, 0, 0, 0, time.UTC)
	statMtime := func(rel string) time.Time {
		t.Helper()
		st, err := os.Stat(filepath.Join(root, rel))
		if err != nil {
			t.Fatal(err)
		}
		return st.ModTime()
	}
	type cacheRecord struct {
		hash  string
		mtime time.Time
	}
	cacheSnapshot := func() map[string]cacheRecord {
		t.Helper()
		dir := filepath.Join(root, ".goxml", "cache")
		entries, err := os.ReadDir(dir)
		if err != nil {
			t.Fatal(err)
		}
		records := make(map[string]cacheRecord)
		for _, e := range entries {
			if e.IsDir() || filepath.Ext(e.Name()) != ".json" {
				continue
			}
			info, err := e.Info()
			if err != nil {
				t.Fatal(err)
			}
			records[e.Name()] = cacheRecord{sha256Hex(readFile(t, filepath.Join(dir, e.Name()))), info.ModTime()}
		}
		return records
	}
	cacheBefore := cacheSnapshot()
	if len(cacheBefore) != len(taskboardViews) {
		t.Fatalf("首次生成应为两个页面分别登记缓存，实得 %d 条", len(cacheBefore))
	}
	write := func(rel string, data []byte) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(root, rel), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, v := range taskboardViews {
		if err := os.Chtimes(filepath.Join(root, v.out), sentinel, sentinel); err != nil {
			t.Fatal(err)
		}
	}
	stdout2, _, rc2 := batch()
	if rc2 != cli.ExitOK {
		t.Fatalf("第二次批次生成 rc=%d", rc2)
	}
	if strings.Count(stdout2, "缓存命中") != 2 {
		t.Fatalf("第二次生成应两个视图都命中缓存：%s", stdout2)
	}
	for _, v := range taskboardViews {
		if !bytes.Equal(first[v.name], readFile(t, filepath.Join(root, v.out))) {
			t.Fatalf("%s 缓存命中却改了字节", v.out)
		}
		if !statMtime(v.out).Equal(sentinel) {
			t.Fatalf("%s 缓存命中却重写了产物（mtime=%v）", v.out, statMtime(v.out))
		}
	}
	if !bytes.Equal(manifest, readFile(t, manifestPath)) {
		t.Fatal("缓存命中却改写了 Manifest")
	}
	if !maps.Equal(cacheBefore, cacheSnapshot()) {
		t.Fatal("缓存命中改写了缓存记录")
	}
	t.Logf("OBS 真缓存命中：两个视图字节与 mtime 未变，Manifest %d 字节未变", len(manifest))

	// G3 坏绑定保旧：摘要页引用不存在的字段 → 整批放弃，磁盘零变更。
	//
	// 这里断言的诊断码是**实测**的 GXML-BIND-001（R15-C 探针：
	// summary.gxml:11:13: GXML-BIND-001: Value: "MissingField" is neither a loop
	// variable nor a field of model.Board），不是「任意错误都算拒绝」。
	// 与 crosspackage-preferences 的类型错误不同：那里删字段导致**包编译不过**
	// 而报 GXML-ROOT-002，这里字段不存在但包能编译，才走到绑定解析。
	origSummary := readFile(t, filepath.Join(root, "view/summary/summary.gxml"))
	badSummary := bytes.Replace(origSummary, []byte("{DoneText}"), []byte("{MissingField}"), 1)
	if bytes.Equal(badSummary, origSummary) {
		t.Fatal("测试自身的绑定改坏没有生效")
	}
	origList := readFile(t, filepath.Join(root, "view/list/list.gxml"))
	changedList := bytes.Replace(origList, []byte("任务板 · 列表"), []byte("待提交的列表"), 1)
	if bytes.Equal(changedList, origList) {
		t.Fatal("测试自身未让合法的列表页产生新候选")
	}
	write("view/list/list.gxml", changedList)
	write("view/summary/summary.gxml", badSummary)
	_, stderr3, rc3 := batch("--check")
	if rc3 != cli.ExitFailure {
		t.Fatalf("坏绑定应 rc=%d，实得 %d\nstderr=%s", cli.ExitFailure, rc3, stderr3)
	}
	for _, want := range []string{"GXML-BIND-001", "批次全部放弃"} {
		if !strings.Contains(stderr3, want) {
			t.Fatalf("坏绑定诊断缺少 %q：%s", want, stderr3)
		}
	}
	for _, v := range taskboardViews {
		if !bytes.Equal(first[v.name], readFile(t, filepath.Join(root, v.out))) {
			t.Fatalf("坏绑定覆盖了已生成代码 %s", v.out)
		}
		if !statMtime(v.out).Equal(sentinel) {
			t.Fatalf("坏绑定重写了 %s（mtime=%v）", v.out, statMtime(v.out))
		}
	}
	if !bytes.Equal(manifest, readFile(t, manifestPath)) {
		t.Fatal("坏绑定改写了 Manifest")
	}
	if !maps.Equal(cacheBefore, cacheSnapshot()) {
		t.Fatal("坏绑定改变了缓存记录集合、字节或 mtime")
	}
	t.Logf("OBS 坏绑定保旧：%s", strings.TrimSpace(strings.SplitN(stderr3, "\n", 2)[0]))

	// G4 恢复：源回到原样后重新命中缓存，产物与首次逐字一致。
	write("view/summary/summary.gxml", origSummary)
	write("view/list/list.gxml", origList)
	stdout4, _, rc4 := batch()
	if rc4 != cli.ExitOK || strings.Count(stdout4, "缓存命中") != 2 {
		t.Fatalf("恢复后应两个视图重新命中缓存 rc=%d：%s", rc4, stdout4)
	}
	for _, v := range taskboardViews {
		if !bytes.Equal(first[v.name], readFile(t, filepath.Join(root, v.out))) {
			t.Fatalf("恢复后 %s 的产物与首次不一致", v.out)
		}
	}
	if !maps.Equal(cacheBefore, cacheSnapshot()) {
		t.Fatal("恢复后的缓存命中改写了缓存记录")
	}
	t.Logf("OBS 恢复后重新命中：两个视图产物与首次逐字一致")

	// G5 入口结构判据：一份模型，两个视图。
	entrySrc := readFile(t, filepath.Join(root, "cmd/taskboard/main.go"))
	if n := taskboardBoardCreations(entrySrc); n != 1 {
		t.Fatalf("入口应只创建一份 ViewModel（NewBoard 调用 %d 次）", n)
	}
	for _, want := range []string{"list.NewGoxmlListView(m)", "summary.NewGoxmlSummaryView(m)"} {
		if strings.Count(string(entrySrc), want) != 1 {
			t.Fatalf("入口没有把同一个 m 交给两个视图：缺少 %q", want)
		}
	}

	// G6 构建需要 PATH 上的 Go；下面所有子进程都关网、只读模块。
	goExe, err := exec.LookPath("go")
	if err != nil {
		t.Fatal("编译需要 PATH 上的 Go:", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 600*time.Second)
	defer cancel()
	env := append(os.Environ(),
		"CGO_ENABLED=0", "GOMAXPROCS=2", "GOPROXY=off", "GOSUMDB=off",
		"GOTOOLCHAIN=local", "GOFLAGS=-mod=readonly")
	runGo := func(dir string, args ...string) ([]byte, error) {
		cmd := exec.CommandContext(ctx, goExe, args...)
		cmd.Dir = dir
		cmd.Env = env
		return cmd.CombinedOutput()
	}

	// G7 窗口入口：只构建，不执行。
	entry := filepath.Join(root, "taskboard.exe")
	buildOut, buildErr := runGo(root, "build", "-mod=readonly", "-o", entry, "./cmd/taskboard")
	if buildErr != nil {
		t.Fatalf("窗口入口构建失败: %v\n%s", buildErr, buildOut)
	}
	st, err := os.Stat(entry)
	if err != nil || st.Size() == 0 {
		t.Fatalf("窗口入口产物缺失: stat=%v", err)
	}
	t.Logf("OBS 窗口入口 %d 字节（只构建，未运行）", st.Size())

	// G8 离屏语义验收：真实 Router 事件，跑模板自带的 6 个用例。
	semOut, semErr := runGo(root, "test", "-mod=readonly", "-p", "2", "-count=1", "-v",
		"-run", "^TestTaskboard", "./view/...")
	if semErr != nil {
		t.Fatalf("跨包任务板离屏语义测试失败: %v\n%s", semErr, semOut)
	}
	if issues := completionMarkerIssues(semOut, taskboardSemTests, "TASKBOARD-DONE"); len(issues) != 0 {
		t.Fatalf("离屏语义执行未完成: %v\n%s", issues, semOut)
	}
	t.Logf("OBS 离屏语义输出（判据与坐标观测）:\n%s", testCmdOutTail(semOut))

	// G9 可编译变异：每条判据都必须能真的变红，而不是「改完还是绿」。
	//
	// 两条业务变异 + 一条结构变异。业务变异要求**可编译**：编译失败只能说明
	// 改名改崩了，说明不了判据有判别力。
	mutRoot := filepath.Join(t.TempDir(), "变异副本")
	type mutation struct {
		id     string
		file   string
		anchor string
		repl   string
		probe  string
		pkg    string
		note   string
	}
	mutations := []mutation{
		{
			id:     "M1-row-identity-lost",
			file:   "model/board.go",
			anchor: "\t\tif m.Items[i].ID == id {\n\t\t\tm.Items[i].Done = !m.Items[i].Done\n",
			repl: "\t\tif i == len(m.Items)-1 { // M1：无视业务键，永远切最后一行（副本变异）\n" +
				"\t\t\tm.Items[i].Done = !m.Items[i].Done\n",
			probe: "TestTaskboardListReorderHitsCurrentRow",
			pkg:   "./view/list/",
			note:  "行事件按位置而不是按 Key 归属",
		},
		{
			id:     "M2-summary-stale",
			file:   "model/board.go",
			anchor: "\t\t\tm.LastAction = \"toggle:\" + strconv.Itoa(id)\n\t\t\tm.LastTappedID = id\n\t\t\tm.refresh()\n",
			repl: "\t\t\tm.LastAction = \"toggle:\" + strconv.Itoa(id)\n" +
				"\t\t\tm.LastTappedID = id\n\t\t\t// M2：切换后不重算派生串（副本变异）\n",
			probe: "TestTaskboardListSummaryFollowsSharedModel",
			pkg:   "./view/summary/",
			note:  "列表改了共享模型但摘要文本不跟着变",
		},
	}
	for _, mu := range mutations {
		mdir := filepath.Join(mutRoot, mu.id)
		copyTree(t, root, mdir)
		src := readFile(t, filepath.Join(mdir, mu.file))
		if n := strings.Count(string(src), mu.anchor); n != 1 {
			t.Fatalf("变异 %s 的锚点命中 %d 次（应恰好 1 次）：%q", mu.id, n, mu.anchor)
		}
		mutated := strings.Replace(string(src), mu.anchor, mu.repl, 1)
		if mutated == string(src) {
			t.Fatalf("变异 %s 没有生效", mu.id)
		}
		if err := os.WriteFile(filepath.Join(mdir, mu.file), []byte(mutated), 0o644); err != nil {
			t.Fatal(err)
		}
		out, err := runGo(mdir, "test", "-mod=readonly", "-count=1", "-run", "^"+mu.probe+"$", mu.pkg)
		if err == nil {
			t.Fatalf("变异 %s（%s）应用后用例仍为绿：判据没有判别力\n%s", mu.id, mu.note, out)
		}
		if bytes.Contains(out, []byte("[build failed]")) {
			t.Fatalf("变异 %s 不是「可编译变异」——编译就失败了，不能算业务判据变红：\n%s", mu.id, out)
		}
		if !bytes.Contains(out, []byte("--- FAIL: "+mu.probe)) {
			t.Fatalf("变异 %s 的失败不是目标用例变红（缺 --- FAIL: %s）：\n%s", mu.id, mu.probe, out)
		}
		t.Logf("OBS 变异 %s（%s）：%s 变红", mu.id, mu.note, mu.probe)
	}

	// G10 结构变异：入口改成两份模型。它必须**可编译**（否则不是「退化写法」而是
	// 语法错误），并且必须让 taskboardBoardCreations 不再等于 1。
	//
	// 这一条专门保护「共享实例」这条判据：如果哪天有人把 M3 这种写法合进来，
	// 结构判据要能拦住；而如果判据被写成「包含 NewBoard 就算通过」，它就拦不住。
	{
		mdir := filepath.Join(mutRoot, "M3-two-boards")
		copyTree(t, root, mdir)
		mainPath := filepath.Join(mdir, "cmd/taskboard/main.go")
		src := readFile(t, mainPath)
		anchor := "\tm := model.NewBoard()\n"
		if n := strings.Count(string(src), anchor); n != 1 {
			t.Fatalf("M3 锚点命中 %d 次（应恰好 1 次）", n)
		}
		mutated := strings.Replace(string(src), anchor,
			"\tm := model.NewBoard()\n\tother := model.NewBoard() // M3：入口建了两份模型（副本变异）\n", 1)
		mutated = strings.Replace(mutated, "summary.NewGoxmlSummaryView(m)", "summary.NewGoxmlSummaryView(other)", 1)
		if err := os.WriteFile(mainPath, []byte(mutated), 0o644); err != nil {
			t.Fatal(err)
		}
		if n := taskboardBoardCreations([]byte(mutated)); n != 2 {
			t.Fatalf("M3 之后判据应数到 2 份模型，实得 %d", n)
		}
		buildMut, err := runGo(mdir, "build", "-mod=readonly", "-o", filepath.Join(mdir, "m3.exe"), "./cmd/taskboard")
		if err != nil {
			t.Fatalf("M3 必须可编译（否则不算退化写法）：%v\n%s", err, buildMut)
		}
		t.Logf("OBS 变异 M3（入口两份模型）：结构判据 1→2 变红，且仍可编译")
	}

	// 源材料必须一字未动：本用例只读模板、只写临时目录。
	for _, rel := range taskboardTemplateFiles {
		if now := sha256Hex(readFile(t, filepath.Join(material, filepath.FromSlash(rel)))); now != before[rel] {
			t.Fatalf("模板材料 %s 被改动：%s -> %s", rel, before[rel], now)
		}
	}
	t.Logf("OBS 模板材料 %d 个文件指纹未变", len(taskboardTemplateFiles))
}

// completionMarkerIssues 检查「每个用例都 PASS 且打出收尾标记」。
//
// 为什么不能只看 --- PASS：测试函数提前 return 也是 Go PASS。标记行必须落在
// 该用例**最后一条断言之后**，所以「有 PASS 无标记」就是「没跑完」。
//
// 与 crossPackageHealthIssues 的关系：那边把 marker 写死成 CROSS-DONE（既有调用方
// 依赖这个签名），这里把 marker 参数化以便同一套判据服务两个工程。两份实现
// 刻意不合并：改共用函数会动到既有工程的判据，收益只是少 20 行。
func completionMarkerIssues(out []byte, names []string, marker string) []string {
	var issues []string
	text := string(out)
	for _, bad := range []string{"--- SKIP", "--- FAIL", "no test files", "no tests to run"} {
		if strings.Contains(text, bad) {
			issues = append(issues, bad)
		}
	}
	lines := strings.Split(text, "\n")
	for _, name := range names {
		passed, done := false, false
		for _, line := range lines {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "--- PASS: "+name+" (") {
				passed = true
			}
			// testing.Log 会在消息前加 "文件:行: "，所以要求「冒号空格之后整段相等」，
			// 不接受前缀匹配或裸子串——否则 <marker> <name>Suffix 会被误判为完成。
			if at := strings.Index(line, ": "); at >= 0 && line[at+2:] == marker+" "+name {
				done = true
			}
		}
		if !passed {
			issues = append(issues, "missing-pass:"+name)
		}
		if !done {
			issues = append(issues, "missing-completion:"+name)
		}
	}
	return issues
}

// TestTaskboardBoardCreationsGuard 证明「数几份模型」这条判据自己能翻红：
// 注释里出现不算、真实第二份才算。
func TestTaskboardBoardCreationsGuard(t *testing.T) {
	one := "func main() {\n\t// 关键点：model.NewBoard() 只调用一次\n\tm := model.NewBoard()\n}\n"
	if n := taskboardBoardCreations([]byte(one)); n != 1 {
		t.Fatalf("注释里的调用被算进判据：%d", n)
	}
	two := "func main() {\n\tm := model.NewBoard()\n\tother := model.NewBoard() // 第二份\n}\n"
	if n := taskboardBoardCreations([]byte(two)); n != 2 {
		t.Fatalf("真实两份模型没有被数出来：%d", n)
	}
}

// TestTaskboardCompletionGuard 证明上面那套判据自己会红：缺标记、标记错名字、
// 混入 SKIP/FAIL、整包没有可用用例，都必须被拦下。
func TestTaskboardCompletionGuard(t *testing.T) {
	name := "TestTaskboardHealthy"
	healthy := []byte("--- PASS: " + name + " (0.00s)\n    sem_test.go:1: TASKBOARD-DONE " + name + "\n")
	if p := completionMarkerIssues(healthy, []string{name}, "TASKBOARD-DONE"); len(p) != 0 {
		t.Fatalf("健康输出被误判: %v", p)
	}
	for _, bad := range []string{
		"--- PASS: " + name + " (0.00s)\n",
		"--- PASS: " + name + " (0.00s)\n    sem_test.go:1: TASKBOARD-DONE " + name + "Suffix\n",
		"--- PASS: " + name + " (0.00s)\n    sem_test.go:1: CROSS-DONE " + name + "\n",
		string(healthy) + "--- SKIP: Other (0.00s)\n",
		string(healthy) + "--- FAIL: Other (0.00s)\n",
		string(healthy) + "no tests to run\n",
	} {
		if p := completionMarkerIssues([]byte(bad), []string{name}, "TASKBOARD-DONE"); len(p) == 0 {
			t.Fatalf("false green: %q", bad)
		}
	}
}
