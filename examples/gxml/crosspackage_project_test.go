// crossPackageModule 是临时 module 的模块路径。模板里的 __MODULE__ 会被替换成它。
const crossPackageModule = "example.com/r10cross"

// crossPackageViews 是本工程的两个生成视图。顺序即生成顺序。
//
// 两个视图的 .gxml 都声明 ViewModel="model.Preferences"（跨包），
// 因此产物落在各自目录的包里、并 import `.../model`。
var crossPackageViews = []struct {
	name   string // 视图名（日志用）
	gxml   string // .gxml 相对工程目录
	out    string // 产物相对工程目录
	symbol string // 生成的视图类型名
}{
	{name: "edit", gxml: "view/edit/edit.gxml", out: "view/edit/edit_gen.go", symbol: "GoxmlEditView"},
	{name: "summary", gxml: "view/summary/summary.gxml", out: "view/summary/summary_gen.go", symbol: "GoxmlSummaryView"},
}

// crossPackageSemTests 是模板自带的离屏语义测试。它们和模板一起复制，
// 因此「教程」与「测试」读的是同一份材料，不存在第二份 fixture。
var crossPackageSemTests = []string{
	"TestCrossEditDraftKeepsSaved",
	"TestCrossEditMaxLenCountsRunes",
	"TestCrossEditPortFilterDropsNonDigits",
	"TestCrossEditConfirmWritesSaved",
	"TestCrossEditConfirmRejectedKeepsSaved",
	"TestCrossEditResetRestoresSaved",
	"TestCrossEditReturnPayloadOnly",
	"TestCrossEditStatusBranch",
	"TestCrossEditInstancesIsolated",
	"TestCrossSummaryFollowsSharedModel",
	"TestCrossSummaryInstancesIsolated",
}

// TestCrossPackageProject 用与教程相同的源材料
// （examples/gxml/testprojects/crosspackage-preferences）跑一遍完整工程流程：
// 复制 → 改名 → 填占位符 → 真实 CLI 生成两个视图 → 离线 go build → 离屏 Router 交互验收。
//
// 与 testdata 下五个示例的根本区别：
//   - 状态在**独立 model 包**，两个生成视图在**另外两个包**，入口用现有 Go 组合；
//   - 一页只读（summary），没有任何事件与输入控件，它的验收只能是「渲染出来的文本」；
//   - 因此验收必须跨包：摘要视图的文本槽位是 view/summary 的包内字段，
//     而交互必须发生在 view/edit 上——两者只能靠共享模型连接。
//
// 窗口入口只构建、不执行；原生窗口与 IME 是人工验收项（Input 输出契约 §9 场景 15）。
func TestCrossPackageProject(t *testing.T) {
	repo, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	// 临时目录**故意**带空格与中文：Windows 上很多路径拼接缺陷只在这种路径下暴露。
	root := filepath.Join(t.TempDir(), "跨包 工程")
	if err := os.MkdirAll(root, 0o755); err != nil {
		t.Fatal(err)
	}

	// 1) 复制模板材料：*.go.txt → *.go，go.mod.txt → go.mod，替换两个占位符。
	//    复制逻辑与 README 的步骤一一对应；材料里没有任何平行 fixture。
	material := filepath.Join(repo, "examples", "gxml", "testprojects", "crosspackage-preferences")
	before := map[string]string{}
	for _, rel := range templateFiles {
		before[rel] = sha256Hex(readFile(t, filepath.Join(material, filepath.FromSlash(rel))))
	}
	mustCopyTemplate(t, material, root, crossPackageModule, repo)

	if b, err := os.ReadFile(filepath.Join(root, "go.sum")); err != nil || len(b) == 0 {
		t.Fatalf("go.sum 缺失，离线构建会失败: %v", err)
	}

	generate := func(gxml string, want int, extra ...string) (string, string) {
		t.Helper()
		var out, errs bytes.Buffer
		argv := append([]string{"generate", filepath.Join(root, gxml)}, extra...)
		rc := cli.Run(argv, &out, &errs)
		if rc != want {
			t.Fatalf("generate %v rc=%d want=%d\nstdout=%s\nstderr=%s", argv, rc, want, out.String(), errs.String())
		}
		return out.String(), errs.String()
	}

	// G1 真实生成：两个视图各一条命令，各自落在自己的包里。
	first := map[string][]byte{}
	for _, v := range crossPackageViews {
		generate(v.gxml, cli.ExitOK)
		gen := readFile(t, filepath.Join(root, v.out))
		if len(gen) == 0 {
			t.Fatalf("%s 产物为空", v.out)
		}
		if !bytes.HasPrefix(gen, []byte("// Code generated by goxml. DO NOT EDIT.")) {
			t.Fatalf("%s 缺少生成头", v.out)
		}
		if bytes.Contains(gen, []byte(repo)) {
			t.Fatalf("%s 泄漏了 checkout 绝对路径", v.out)
		}
		// 跨包的**结构证据**：产物必须 import 另一个包里的 ViewModel。
		if !bytes.Contains(gen, []byte(`"`+crossPackageModule+`/model"`)) {
			t.Fatalf("%s 未跨包 import model 包：\n%s", v.out, headOf(gen, 20))
		}
		if !bytes.Contains(gen, []byte("type "+v.symbol+" struct")) {
			t.Fatalf("%s 未声明类型 %s", v.out, v.symbol)
		}
		first[v.name] = gen
		t.Logf("OBS %s %d 字节 sha256=%s", v.out, len(gen), sha256Hex(gen))
	}

	// 结构证据之二：生成产物所在包的包名与该 .gxml 目录的包名一致，
	// 而 ViewModel 的类型定义在 model 包——两边不是同一个包。
	for _, v := range crossPackageViews {
		dirPkg := packageClauseOf(t, filepath.Join(root, filepath.Dir(v.out), "doc.go"))
		if !bytes.Contains(first[v.name], []byte("package "+dirPkg+"\n")) {
			t.Fatalf("%s 的 package 子句应为 %q:\n%s", v.out, dirPkg, headOf(first[v.name], 6))
		}
		if dirPkg == "model" {
			t.Fatalf("%s 的包名不该是 model（那就不叫跨包了）", v.out)
		}
	}

	// G2 缓存命中：字节相同、mtime 不动（真的没重写）、Manifest 不动。
	manifestPath := filepath.Join(root, ".goxml", "generate-manifest.json")
	manifest := readFile(t, manifestPath)
	for _, marker := range []string{"view/edit/edit_gen.go", "view/summary/summary_gen.go"} {
		if !bytes.Contains(manifest, []byte(marker)) {
			t.Fatalf("Manifest 缺少 %s 这一条：\n%s", marker, manifest)
		}
	}
	sentinel := time.Date(2001, time.January, 1, 0, 0, 0, 0, time.UTC)
	statMtime := func(rel string) time.Time {
		t.Helper()
		st, err := os.Stat(filepath.Join(root, rel))
		if err != nil {
			t.Fatal(err)
		}
		return st.ModTime()
	}
	write := func(rel string, data []byte) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(root, rel), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, v := range crossPackageViews {
		if err := os.Chtimes(filepath.Join(root, v.out), sentinel, sentinel); err != nil {
			t.Fatal(err)
		}
	}
	for _, v := range crossPackageViews {
		out, _ := generate(v.gxml, cli.ExitOK)
		if !strings.Contains(out, "缓存命中") {
			t.Fatalf("第二次生成 %s 未命中缓存：%s", v.gxml, out)
		}
		if !bytes.Equal(first[v.name], readFile(t, filepath.Join(root, v.out))) {
			t.Fatalf("%s 缓存命中却改了字节", v.out)
		}
		if !statMtime(v.out).Equal(sentinel) {
			t.Fatalf("%s 缓存命中却重写了产物（mtime=%v）", v.out, statMtime(v.out))
		}
	}
	if !bytes.Equal(manifest, readFile(t, manifestPath)) {
		t.Fatal("缓存命中却改写了 Manifest")
	}
	t.Logf("OBS 缓存命中：两个视图字节与 mtime 未变，Manifest %d 字节未变", len(manifest))

	// G3 只改 model 让缓存失效：产物字节应当**不变**（改的是注释），但必须真重写。
	//
	// 这一条同时钉住两件事：依赖闭包（model 包源码）进了缓存键；以及「失效」
	// 不是靠比对产物字节实现的——字节一样也照写，否则无法区分「命中」和「漏写」。
	origModel := readFile(t, filepath.Join(root, "model/preferences.go"))
	commented := bytes.Replace(origModel,
		[]byte("// refresh 在**事件处理器**里准备所有显示串"),
		[]byte("// refresh 在**事件处理器**里准备所有显示串（R10 缓存失效探针）"), 1)
	if bytes.Equal(commented, origModel) {
		t.Fatal("测试自身的 model 注释修改没有生效")
	}
	write("model/preferences.go", commented)
	afterInvalidate := map[string]time.Time{}
	for _, v := range crossPackageViews {
		out, _ := generate(v.gxml, cli.ExitOK)
		if strings.Contains(out, "缓存命中") {
			t.Fatalf("只改 model 后 %s 仍命中缓存：%s", v.gxml, out)
		}
		if !bytes.Equal(first[v.name], readFile(t, filepath.Join(root, v.out))) {
			t.Fatalf("%s 只改模型注释却变了产物字节", v.out)
		}
		if statMtime(v.out).Equal(sentinel) {
			t.Fatalf("%s 失效后没有真正重写（仍是哨兵 mtime）", v.out)
		}
		afterInvalidate[v.name] = statMtime(v.out)
	}
	t.Logf("OBS 仅改 model 即失效：两个视图均重写，字节未变")

	// G4 结构错误：.gxml 少一个闭合标签 → 退出码 2，旧产物与 Manifest 一字不动。
	origEdit := readFile(t, filepath.Join(root, "view/edit/edit.gxml"))
	write("view/edit/edit.gxml", bytes.Replace(origEdit, []byte("</Goxml>"), []byte(""), 1))
	_, errs4 := generate("view/edit/edit.gxml", cli.ExitFailure)
	if !strings.Contains(errs4, "GXML-SYNTAX") {
		t.Fatalf("结构错误应报 GXML-SYNTAX，实际 stderr=%s", errs4)
	}
	if !bytes.Equal(first["edit"], readFile(t, filepath.Join(root, "view/edit/edit_gen.go"))) {
		t.Fatal("结构错误覆盖了已生成代码")
	}
	if !bytes.Equal(manifest, readFile(t, manifestPath)) {
		t.Fatal("结构错误改写了 Manifest")
	}
	write("view/edit/edit.gxml", origEdit)
	t.Logf("OBS 结构错误保旧：%s", strings.TrimSpace(strings.SplitN(errs4, "\n", 2)[0]))

	// G5 类型错误：删掉 model 里的 SavedName 字段 → 摘要页的绑定解析不了，
	// 退出码 2，旧产物与 Manifest 一字不动。
	origSummary := readFile(t, filepath.Join(root, "view/summary/summary.gxml"))
	noField := bytes.Replace(origModel, []byte("\tSavedName string\n"), []byte(""), 1)
	if bytes.Equal(noField, origModel) {
		t.Fatal("测试自身的字段删除没有生效")
	}
	write("model/preferences.go", noField)
	_, errs5 := generate("view/summary/summary.gxml", cli.ExitFailure)
	// 实测诊断码是 GXML-ROOT-002（ViewModel 所在包加载失败），而不是字段级的
	// GXML-BIND-001：删掉字段后 **包本身**就编译不过，前端在解析 ViewModel 时
	// 已经失败，尚未走到绑定解析。断言码本身，避免「任意错误都算拒绝」。
	if !strings.Contains(errs5, "GXML-ROOT-002") {
		t.Fatalf("类型错误应报 GXML-ROOT-002，实际 stderr=%s", errs5)
	}
	if !bytes.Equal(first["summary"], readFile(t, filepath.Join(root, "view/summary/summary_gen.go"))) {
		t.Fatal("类型错误覆盖了已生成代码")
	}
	if !bytes.Equal(manifest, readFile(t, manifestPath)) {
		t.Fatal("类型错误改写了 Manifest")
	}
	t.Logf("OBS 类型错误保旧：%s", strings.TrimSpace(strings.SplitN(errs5, "\n", 2)[0]))

	// G6 恢复：模型与源回到原样后，缓存重新命中，产物与首次逐字一致。
	write("model/preferences.go", origModel)
	for _, v := range crossPackageViews {
		out, _ := generate(v.gxml, cli.ExitOK)
		if !strings.Contains(out, "缓存命中") {
			t.Fatalf("恢复后 %s 应重新命中缓存：%s", v.gxml, out)
		}
		if !bytes.Equal(first[v.name], readFile(t, filepath.Join(root, v.out))) {
			t.Fatalf("恢复后 %s 的产物与首次不一致", v.out)
		}
	}
	t.Logf("OBS 恢复后重新命中：两个视图产物与首次逐字一致（summary 源 %d 字节）", len(origSummary))

	// G7 --no-cache：即使字节相同也必须真重写（绕过缓存，不绕过写盘）。
	for _, v := range crossPackageViews {
		before := statMtime(v.out)
		generate(v.gxml, cli.ExitOK, "--no-cache")
		if !bytes.Equal(first[v.name], readFile(t, filepath.Join(root, v.out))) {
			t.Fatalf("%s 用 --no-cache 生成出不同字节", v.out)
		}
		if statMtime(v.out).Equal(before) {
			t.Fatalf("%s 用 --no-cache 没有实际重写（mtime 未变）", v.out)
		}
	}
	t.Logf("OBS --no-cache：两个视图都真重写且字节等价")

	// G8 非法绑定负例：引用不存在的字段 → GXML-BIND-001，磁盘零变更。
	write("view/edit/edit.gxml", bytes.Replace(origEdit, []byte("{DirtyText}"), []byte("{Missing}"), 1))
	_, errs8 := generate("view/edit/edit.gxml", cli.ExitFailure)
	if !strings.Contains(errs8, "GXML-BIND-001") {
		t.Fatalf("非法绑定应报 GXML-BIND-001，实际 stderr=%s", errs8)
	}
	if !bytes.Equal(first["edit"], readFile(t, filepath.Join(root, "view/edit/edit_gen.go"))) {
		t.Fatal("非法绑定覆盖了已生成代码")
	}
	write("view/edit/edit.gxml", origEdit)

	// G9 包名冲突负例：目标包里多出一个别的 package → fail-closed，磁盘零变更。
	//
	// 这条负例不是为了「覆盖一个错误分支」，而是钉住输出契约 §3.2 的定名口径：
	// 目标目录必须是**唯一**一个 Go package，猜一个算一个会让产物写进错误包名。
	write(filepath.Join("view", "edit", "conflict.go"), []byte("package other\n"))
	_, errs9 := generate("view/edit/edit.gxml", cli.ExitFailure)
	if strings.TrimSpace(errs9) == "" {
		t.Fatal("包名冲突必须有诊断输出")
	}
	if !bytes.Equal(first["edit"], readFile(t, filepath.Join(root, "view/edit/edit_gen.go"))) {
		t.Fatal("包名冲突覆盖了已生成代码")
	}
	if err := os.Remove(filepath.Join(root, "view", "edit", "conflict.go")); err != nil {
		t.Fatal(err)
	}
	t.Logf("OBS 两个负例都未写盘：%s", strings.TrimSpace(strings.SplitN(errs9, "\n", 2)[0]))
	// 负例之后再把状态复位到「刚生成完」，下面的语义测试才在干净产物上跑。
	for _, v := range crossPackageViews {
		generate(v.gxml, cli.ExitOK)
	}
	t.Logf("OBS 失效后 mtime：edit=%v summary=%v", afterInvalidate["edit"], afterInvalidate["summary"])

	// G10 离屏语义验收：跑模板自带的测试（真实事件走 input.Router）。
	goExe, err := exec.LookPath("go")
	if err != nil {
		t.Fatal("编译需要 PATH 上的 Go:", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 600*time.Second)
	defer cancel()
	env := append(os.Environ(),
		"CGO_ENABLED=0", "GOMAXPROCS=2", "GOPROXY=off", "GOSUMDB=off",
		"GOTOOLCHAIN=local", "GOFLAGS=-mod=readonly")
	runGo := func(dir string, args ...string) ([]byte, error) {
		cmd := exec.CommandContext(ctx, goExe, args...)
		cmd.Dir = dir
		cmd.Env = env
		return cmd.CombinedOutput()
	}

	semOut, semErr := runGo(root, "test", "-mod=readonly", "-p", "2", "-count=1", "-v",
		"-run", "^TestCross", "./view/...")
	if semErr != nil {
		t.Fatalf("跨包离屏语义测试失败: %v\n%s", semErr, semOut)
	}
	if issues := crossPackageHealthIssues(semOut, crossPackageSemTests); len(issues) != 0 {
		t.Fatalf("跨包语义执行未完成: %v\n%s", issues, semOut)
	}
	t.Logf("OBS 离屏语义输出（判据与坐标观测）:\n%s", testCmdOutTail(semOut))

	// G11 窗口入口：只构建，不执行。
	entry := filepath.Join(root, "crosspackage-entry.exe")
	buildOut, buildErr := runGo(root, "build", "-mod=readonly", "-o", entry, "./cmd/preferences")
	if buildErr != nil {
		t.Fatalf("窗口入口构建失败: %v\n%s", buildErr, buildOut)
	}
	st, err := os.Stat(entry)
	if err != nil || st.Size() == 0 {
		t.Fatalf("窗口入口产物缺失: stat=%v", err)
	}
	t.Logf("OBS 窗口入口 %d 字节（只构建，未运行）", st.Size())

	// G12 判别变异：把模型里的**业务接线**改坏（只改副本，模板与临时工程都不动），
	// 对应行为用例必须真的变红——否则那条判据没有判别力。
	//
	// 两个变异都要求「可编译」：编译失败说明不了判据有判别力，只能说明改名改崩了。
	mutRoot := filepath.Join(t.TempDir(), "变异副本")
	type mutation struct {
		id     string
		file   string
		anchor string
		repl   string
		probe  string
		pkg    string
		note   string
	}
	mutations := []mutation{
		{
			id:     "M1-saved-wiring-lost",
			file:   "model/preferences.go",
			anchor: "\tm.SavedName = m.Name\n",
			repl:   "\t_ = m.Name // M1：确认不写已保存值（副本变异）\n",
			probe:  "TestCrossEditConfirmWritesSaved",
			pkg:    "./view/edit/",
			note:   "保存接线丢失",
		},
		{
			id:     "M2-summary-stale",
			file:   "model/preferences.go",
			anchor: "\tm.LastAction = \"confirm\"\n\tm.refresh()\n",
			repl:   "\tm.LastAction = \"confirm\" // M2：确认后不重算派生串（副本变异）\n",
			probe:  "TestCrossSummaryFollowsSharedModel",
			pkg:    "./view/summary/",
			note:   "摘要不随模型更新",
		},
	}
	for _, mu := range mutations {
		mdir := filepath.Join(mutRoot, mu.id)
		copyTree(t, root, mdir)
		src := readFile(t, filepath.Join(mdir, mu.file))
		if n := strings.Count(string(src), mu.anchor); n != 1 {
			t.Fatalf("变异 %s 的锚点命中 %d 次（应恰好 1 次）：%q", mu.id, n, mu.anchor)
		}
		mutated := strings.Replace(string(src), mu.anchor, mu.repl, 1)
		if mutated == string(src) {
			t.Fatalf("变异 %s 没有生效", mu.id)
		}
		if err := os.WriteFile(filepath.Join(mdir, mu.file), []byte(mutated), 0o644); err != nil {
			t.Fatal(err)
		}
		out, err := runGo(mdir, "test", "-mod=readonly", "-count=1", "-run", "^"+mu.probe+"$", mu.pkg)
		if err == nil {
			t.Fatalf("变异 %s（%s）应用后用例仍为绿：判据没有判别力\n%s", mu.id, mu.note, out)
		}
		if bytes.Contains(out, []byte("[build failed]")) {
			t.Fatalf("变异 %s 不是「可编译变异」——编译就失败了，不能算业务判据变红：\n%s", mu.id, out)
		}
		if !bytes.Contains(out, []byte("--- FAIL: "+mu.probe)) {
			t.Fatalf("变异 %s 的失败不是目标用例变红（缺 --- FAIL: %s）：\n%s", mu.id, mu.probe, out)
		}
		t.Logf("OBS 变异 %s（%s）：%s 变红", mu.id, mu.note, mu.probe)
	}

	// 源材料必须一字未动：本用例只读模板、只写临时目录。
	// 判据是**同一次运行内**的 before/after 指纹，不是另抄一份常量表——
	// 常量表会随材料漂移，而 before/after 直接抓「有没有写回仓库」。
	for _, rel := range templateFiles {
		if now := sha256Hex(readFile(t, filepath.Join(material, filepath.FromSlash(rel)))); now != before[rel] {
			t.Fatalf("模板材料 %s 被改动：%s -> %s", rel, before[rel], now)
		}
	}
	t.Logf("OBS 模板材料 %d 个文件指纹未变", len(templateFiles))
}

