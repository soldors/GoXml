// copyTree 复制整个工程目录（用于变异副本）。跳过窗口入口产物：
// 它是 12 MB 的 exe，复制它只会拖慢用例，对变异判据没有任何作用。
func copyTree(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.WalkDir(src, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		if rel == "." {
			return os.MkdirAll(dst, 0o755)
		}
		if d.IsDir() {
			return os.MkdirAll(filepath.Join(dst, rel), 0o755)
		}
		if strings.HasSuffix(d.Name(), ".exe") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(dst, rel), data, 0o644)
	})
	if err != nil {
		t.Fatalf("复制工程目录失败: %v", err)
	}
}

// mustCopyTemplate 把模板目录复制成可构建的工程目录。
//
// 与 README 的步骤一致：`*.go.txt` → `*.go`、`go.mod.txt` → `go.mod`、
// 填入 __MODULE__ / __GOXML_DIR__、补 go.sum（离线构建必需）。
func mustCopyTemplate(t *testing.T, material, root, module, repo string) {
	t.Helper()
	err := filepath.WalkDir(material, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(material, path)
		if err != nil {
			return err
		}
		if rel == "." {
			return nil
		}
		dst := filepath.Join(root, rel)
		if d.IsDir() {
			return os.MkdirAll(dst, 0o755)
		}
		if name := d.Name(); strings.HasSuffix(name, ".go.txt") {
			dst = filepath.Join(root, strings.TrimSuffix(rel, ".txt"))
		} else if name == "go.mod.txt" {
			// `go.mod.txt` 不以 `.go.txt` 结尾（最后一个点是 `.txt`），单独改名。
			dst = filepath.Join(root, strings.TrimSuffix(rel, ".txt"))
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		switch filepath.Ext(dst) {
		case ".go", ".mod":
			data = bytes.ReplaceAll(data, []byte("__MODULE__"), []byte(module))
			data = bytes.ReplaceAll(data, []byte("__GOXML_DIR__"), []byte(filepath.ToSlash(repo)))
		}
		return os.WriteFile(dst, data, 0o644)
	})
	if err != nil {
		t.Fatalf("复制模板失败: %v", err)
	}
	// go.sum 来自仓库根：模板不复制第三方校验和文件，避免它随依赖升级漂移。
	sum := readFile(t, filepath.Join(repo, "go.sum"))
	if err := os.WriteFile(filepath.Join(root, "go.sum"), sum, 0o644); err != nil {
		t.Fatal(err)
	}
}

func readFile(t *testing.T, path string) []byte {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("读取 %s 失败: %v", path, err)
	}
	return data
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func headOf(data []byte, n int) string {
	lines := strings.Split(string(data), "\n")
	if len(lines) > n {
		lines = lines[:n]
	}
	return strings.Join(lines, "\n")
}

// packageClauseOf 读一个 Go 文件的 package 子句。
func packageClauseOf(t *testing.T, path string) string {
	t.Helper()
	for _, line := range strings.Split(string(readFile(t, path)), "\n") {
		if strings.HasPrefix(line, "package ") {
			return strings.TrimSpace(strings.TrimPrefix(line, "package "))
		}
	}
	t.Fatalf("%s 没有 package 子句", path)
	return ""
}

// crossPackageHealthIssues requires an exact terminal marker after each case's
// final assertion. A test function returning early is still a Go PASS.
func crossPackageHealthIssues(out []byte, names []string) []string {
	var issues []string
	text := string(out)
	for _, bad := range []string{"--- SKIP", "--- FAIL", "no test files", "no tests to run"} {
		if strings.Contains(text, bad) {
			issues = append(issues, bad)
		}
	}
	lines := strings.Split(text, "\n")
	for _, name := range names {
		passed, done := false, false
		for _, line := range lines {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "--- PASS: "+name+" (") {
				passed = true
			}
			// testing.Log prefixes the source location; require the exact message
			// suffix after that location, not a test-name prefix or a raw substring.
			if at := strings.Index(line, ": "); at >= 0 && line[at+2:] == "CROSS-DONE "+name {
				done = true
			}
		}
		if !passed {
			issues = append(issues, "missing-pass:"+name)
		}
		if !done {
			issues = append(issues, "missing-completion:"+name)
		}
	}
	return issues
}

func TestCrossPackageCompletionGuard(t *testing.T) {
	name := "TestCrossHealthy"
	healthy := []byte("--- PASS: " + name + " (0.00s)\n    sem_test.go:1: CROSS-DONE " + name + "\n")
	if p := crossPackageHealthIssues(healthy, []string{name}); len(p) != 0 {
		t.Fatal(p)
	}
	for _, bad := range []string{
		"--- PASS: " + name + " (0.00s)\n",
		"--- PASS: " + name + " (0.00s)\n    sem_test.go:1: CROSS-DONE " + name + "Suffix\n",
		string(healthy) + "--- SKIP: Other (0.00s)\n",
		string(healthy) + "--- FAIL: Other (0.00s)\n",
		string(healthy) + "no tests to run\n",
	} {
		if p := crossPackageHealthIssues([]byte(bad), []string{name}); len(p) == 0 {
			t.Fatalf("false green: %q", bad)
		}
	}
}

func TestCrossPackageCompletionGuardRejectsCompilingEarlyReturn(t *testing.T) {
	root := t.TempDir()
	src := "package early\nimport \"testing\"\nfunc TestCrossEarly(t *testing.T) { return; t.Log(\"CROSS-DONE TestCrossEarly\") }\n"
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.com/early\n\ngo 1.26\n"), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "early_test.go"), []byte(src), 0600); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "go", "test", "-count=1", "-v", ".")
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOPROXY=off", "GOTOOLCHAIN=local", "GOFLAGS=-mod=readonly")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("counterexample must compile and PASS: %v\n%s", err, out)
	}
	if !bytes.Contains(out, []byte("--- PASS: TestCrossEarly")) {
		t.Fatalf("no observed child PASS: %s", out)
	}
	issues := crossPackageHealthIssues(out, []string{"TestCrossEarly"})
	if len(issues) != 1 || issues[0] != "missing-completion:TestCrossEarly" {
		t.Fatalf("early return not detected: %v\n%s", issues, out)
	}
}
