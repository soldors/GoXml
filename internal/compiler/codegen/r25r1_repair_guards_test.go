package codegen

// R23-R1/R25-R1 返修守卫（来自 R25 协调者独立探针，格式化后采纳为持久守卫）：
//   - F-B1：Expanded 子节点自身 Width 不得静默丢失（生成字节必须不同）；
//   - F-B2：Expanded 自身 Padding 不得静默忽略；Grid 内 Expanded 不得静默接受。
// 语义仍是隔离候选，未批准不进 ready。

import (
	"bytes"
	"testing"
)

func TestCoordinatorExpandedChildSizeNotIgnored(t *testing.T) {
	a, err := Generate(verified(t, `<Row><Expanded><Text Value="x"/></Expanded></Row>`), defaultOpts())
	if err != nil {
		t.Fatal(err)
	}
	b, err := Generate(verified(t, `<Row><Expanded><Text Width="12" Value="x"/></Expanded></Row>`), defaultOpts())
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Equal(a, b) {
		t.Fatal("EXPANDED-CHILD-WIDTH silently ignored: identical generated bytes")
	}
}

func TestCoordinatorExpandedPaddingNotIgnored(t *testing.T) {
	if _, err := Generate(verified(t, `<Row><Expanded Padding="8"><Text Value="x"/></Expanded></Row>`), defaultOpts()); err == nil {
		t.Fatal("EXPANDED-PADDING silently ignored: must be explicitly rejected (F-B2)")
	}
}

func TestCoordinatorExpandedGridNotSilent(t *testing.T) {
	if _, err := Generate(verified(t, `<Grid Columns="*"><Expanded><Text Value="x"/></Expanded></Grid>`), defaultOpts()); err == nil {
		t.Fatal("EXPANDED-GRID silently accepted although documented undecided/unsupported")
	}
}
