// ============================================================================
// TASK-CODEGEN-NAMING-001 切片 C2：同包多源端到端编译回归
//
// 为什么单独建这个文件（验收阻塞项）：
//
//	TestGeneratedCompiles 只编译**单个**生成文件；
//	TestBindingGeneratedCompiles 也只编译单个（含绑定）生成文件。
//	两者都不能独立证明「两个不同 .gxml 生成的完整产物放进同一 Go 包后可以一起编译」——
//	而这恰恰是 C2 修复的缺陷：C2 之前 renderKey/textCache 是固定名，
//	同包两个源会重复声明，CLI 却报「生成成功」，直到 go build 才炸。
//
// 本文件把「同包多源」从纸面推导升级为可执行判据：
// 生成两份完整产物 → 写入同一临时包 → 真实 `go build`。
//
// 组合覆盖（用户点名要求「静态页与含绑定页的混合组合」）：
//  1. 静态 + 静态：只有 renderKey 类型，验证两类产物共存的基线；
//  2. 静态 + 含绑定：一侧无 textCache、一侧有，验证保守上界不影响编译；
//  3. 含绑定 + 含绑定：两侧都声明各自的 textCache，是最强的重复声明面。
// ============================================================================

// dualSource 描述一个待生成的 .gxml 输入。
type dualSource struct {
	// fileName 是写入同一包目录下的产物文件名（仅本测试内部使用）。
	fileName string
	// sourcePath 是符号派生的唯一依据（卡 §5.1）：禁止随机/时间/序号参与。
	sourcePath string
	// body 是 <Page> 内容。
	body string
	// opts 是生成选项；含绑定页必须带 ModulePath（ViewModel 跨包）。
	opts Options
}

// staticSource 造一个静态页输入。
func staticSource(fileName, sourcePath, text string) dualSource {
	return dualSource{
		fileName:   fileName,
		sourcePath: sourcePath,
		body:       `<Text Value="` + text + `"/>`,
		opts:       Options{PackageName: "demo", SourcePath: sourcePath},
	}
}

// bindingSource 造一个含绑定页输入。
//
// 绑定页的 ViewModel 在 internal/compiler/analyzer/testdata/fixture，
// 跨包引用需要 ModulePath，故沿用 bindingOpts() 的设置。
func bindingSource(fileName, sourcePath string) dualSource {
	return dualSource{
		fileName:   fileName,
		sourcePath: sourcePath,
		// 静态节点 + 绑定节点混排：这类页面既走整页缓存又带绑定槽位。
		body: `<Column><Text Value="Static"/><Text Value="{Title}"/></Column>`,
		opts: Options{
			PackageName: "demo",
			ModulePath:  "github.com/goxml/goxml",
			SourcePath:  sourcePath,
		},
	}
}

// buildTwoSourcesTogether 生成两个源到**同一个**临时包，真实 go build 并返回两份源码。
//
// **必须**在仓库内建包，不能建独立模块——原因已实测（见
// binding_compile_test.go 的顶部注释）：Go 的 internal 规则禁止外部模块
// import github.com/goxml/goxml/internal/...，而本包测试用的 ViewModel
// 恰在 internal/compiler/analyzer/testdata/fixture。
//
// 目录建在 testdata/ 之下：Go 工具链不枚举 testdata，
// 不会像 binding_runtime_test.go 那样被运行期 `./...` 撞上。
func buildTwoSourcesTogether(t *testing.T, a, b dualSource) (string, string) {
	t.Helper()

	srcA := string(mustGen(t, a.body, a.opts))
	srcB := string(mustGen(t, b.body, b.opts))

	// 两份产物必须声明同一包名，否则「同包」前提不成立。
	// 不能判前缀——产物开头是三行保护头（契约 §3.1）。
	for _, s := range []string{srcA, srcB} {
		if !strings.HasPrefix(s, "// Code generated by goxml. DO NOT EDIT.\n") {
			t.Fatalf("产物缺少保护头:\n%s", headOf(s, 4))
		}
		if !strings.Contains(s, "\npackage demo\n") {
			t.Fatalf("产物 package 子句不是 demo:\n%s", headOf(s, 8))
		}
	}

	repoRoot := repoRootOf(t)
	dir := filepath.Join(repoRoot, "internal", "compiler", "codegen",
		"testdata", fmt.Sprintf("tmpdual%d%d", os.Getpid(), time.Now().UnixNano()))
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(dir)

	for _, w := range []struct{ name, src string }{
		{a.fileName, srcA},
		{b.fileName, srcB},
	} {
		if err := os.WriteFile(filepath.Join(dir, w.name), []byte(w.src), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	rel, err := filepath.Rel(repoRoot, dir)
	if err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("go", "build", "./"+filepath.ToSlash(rel)+"/...")
	cmd.Dir = repoRoot
	cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOPROXY=off")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("同包两份产物无法一起编译（这正是 C2 修复的缺陷）:\n%s\n--- %s ---\n%s\n--- %s ---\n%s",
			out, a.sourcePath, srcA, b.sourcePath, srcB)
	}

	t.Logf("同包编译通过：%s + %s（%d + %d 字节产物）",
		a.sourcePath, b.sourcePath, len(srcA), len(srcB))
	return srcA, srcB
}

// assertSymbolsOfSource 断言产物声明了本源派生的符号，且**没有**另一源的符号。
//
// 交叉断言的意义：防止「两份产物看似都能编译，实际其中一份借用了另一份的符号名」。
func assertSymbolsOfSource(t *testing.T, src, sourcePath, otherSourcePath string) {
	t.Helper()

	suffix, err := sourceSymbolSuffix(sourcePath)
	if err != nil {
		t.Fatalf("派生后缀失败: %v", err)
	}
	otherSuffix, err := sourceSymbolSuffix(otherSourcePath)
	if err != nil {
		t.Fatalf("派生后缀失败: %v", err)
	}

	for _, want := range []string{
		"Goxml" + suffix + "View",
		"NewGoxml" + suffix + "View",
		"goxmlRenderKey" + suffix,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("%s 的产物应声明 %q:\n%s", sourcePath, want, headOf(src, 40))
		}
	}
	for _, bad := range []string{
		"Goxml" + otherSuffix + "View",
		"goxmlRenderKey" + otherSuffix,
		"goxmlTextCache" + otherSuffix,
	} {
		if strings.Contains(src, bad) {
			t.Errorf("%s 的产物不应出现另一源 %s 的符号 %q:\n%s",
				sourcePath, otherSourcePath, bad, headOf(src, 40))
		}
	}
}

// headOf 取前 n 行并标注截断，避免失败信息刷屏。
//
// 与 codegen_test.go 的 firstLines 区别：这里会显式标出「已截断」，
// 防止读日志的人把截断后的产物误当成完整产物。
func headOf(s string, n int) string {
	lines := strings.Split(s, "\n")
	if len(lines) > n {
		return strings.Join(lines[:n], "\n") + "\n...（截断）"
	}
	return s
}

// TestTwoStaticSourcesSamePackage 两个静态页同包：产物各自唯一且能一起编译。
func TestTwoStaticSourcesSamePackage(t *testing.T) {
	a := staticSource("gen_home.go", "home.gxml", "Hello Home")
	b := staticSource("gen_detail.go", "detail.gxml", "Hello Detail")

	srcA, srcB := buildTwoSourcesTogether(t, a, b)

	assertSymbolsOfSource(t, srcA, a.sourcePath, b.sourcePath)
	assertSymbolsOfSource(t, srcB, b.sourcePath, a.sourcePath)

	// 静态页不声明绑定槽位缓存类型（usesVM 为假），因此这里不断言 textCache。
	for name, src := range map[string]string{a.sourcePath: srcA, b.sourcePath: srcB} {
		if strings.Contains(src, "goxmlTextCache") {
			t.Errorf("%s 是静态页，不应声明绑定槽位缓存类型:\n%s", name, headOf(src, 40))
		}
	}
}

// TestStaticAndBindingSourcesSamePackage 静态页 + 含绑定页同包（用户点名的混合组合）。
//
// 这个组合的价值：两侧的**符号集合不同**（一侧有 textCache、一侧没有），
// 能验证「按源唯一」在两类产物上的派生是一致的，而不是只在单一产物形态下成立。
func TestStaticAndBindingSourcesSamePackage(t *testing.T) {
	a := staticSource("gen_home.go", "home.gxml", "Hello Home")
	b := bindingSource("gen_detail.go", "detail.gxml")

	srcA, srcB := buildTwoSourcesTogether(t, a, b)

	assertSymbolsOfSource(t, srcA, a.sourcePath, b.sourcePath)
	assertSymbolsOfSource(t, srcB, b.sourcePath, a.sourcePath)

	// 含绑定页声明自己的槽位缓存类型；静态页不声明。
	if !strings.Contains(srcB, "goxmlTextCacheDetail") {
		t.Errorf("%s 是含绑定页，应声明 goxmlTextCacheDetail:\n%s", b.sourcePath, headOf(srcB, 40))
	}
	if strings.Contains(srcA, "goxmlTextCache") {
		t.Errorf("%s 是静态页，不应声明绑定槽位缓存类型:\n%s", a.sourcePath, headOf(srcA, 40))
	}
}

// TestTwoBindingSourcesSamePackage 两个含绑定页同包：两侧都声明各自的 textCache。
//
// 这是最强的重复声明面：C2 之前的固定名 textCache 在这一组合下必然 redeclared。
func TestTwoBindingSourcesSamePackage(t *testing.T) {
	a := bindingSource("gen_home.go", "home.gxml")
	b := bindingSource("gen_detail.go", "detail.gxml")

	srcA, srcB := buildTwoSourcesTogether(t, a, b)

	assertSymbolsOfSource(t, srcA, a.sourcePath, b.sourcePath)
	assertSymbolsOfSource(t, srcB, b.sourcePath, a.sourcePath)

	for name, src := range map[string]string{
		"goxmlTextCacheHome":   srcA,
		"goxmlTextCacheDetail": srcB,
	} {
		if !strings.Contains(src, name) {
			t.Errorf("含绑定页产物应声明 %q", name)
		}
	}
}

// TestSamePackageTwoSourcesUseDistinctTypeNames 不启动子进程的类型名唯一性判据。
//
// 上面的编译测试是最强证据但较慢；这里给出同一事实的快速判据：
// 两个不同源派生的**包级类型名**必须两两不同（C2 的核心不变量）。
func TestSamePackageTwoSourcesUseDistinctTypeNames(t *testing.T) {
	paths := []string{"home.gxml", "detail.gxml", "sub/home.gxml", "ui/detail.gxml", "settings_page.gxml"}

	seen := map[string]string{}
	for _, p := range paths {
		keyType, cacheType, err := generatedTypeNames(p)
		if err != nil {
			t.Fatalf("generatedTypeNames(%q): %v", p, err)
		}
		for _, sym := range []string{keyType, cacheType} {
			if prev, dup := seen[sym]; dup {
				t.Errorf("源 %q 与 %q 派生出同一包级类型名 %q（同包会重复声明）", prev, p, sym)
				continue
			}
			seen[sym] = p
		}
	}
}
