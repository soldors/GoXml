// ============================================================================
// F-06 回归（TASK-CODEGEN-NAMING-001 卡 §10.4.3 的 C4-PRE-1）
//
// 缺陷：`isOwnArtifact` 用**裸** SourcePath 去比保护头里的 `// Source:`，
// 而保护头是 headerFor 写的、走 normalizeSourcePath（统一 `/`）。
// 调用方一旦给平台原生分隔符（Windows 的 `\`），自己的上一版产物就
// **不再被排除**，于是被当成他人声明 → 误报冲突。
//
// 为什么现在修：C4 会把预检接到 CLI 失败路径上。接线之后，一次误报
// 就等于「合法工程再也生成不了」，代价远高于此前（此前预检无人调用）。
//
// 变红方式（已实测，见 dev-log `2026-10-22.md` §5.1）：
//   - 把 isOwnArtifact 里的 normalizeSourcePath 去掉 → 本文件两个用例红。
// ============================================================================

// ownArtifactSource 里写进保护头的 Source 值：归一化形态（统一 `/`）。
// 与 headerFor 的输出形态一致——它是产物真实拥有的形态。
const ownArtifactSource = "ui/dashboard.gxml"

// ownArtifactCallerSource 是调用方传入的 SourcePath：平台原生分隔符。
//
// 在 Linux 上 `\` 只是普通字符，在 Windows 上是分隔符；两种平台上它与
// ownArtifactSource 都是**同一个**源的不同书写形态，归一化后必须相等。
const ownArtifactCallerSource = `ui\dashboard.gxml`

// writeOwnArtifact 写一份「本源的上一版产物」到 dir/name。
//
// 内容声明 callerSource 将发出的**全部**包级符号（由 generatedPackageSymbols
// 派生，不写死字面量），因此只要排除逻辑失效，就一定会被判为冲突。
func writeOwnArtifact(t *testing.T, dir, name, headerSource, callerSource string) string {
	t.Helper()
	syms, err := generatedPackageSymbols(callerSource)
	if err != nil {
		t.Fatalf("generatedPackageSymbols(%q): %v", callerSource, err)
	}
	var b strings.Builder
	b.WriteString("// Code generated by goxml. DO NOT EDIT.\n")
	b.WriteString("// Source: " + headerSource + "\n")
	b.WriteString("// Goxml-Version: " + goxmlVersion + "\n\n")
	b.WriteString("package demo\n\n")
	for _, s := range syms {
		// New<View> 是构造函数，其余是类型；声明形态不影响 packageLevelNames
		// 的收录，但照真实产物写能让这份夹具在将来被复用时不误导。
		if strings.HasPrefix(s, "New") {
			fmt.Fprintf(&b, "func %s() {}\n", s)
			continue
		}
		fmt.Fprintf(&b, "type %s struct{}\n", s)
	}
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

// ownArtifactTargets 构造一个 target，其 OutputPath **故意**指向别的文件。
//
// 目的：封死「靠路径相等被排除」这条退路——本用例只可能被保护头比对救下。
func ownArtifactTargets(dir, callerSource string) []NamingTarget {
	return []NamingTarget{{
		SourceAbs:  filepath.Join(dir, "dashboard.gxml"),
		SourcePath: callerSource,
		TargetDir:  dir,
		OutputPath: filepath.Join(dir, "dashboard_gen.go"),
	}}
}

// TestNamingOwnArtifactUsesNormalizedSourcePath：自己上一版产物的保护头
// 是归一化形态，调用方给原生分隔符时仍必须认出是自己的。
func TestNamingOwnArtifactUsesNormalizedSourcePath(t *testing.T) {
	dir := t.TempDir()
	writeOwnArtifact(t, dir, "old_dashboard_gen.go", ownArtifactSource, ownArtifactCallerSource)

	conflicts, err := detectNamingConflicts(ownArtifactTargets(dir, ownArtifactCallerSource))
	if err != nil {
		t.Fatalf("预检报错: %v", err)
	}
	if len(conflicts) != 0 {
		t.Fatalf("自家产物（归一化路径）不应算冲突；实际=%v", symbolsOf(conflicts))
	}
}

// TestNamingOwnArtifactMismatchStillConflicts：反向对照——产物内容依然是
// 本源将发出的符号，但保护头的 Source 指向**别的**源，冲突必须照报。
//
// 没有这条，上一条可能因为「符号根本没被解析到」而假绿：这里证明同一份
// 符号声明确实会进入 existing 集合，上一条的"无冲突"只能来自排除逻辑。
func TestNamingOwnArtifactMismatchStillConflicts(t *testing.T) {
	dir := t.TempDir()
	// 头写 other.gxml（与本批源无关），内容按本源派生 → 只能是"他人声明"。
	writeOwnArtifact(t, dir, "foreign_gen.go", "other.gxml", ownArtifactCallerSource)

	targets := ownArtifactTargets(dir, ownArtifactCallerSource)
	conflicts, err := detectNamingConflicts(targets)
	if err != nil {
		t.Fatalf("预检报错: %v", err)
	}
	// 只要求「报出了冲突且报的是 existing」：具体撞哪个符号由派生规则决定，
	// 写死符号名会让本用例在命名规则演进时假红。
	sawExisting := false
	for _, c := range conflicts {
		if c.Kind == namingConflictExisting {
			sawExisting = true
		}
	}
	if !sawExisting {
		t.Fatalf("他人产物应报 existing 冲突；实际=%v", symbolsOf(conflicts))
	}
}

// TestNamingOwnArtifactDiagnosticCodesF06：F-06 修复后，自家产物场景
// 经 CheckNamingConflicts 也不得产出任何诊断（C4 接线走的是这条入口）。
func TestNamingOwnArtifactDiagnosticCodesF06(t *testing.T) {
	dir := t.TempDir()
	writeOwnArtifact(t, dir, "old_dashboard_gen.go", ownArtifactSource, ownArtifactCallerSource)

	diags, err := CheckNamingConflicts(ownArtifactTargets(dir, ownArtifactCallerSource))
	if err != nil {
		t.Fatalf("预检报错: %v", err)
	}
	if len(diags) != 0 {
		msgs := make([]string, 0, len(diags))
		for _, d := range diags {
			msgs = append(msgs, d.Code+": "+d.Message)
		}
		t.Fatalf("自家产物不应产出诊断；实际=%v", msgs)
	}
}
