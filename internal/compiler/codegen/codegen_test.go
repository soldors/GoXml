const vmPath = "internal/compiler/analyzer/testdata/fixture.ViewModel"

// gen 走完整前端 + 分析 + 生成。
func gen(t *testing.T, body string, opts Options) ([]byte, error) {
	t.Helper()
	v := verified(t, body)
	return Generate(v, opts)
}

// mustGen 要求生成成功。
func mustGen(t *testing.T, body string, opts Options) []byte {
	t.Helper()
	out, err := gen(t, body, opts)
	if err != nil {
		t.Fatalf("生成失败: %v", err)
	}
	return out
}

// defaultOpts 是测试用的默认选项。
func defaultOpts() Options {
	return Options{PackageName: "demo", SourcePath: "dashboard.gxml"}
}

// verified 跑 Parser → Expander → Analyzer 并取得凭证。
func verified(t *testing.T, body string) *analyzer.VerifiedDoc {
	t.Helper()
	src := `<Goxml Version="1" ViewModel="` + vmPath + `">
  <Page Route="/">` + body + `</Page>
</Goxml>`

	p := runFrontend(t, src)
	r := analyzer.Analyze("case.gxml", p.doc, p.schemas, p.env)
	if r.Status != analyzer.StatusOK {
		t.Fatalf("Analyzer 未通过: %v", codes(r))
	}
	v, err := r.Verified()
	if err != nil {
		t.Fatalf("取凭证失败: %v", err)
	}
	return v
}

// verifiedErr 与 verified 相同，但 Analyzer 失败时返回错误而非 t.Fatal。
//
// 用途：测试「非法输入必须被 Analyzer 拒绝」这类负向用例。
func verifiedErr(t *testing.T, body string) (*analyzer.VerifiedDoc, error) {
	t.Helper()
	src := `<Goxml Version="1" ViewModel="` + vmPath + `">
  <Page Route="/">` + body + `</Page>
</Goxml>`

	p := runFrontend(t, src)
	r := analyzer.Analyze("case.gxml", p.doc, p.schemas, p.env)
	if r.Status != analyzer.StatusOK {
		return nil, fmt.Errorf("analyzer status=%s diags=%v", r.Status, codes(r))
	}
	return r.Verified()
}

// codes 汇总诊断码，便于失败信息。
func codes(r *analyzer.Result) []string {
	var out []string
	for _, d := range r.Diags {
		out = append(out, d.Code)
	}
	return out
}

// frontend 是一次前端的产物。
type frontend struct {
	doc     *contracts.DocumentIR
	schemas expander.SchemaRegistry
	env     *analyzer.TypeEnv
}

// runFrontend 跑 Parser → Expander。
func runFrontend(t *testing.T, src string) frontend {
	t.Helper()

	root := repoRootOf(t)
	env, err := analyzer.NewTypeEnv(analyzer.Config{
		ModuleRoot: root,
		SourceDir:  filepath.Join(root, "internal", "compiler", "codegen"),
	})
	if err != nil {
		t.Fatalf("创建 TypeEnv: %v", err)
	}

	doc, pdiags := gxmlparser.Parse("case.gxml", []byte(src))
	if len(pdiags) > 0 {
		t.Fatalf("Parser: %s", pdiags[0].Error())
	}
	er := expander.Expand("case.gxml", doc)
	if len(er.Diags) > 0 {
		t.Fatalf("Expander: %s", er.Diags[0].Error())
	}
	return frontend{doc: er.Doc, schemas: er.Schemas, env: env}
}

