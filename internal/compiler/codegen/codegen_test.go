func TestImportsAllUsed(t *testing.T) {
	// 生成文件里的每个 import 都必须被引用，否则 go build 会失败。
	out := mustGen(t, `<Text Value="x"/>`, defaultOpts())
	f := parseGo(t, out)

	used := map[string]bool{}
	ast.Inspect(f, func(n ast.Node) bool {
		sel, ok := n.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		if id, ok := sel.X.(*ast.Ident); ok {
			used[id.Name] = true
		}
		return true
	})

	for _, imp := range f.Imports {
		name := "material"
		if imp.Name != nil {
			name = imp.Name.Name
		} else if strings.Contains(imp.Path.Value, "layout") {
			name = "layout"
		} else if strings.Contains(imp.Path.Value, "material") {
			name = "material"
		}
		if !used[name] {
			t.Errorf("import %s (%s) 未被使用", imp.Path.Value, name)
		}
	}
}

