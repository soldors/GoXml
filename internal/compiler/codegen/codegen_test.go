// buildInTempModule 在临时模块中编译生成的源码。
//
// 临时模块复用仓库的 go.sum 与 Gio 版本，因此离线也能构建。
func buildInTempModule(t *testing.T, src []byte) {
	t.Helper()

	repoRoot := repoRootOf(t)

	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "gen.go"), src, 0o644); err != nil {
		t.Fatal(err)
	}

	gomod := "module gotest\n\ngo 1.26.0\n\nrequire gioui.org v0.10.3\n"
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(gomod), 0o644); err != nil {
		t.Fatal(err)
	}
	// 复制 go.sum：其中已含 gioui 及其传递依赖的校验和，避免联网。
	sum, err := os.ReadFile(filepath.Join(repoRoot, "go.sum"))
	if err != nil {
		t.Fatalf("读取 go.sum: %v", err)
	}
	if err := os.WriteFile(filepath.Join(dir, "go.sum"), sum, 0o644); err != nil {
		t.Fatal(err)
	}

	cmd := exec.Command("go", "build", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(),
		"CGO_ENABLED=0",
		"GOFLAGS=-mod=mod",
		"GOPROXY=off", // 只用本地缓存，测试不依赖网络
	)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("生成代码编译失败: %v\n%s\n--- 生成的源码 ---\n%s", err, out, src)
	}
}

// repoRootOf 从测试工作目录向上定位模块根。
func repoRootOf(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatal("未找到 go.mod")
		}
		dir = parent
	}
}

// parseGo 解析生成源码。
func parseGo(t *testing.T, src []byte) *ast.File {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "gen.go", src, parser.ParseComments)
	if err != nil {
		t.Fatalf("解析生成源码失败: %v\n%s", err, src)
	}
	return f
}

// firstLines 返回前 n 行，便于错误信息。
func firstLines(s string, n int) string {
	lines := strings.Split(s, "\n")
	if len(lines) > n {
		lines = lines[:n]
	}
	return strings.Join(lines, "\n")
}

