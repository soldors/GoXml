package codegen

import (
	"strings"
	"testing"
)

// ============================================================================
// G1：保护头与契约 §3.1 逐字节一致（TASK-GENERATE-CLI-001 前置必修）
//
// --clean 的所有权判定依赖「仍带保护头」；头若与契约不一致，
// 清理就失去判定依据。判定与生成必须使用同一规范。
// ============================================================================

const wantHeader = "// Code generated by goxml. DO NOT EDIT.\n" +
	"// Source: dashboard.gxml\n" +
	"// Goxml-Version: 1\n"

// TestHeaderMatchesContract 生成的保护头与契约 §3.1 逐字节一致
// （行顺序、标点、换行、版本字段格式）。
func TestHeaderMatchesContract(t *testing.T) {
	v := verified(t, `<Text Value="x"/>`)
	out, err := Generate(v, bindingOpts())
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(out), wantHeader) {
		t.Errorf("保护头与契约 §3.1 不一致。\n期望前缀:\n%s\n实际开头:\n%.120s", wantHeader, out)
	}
	// 首行必须被 Go 工具链识别为生成文件（^// Code generated .* DO NOT EDIT\.$）。
	first := strings.SplitN(string(out), "\n", 2)[0]
	if !strings.HasPrefix(first, "// Code generated ") || !strings.HasSuffix(first, " DO NOT EDIT.") {
		t.Errorf("首行不符合 Go 生成文件识别规则: %q", first)
	}
}

// TestHeaderPathNormalization Source 路径统一 `/` 分隔（契约 §3.1）。
//
// Windows 下若 SourcePath 带反斜杠，两次生成的头必须相同——
// 否则同一输入在不同平台产生不同输出（违反契约 §6 确定性）。
func TestHeaderPathNormalization(t *testing.T) {
	if normalizeSourcePath("ui\\dashboard.gxml") != "ui/dashboard.gxml" {
		t.Errorf("反斜杠应规范化为 /: %q", normalizeSourcePath("ui\\dashboard.gxml"))
	}
}

// TestHasProtectedHeader 清理判定与生成同规范（契约 §10）。
func TestHasProtectedHeader(t *testing.T) {
	cases := []struct {
		name string
		src  string
		want bool
	}{
		{"标准三行", wantHeader + "package x\n", true},
		{"缺第三行", "// Code generated by goxml. DO NOT EDIT.\n// Source: a.gxml\n", false},
		{"版本不符", "// Code generated by goxml. DO NOT EDIT.\n// Source: a.gxml\n// Goxml-Version: 2\n", false},
		{"工具名不符", "// Code generated by other. DO NOT EDIT.\n// Source: a.gxml\n// Goxml-Version: 1\n", false},
		{"Source 缺失", "// Code generated by goxml. DO NOT EDIT.\n// Goxml-Version: 1\n", false},
		{"用户文件", "package main\n\nfunc main() {}\n", false},
		{"空输入", "", false},
		{"只有一行", "// Code generated by goxml. DO NOT EDIT.\n", false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := HasProtectedHeader([]byte(c.src)); got != c.want {
				t.Errorf("HasProtectedHeader = %v, 期望 %v", got, c.want)
			}
		})
	}
}

// TestHasProtectedHeaderAcceptsOwnOutput 生成产物必须被判定为受管理文件。
func TestHasProtectedHeaderAcceptsOwnOutput(t *testing.T) {
	v := verified(t, `<Text Value="x"/>`)
	out, err := Generate(v, bindingOpts())
	if err != nil {
		t.Fatal(err)
	}
	if !HasProtectedHeader(out) {
		t.Error("本工具生成的文件必须被 HasProtectedHeader 识别（--clean 的前提）")
	}
}
