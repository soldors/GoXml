// Package codegen 把 Analyzer 验证过的语义 IR 生成为 Go 源码。
//
// 职责边界（契约 §2.1–§2.3、§4.4）：
//   - 入口只接受 *analyzer.VerifiedDoc，未验证的 IR 在类型层面传不进来；
//   - 只返回 []byte，**不写文件**——写入与原子替换由编排层负责；
//   - 只消费已验证的事实，不重新推导布局语义、不重新判断兼容性。
//
// 当前实现范围：静态 Page/Text 整页固化、Column/Row/Page 布局、`<Spacer>` 占位、
// `<Grid>` 网格（列定义、行优先换行、补位单元格、Gap 双轴）、
// `<Text>`/`<Button>` 的绑定读取与 Click 事件、`<Input>` 受控输入、
// `<Image>` 静态资产（//go:embed）、`<If>`/`<For>` 内联展开，
// 以及 `Width`/`Height`/`Align`/`Justify`/`Gap` 的映射。
// `<Expanded>` 尚未实现，见输出契约 §4.6。
package codegen

import (
	"fmt"
	"go/format"
	"go/token"
	"go/types"
	"path/filepath"
	"sort"
	"strings"

	"github.com/goxml/goxml/contracts"
	"github.com/goxml/goxml/internal/compiler/analyzer"
)

// Options 是生成所需的全部外部输入。
//
// Codegen 不读磁盘、不加载包：包名与源路径由编排层确定后传入（契约 §4.4）。
type Options struct {
	// PackageName 是生成文件的 package 子句。
	//
	// 由调用方按契约 §4.1 从目标目录的 Go package 解析得到。
	// Codegen 不推导、不猜测；为空时生成失败。
	PackageName string
	// ModulePath 是 go.mod 的 module 路径。
	//
	// 仅当 ViewModel 位于**其他包**时需要：用于拼出该包的 import 路径。
	// 同包 ViewModel（或纯静态页面）不需要设置。
	ModulePath string

	// SourcePath 是 .gxml 相对目标包目录的路径（如 "ui/dashboard.gxml"），
	// 用于按契约 §4.2 推导符号名。
	SourcePath string

	// ViewModelPackageDir 是 ViewModel 实际所在包相对模块根的目录（`/` 分隔；
	// 空串表示「与源 .gxml 同包」，即 analyzer.ViewModelRef.PkgDir 的同包语义）。
	// 仅当 ViewModel 存在（动态页）时有意义。
	//
	// 用途（R4-A 片2）：`--out-dir` 把产物搬到与源不同的包时，「与 GXML 同包」的
	// ViewModel 已**不在产物包**。Codegen 需知 VM 真实包目录以判断是否需要 import。
	// 由调用方（内部 pipeline）从源目录 rel 填入；Codegen 自己**不读盘、不加载包**。
	ViewModelPackageDir string
	// OutputPackageDir 是产物所在包相对模块根的目录（`/` 分隔；空串表示「与源同目录」）。
	// 当它 != ViewModelPackageDir 时，同包 ViewModel 必须跨包 import。
	OutputPackageDir string

	// ViewModelPackageName is the source package name for same-package callers
	// that lack a package name in the verified ViewModel reference.
	ViewModelPackageName string
	// PackageNames contains declarations in the output package reserved by precheck.
	PackageNames map[string]string
}

// GoxmlVersion 是保护头与 Manifest 共用的语言版本字段（契约 §3.1）。
//
// 它是 GXML 语言版本，不是编译器构建版本——同一语言版本的不同构建
// 必须产生逐字节相同的保护头（契约 §6 确定性）。
// G3 决策：版本来源显式单一，Manifest 与保护头从这里取值。
const GoxmlVersion = "1"

// goxmlVersion 是包内引用别名。
const goxmlVersion = GoxmlVersion

// headerFor 生成文件的保护头（契约 §3.1，三行格式）：
//
//	// Code generated by goxml. DO NOT EDIT.
//	// Source: ui/dashboard.gxml
//	// Goxml-Version: 1
//
// Source 使用项目相对路径，统一 `/` 分隔；禁止绝对路径、机器名与时间戳。
// 首行必须匹配 Go 工具链的 `^// Code generated .* DO NOT EDIT\.$`。
func headerFor(sourcePath string) string {
	return "// Code generated by goxml. DO NOT EDIT.\n" +
		"// Source: " + normalizeSourcePath(sourcePath) + "\n" +
		"// Goxml-Version: " + goxmlVersion + "\n\n"
}

// normalizeSourcePath 把 Source 路径规范为契约 §3.1 要求的形态：
// 统一 `/` 分隔。路径的相对性与边界由调用方（Pipeline/CLI）保证；
// 这里只做展示形态的规范化，避免同一输入因平台分隔符差异而输出不同。
func normalizeSourcePath(p string) string {
	return strings.ReplaceAll(p, "\\", "/")
}

// HasProtectedHeader 报告一段源码是否带**本工具**的保护头。
//
// 用途：`--clean` 的所有权判定（契约 §10）——只删除「Manifest 登记
// 且仍带保护头」的文件。判定与 headerFor 使用**同一规范**：
// 逐字节比较三行，不做宽松子串匹配。
//
// 判定规则：
//   - 第 1 行逐字节等于 `// Code generated by goxml. DO NOT EDIT.`
//   - 第 2 行以 `// Source: ` 开头（路径内容不作校验——所有权由
//     Manifest 登记 + 本头共同证明，路径本身不参与判定）
//   - 第 3 行逐字节等于 `// Goxml-Version: 1`
func HasProtectedHeader(src []byte) bool {
	lines := strings.Split(string(src), "\n")
	if len(lines) < 3 {
		return false
	}
	if lines[0] != "// Code generated by goxml. DO NOT EDIT." {
		return false
	}
	if !strings.HasPrefix(lines[1], "// Source: ") {
		return false
	}
	return lines[2] == "// Goxml-Version: "+goxmlVersion
}

// Generate 生成单个 Go 源文件。
//
// 成功返回已格式化的源码；失败返回 error 且**不返回部分代码**——
// 部分产物可能被调用方误写出去，破坏「失败不覆盖旧文件」的保证（契约 §2.3）。
func Generate(v *analyzer.VerifiedDoc, opts Options) ([]byte, error) {
	out, _, err := generateWithSlots(v, opts)
	return out, err
}

// generateWithSlots 与 Generate 完全相同，额外返回本次发射**实际累加**的
// 显示缓存槽位数。
//
// 存在理由（C5 独立复审 P1-1）：CountBindSlots 是另一套遍历，必须能与发射侧
// 的累加值**逐例相等**。只用「产物是否声明 goxmlTextCache」只能证明零/非零
// 一致，证明不了总数相等——两个绑定被漏算成零会红，但 3 个算成 2 个不会红。
// 把累加值暴露给同包测试，才能把「统计槽位数」这个函数名兑现。
//
// 不导出：生产代码没有第二个调用方，导出面越小越好。
func generateWithSlots(v *analyzer.VerifiedDoc, opts Options) ([]byte, int, error) {
	if v == nil {
		return nil, 0, fmt.Errorf("codegen: nil VerifiedDoc")
	}
	if v.Document() == nil {
		return nil, 0, fmt.Errorf("codegen: VerifiedDoc has no document")
	}
	if opts.PackageName == "" {
		return nil, 0, fmt.Errorf("codegen: Options.PackageName is required; it is not derived from the source path")
	}
	if !isGoIdent(opts.PackageName) {
		return nil, 0, fmt.Errorf("codegen: PackageName %q is not a valid Go identifier", opts.PackageName)
	}
	if opts.SourcePath == "" {
		return nil, 0, fmt.Errorf("codegen: Options.SourcePath is required to derive the view symbol")
	}

	view, err := viewSymbol(opts.SourcePath)
	if err != nil {
		return nil, 0, err
	}
	// 包级生成类型必须**按源文件唯一**（TASK-CODEGEN-NAMING-001 卡 §5.1 的 D-2 裁决）：
	// 同包多 .gxml 时固定名会重复声明（实测 renderKey/textCache redeclared）。
	keyType, cacheType, err := generatedTypeNames(opts.SourcePath)
	if err != nil {
		return nil, 0, err
	}
	assetVar, err := assetSymbol(opts.SourcePath)
	if err != nil {
		return nil, 0, err
	}

	vmRef, _ := v.ViewModel()

	// R14-B：目标包已有包级符号（命名预检事实）+ 本文件将声明的包级名，
	// 都是导入名（文件块）不得触碰的名字——同名标识符不能同时出现在
	// 文件块与包块（Go 规范），用户合法声明 `layout`/`material`/`op` 时
	// 固定限定符会让生成文件编译失败。
	taken := make(map[string]bool, len(opts.PackageNames)+4)
	for n := range opts.PackageNames {
		taken[n] = true
	}
	taken[view] = true
	taken["New"+view] = true
	taken[keyType] = true
	taken[cacheType] = true

	g := &generator{
		opts:       opts,
		view:       view,
		keyType:    keyType,
		cacheType:  cacheType,
		assetVar:   assetVar,
		assetSlots: make(map[string]int),
		imports:    newImportSetWithTaken(taken),
		facts:      v.Facts(),
		vmRef:      vmRef,
	}

	// 页面是生成的主体。没有 Page 时不应走到这里——Parser 保证存在，
	// 但 VerifiedDoc 不变量若被破坏，这里必须明确失败而不是产出空文件。
	page := v.Document().Page
	if page == nil {
		return nil, 0, fmt.Errorf("codegen: document has no <Page>; nothing to generate")
	}
	reserveLoopNames(page, g.facts, taken)

	body, err := g.page(page)
	if err != nil {
		return nil, 0, err
	}

	src, err := g.assemble(body)
	if err != nil {
		return nil, 0, err
	}
	out, err := format.Source([]byte(src))
	if err != nil {
		// 格式化失败说明生成器有缺陷。返回错误并附上原文，便于定位，
		// 但绝不把未格式化的源码当作成功结果返回。
		return nil, 0, fmt.Errorf("codegen: generated source does not parse: %w\n--- source ---\n%s", err, src)
	}
	// g.bindSlots 是发射过程中**实际累加**的值（分配序号时 ++），
	// 不是重新数一遍——这正是 CountBindSlots 要对齐的基准。
	return out, g.bindSlots, nil
}

// A range variable is in scope when child qualifiers are emitted. Reserve
// these names before registering any import, including numeric alias variants.
func reserveLoopNames(n *contracts.NodeIR, facts *analyzer.Facts, taken map[string]bool) {
	if n == nil {
		return
	}
	if loop, ok := lookupFor(n, facts); ok {
		taken[loop.Each] = true
		if loop.Index != "" {
			taken[loop.Index] = true
		}
	}
	for _, child := range n.Children {
		reserveLoopNames(child, facts, taken)
	}
	if n.If != nil {
		for _, branch := range [][]*contracts.NodeIR{n.If.Then, n.If.Else} {
			for _, child := range branch {
				reserveLoopNames(child, facts, taken)
			}
		}
	}
}

// generator 是单次生成的状态。
type generator struct {
	opts Options
	view string
	// keyType / cacheType 是**按源文件唯一**的包级生成类型名（TASK-CODEGEN-NAMING-001 卡 §5.1）。
	// 固定名 renderKey/textCache 会在同包多文件时重复声明。
	keyType   string
	cacheType string
	// assetVar 是本文件 embed.FS 变量名（goxmlAssets<Source>）；无资产时为空。
	assetVar string
	// assets 是按首次出现顺序记录的静态 Image 资产（已归一化路径）。
	assets []string
	// assetSlots 把资产路径映射到 img<n> 字段序号，重复 Src 共用一次解码。
	assetSlots map[string]int
	imports    *importSet
	// facts 是 Analyzer 已验证的语义事实。绑定路径与目标类型都取自此处，
	// Codegen **不得**自行解析绑定路径。
	facts *analyzer.Facts
	// usesVM 表示页面**动态**（含绑定或事件）：需要 vm 参数，且**不得**整页静态固化。
	usesVM bool
	// opsName 是顶层容器布局所用的 Ops 变量名。
	//
	// 静态页面为 "rec"（录制到 cacheOps）；含绑定页面为 "gtx"（直接布局到帧）。
	opsName string
	// vmRef 是 ViewModel 类型引用（不含 go/types）。
	vmRef analyzer.ViewModelRef
	// bindSlots 是页面中绑定 <Text> 的数量（用于生成显示缓存槽位）。
	bindSlots int
	// clickSlots 是页面中 <Button> 的数量（用于生成 widget.Clickable 字段）。
	clickSlots int
	// clicks 记录需要轮询的事件槽位（事件处理输出契约 §2）。
	clicks []clickSlot
	// inFor 表示当前正在生成 <For> 循环体内部。
	//
	// 循环体内**不得**分配显示缓存槽位：槽位是按节点分配的，
	// 每行复用同一槽位会互相覆盖（<For> 列表契约 §6.2）。
	inFor bool
	// rowClicks 汇总循环内需要行状态池的按钮（<For> 列表契约 §3）。
	rowClicks []rowClickSlot
	// currentFor 是当前正在生成的 <For> 节点（nodeExpr 没有祖先链，
	// 用生成时的作用域标记传递）。
	currentFor *contracts.NodeIR
	// guards 是当前所处的 <If> 分支条件（由外到内）。
	guards []guardCond
	// inputSlots 是页面中 <Input> 的数量（生成 input<n> 字段）。
	inputSlots int
	// inputs 记录每个 <Input> 的生成信息（D4-A）。
	inputs []inputSlot
	// staticSlots 是"动态父容器内最大纯静态子树"局部缓存槽位的数量（R10-B，
	// 契约 §16、ADR-0006 §2.1）。仅动态页（usesVM）分配；静态页由整页
	// 缓存覆盖，<For> 体内不分配（沿用既有路径）。
	staticSlots int
	// inLocalStatic 是当前生成深度是否处于某个局部静态子树内部（>0）。
	// 内部节点由外层槽位整体覆盖，不得再分配嵌套槽位。
	inLocalStatic int
	// curMainAxis 是当前容器主轴方向（R25-R1 恢复：Expanded 子节点约束
	// 改写需要知道 Width/Height 各属主/交叉轴——这是它在本实现中的唯一
	// 消费点；由四类容器设置/恢复，Page 顶层为 vertical）。
	curMainAxis bool
	// inGridCell 表示当前处于 Grid 单元格生成内（R25-R1 F-B2：Expanded
	// 在 Grid 内准入未定义 → 显式拒绝）。
	inGridCell bool
}

// clickSlot 是一个待轮询的控件状态槽位。
type clickSlot struct {
	// index 对应生成字段 click<index>。
	index int
	// method 是 ViewModel 上的方法名。
	method string
	// args 是已渲染的实参列表（逗号分隔，可为空）。
	//
	// 实参来自 Analyzer 的 ResolvedArg（事件处理输出契约 §5.4），
	// Codegen 只负责渲染语法。
	args string
	// inFor 表示该按钮位于 <For> 循环体内，行状态从池中取。
	inFor bool
	// keyExpr 是行状态的 Key 表达式（inFor 时有效），如 item.ID。
	keyExpr string
	// poolIndex 是所属行状态池的编号（inFor 时有效）。
	poolIndex int
	// guards 是轮询时必须同时成立的条件表达式（If 输出契约 §2.2）。
	// 由外到内排列；空表示无条件。
	guards []guardCond
}

// rowClickSlot 记录一个 <For> 的行状态池（<For> 列表契约 §3）。
//
// 每个按钮一个池：同一行的多个按钮保留独立的 Clickable 状态。
type rowClickSlot struct {
	// inExpr 是数据源表达式（如 v.vm.Items），轮询与渲染共用。
	inExpr string
	// keyExpr 是轮询作用域中的 Key 表达式（如 rowItem.ID）。
	keyExpr string
	// keyType 是 Key 的类型信息（用于生成 map 的键类型）。
	keyType analyzer.TypeInfo
	// index 是索引变量名（可为空）。
	index string
	// method 是该行按钮的处理器方法名。
	method string
	// args 是已渲染的实参。
	args string
	// fieldIndex 是该池在生成结构体里的编号（rowClicks<N>）。
	fieldIndex int
	// guards 是轮询与清理时必须成立的条件（If 输出契约 §4.1）。
	guards []guardCond
}

// keyTypeExpr 渲染 map 的键类型；不可比较类型显式报错（契约 §3.2）。
func (s rowClickSlot) keyTypeExpr() (string, error) {
	switch s.keyType.Kind {
	case analyzer.ValueString, analyzer.ValueBool, analyzer.ValueInt,
		analyzer.ValueUint, analyzer.ValueFloat, analyzer.ValuePointer:
		return s.keyType.Display, nil
	case analyzer.ValueStruct:
		// 结构体的可比性取决于字段，Analyzer 的 Display 不够判；
		// 走到这里说明上游未拦截，显式拒绝而不是生成可能编译失败的代码。
		return "", fmt.Errorf(
			"codegen: <For> Key of struct type %q is not supported; use a comparable scalar key", s.keyType.Display)
	default:
		return "", fmt.Errorf(
			"codegen: <For> Key type %q is not comparable and cannot index row state", s.keyType.Display)
	}
}

// page 生成页面根节点的渲染体。
//
// `<Page>` 等价于无 Gap/Padding 的 `<Column>`（规范 §3.1），因此按垂直容器生成。
func (g *generator) page(n *contracts.NodeIR) (string, error) {
	// Parser 保证 <Page> 至少有一个渲染子节点（GXML-ROOT-001），
	// 因此这里不必再判空；若真为空是上游不变式被破坏。
	if len(n.Children) == 0 {
		return "", fmt.Errorf("codegen: <Page> has no children; Parser should have rejected this")
	}

	// 预扫描：先确定是否含绑定，因为 ops 与返回形态都取决于它。
	g.usesVM = hasDynamic(n)

	ops := "rec"
	if g.usesVM {
		// 含绑定：直接布局到帧 Ops，且**不**赋给 cacheDims
		// （没有静态缓存，也不得把动态结果固化）。
		ops = "gtx"
	}
	// <Page> 不消费布局属性：契约 §3.1/§4.7.2 定义它等价于「没有 Gap/Padding 的 <Column>」，
	// 且 Gap/Align 的适用标签只有 Column/Row/Grid（expander 的布局属性表）。
	//
	// 这里不存在「漏了对齐」的问题：<Page> 按 ADR-0008 §2.8.1 沿用 <Column> 的
	// 默认交叉轴对齐（Start），而 Gio 的零值 Alignment 恰好就是 Start，
	// 因此省略字段与显式写出 `Alignment: layout.Start` 视觉等价。
	expr, err := g.containerExpr(n.Children, false, ops, "")
	if err != nil {
		return "", err
	}
	if g.usesVM {
		return expr, nil
	}
	// 静态：录制发生在 cacheOps 上（rec），不是帧 Ops。
	return "v.cacheDims = " + expr, nil
}

// containerExpr 生成一个 Flex 容器的表达式（契约 §4.7.2）。
//
// 子节点顺序严格等于声明顺序；每个直接子节点进入 `sizeWrap`（layout.go），
// 由它统一决定包成 `layout.Rigid` 还是 `layout.Flexed`，以及是否在闭包内
// 改写 `gtx.Constraints`（`Width` / `Height` 的语义）。
//
// 含 <For> 时子项数编译期不可知，必须先运行时组装 `[]layout.FlexChild`
// （<For> 列表契约 §2：内联展开，不引入嵌套 Flex）。
// fields 是已拼好的 `, Alignment: ..., Gap: ...` 片段（无布局属性时为空串），
// 由 layout.go 的 flexFieldsExpr 生成；主生成器不参与布局属性的语义决策。
//
// mainIsHorizontal 是**本容器**的主轴方向，同时决定两件事：Flex 的 Axis，
// 以及传给 sizeWrap 的「子项主轴方向」。两者取自同一个 bool，避免出现
// 「Axis 写成 Horizontal 却按 Vertical 解释尺寸」这种只错一半的组合。
func (g *generator) containerExpr(children []*contracts.NodeIR, mainIsHorizontal bool, ops, fields string) (string, error) {
	ql := g.q("gioui.org/layout", "layout")
	prevAxis := g.curMainAxis
	g.curMainAxis = mainIsHorizontal
	defer func() { g.curMainAxis = prevAxis }()

	if hasForChild(children) || hasIfChild(children) {
		return g.dynamicContainerExpr(children, mainIsHorizontal, ops, fields)
	}

	var b strings.Builder
	b.WriteString(ql + ".Flex{Axis: " + axisIdent(g, mainIsHorizontal) + fields + "}.Layout(" + ops)
	for _, c := range children {
		inner, err := g.nodeExpr(c)
		if err != nil {
			return "", err
		}
		// 尺寸语义（含「无界不抬 Min」的唯一判据）全部在 sizeWrap 内，
		// 本函数只负责按声明顺序拼接，不复制任何条件表达式。
		b.WriteString(",\n\t\t" + sizeWrap(g, c, inner, mainIsHorizontal))
	}
	b.WriteString(")")
	return b.String(), nil
}

// dynamicContainerExpr 生成「运行时组装子项」的容器表达式。
//
// 形态是立即调用的闭包，因此仍是表达式，可直接放进既有 `return <expr>` 位置：
//
//	func() layout.Dimensions {
//		children := make([]layout.FlexChild, 0, <静态子项数>)
//		children = append(children, layout.Rigid(...))   // 静态子项
//		{ items := ...; for _, item := range items { ... } }  // <For> 内联展开
//		return layout.Flex{Axis: ...}.Layout(gtx, children...)
//	}()
//
// 子项一律经 sizeWrap 包装（与静态路径同一模板）：动态路径曾经硬编码
// `layout.Rigid(...)` 并静默忽略 Width/Height，现在由 sizeWrap 统一决定
// Rigid/Flexed 与约束改写，主轴方向由调用方逐层透传。
func (g *generator) dynamicContainerExpr(children []*contracts.NodeIR, mainIsHorizontal bool, ops, fields string) (string, error) {
	ql := g.q("gioui.org/layout", "layout")
	prevAxis := g.curMainAxis
	g.curMainAxis = mainIsHorizontal
	defer func() { g.curMainAxis = prevAxis }()
	// 初始容量取静态子项数；<For> 的项数编译期不可知，由 append 增长。
	static := 0
	for _, c := range children {
		if !isForNode(c) && !isIfNode(c) {
			static++
		}
	}

	var b strings.Builder
	b.WriteString("func() " + ql + ".Dimensions {\n")
	b.WriteString(fmt.Sprintf("\t\t\tchildren := make([]"+ql+".FlexChild, 0, %d)\n", static))

	for _, c := range children {
		if isForNode(c) {
			if err := g.emitForChildren(&b, c, "\t\t\t", mainIsHorizontal); err != nil {
				return "", err
			}
			continue
		}
		if isIfNode(c) {
			if err := g.emitIfChildren(&b, c, "\t\t\t", mainIsHorizontal); err != nil {
				return "", err
			}
			continue
		}
		inner, err := g.nodeExpr(c)
		if err != nil {
			return "", err
		}
		// 与静态路径共用同一 sizeWrap：动态路径不得另写一份尺寸判断。
		b.WriteString("\t\t\tchildren = append(children, " + sizeWrap(g, c, inner, mainIsHorizontal) + ")\n")
	}

	b.WriteString("\t\t\treturn " + ql + ".Flex{Axis: " + axisIdent(g, mainIsHorizontal) + fields + "}.Layout(" + ops + ", children...)\n")
	b.WriteString("\t\t}()")
	return b.String(), nil
}

// emitForChildren 把一个 <For> 内联展开为「循环 + 逐项 append」的语句块。
//
// 关键一致性（<For> 列表契约 §5）：数据源只求值一次并存入局部变量 items，
// 供后续事件轮询与渲染共用——两处各写一遍取数表达式会在并发修改下串位。
func (g *generator) emitForChildren(b *strings.Builder, n *contracts.NodeIR, indent string, mainIsHorizontal bool) error {
	nf, ok := lookupFor(n, g.facts)
	if !ok {
		return fmt.Errorf("codegen: <%s> has no resolved for-clause facts; the analyzer result is inconsistent", n.Tag)
	}
	if nf.In == nil {
		return fmt.Errorf("codegen: <For> has no resolved In path")
	}
	if nf.Each == "" {
		return fmt.Errorf("codegen: <For> has no Each variable")
	}
	// 循环变量名不得与生成代码使用的标识符冲突（契约 §6.1）。
	// 静默覆盖会生成语法正确但语义错误的代码，因此显式报错。
	if err := checkLoopVarName(nf.Each); err != nil {
		return err
	}
	if nf.Index != "" {
		if err := checkLoopVarName(nf.Index); err != nil {
			return err
		}
		if nf.Index == nf.Each {
			return fmt.Errorf("codegen: <For> Each and Index must differ (both %q)", nf.Each)
		}
	}
	if len(n.Children) == 0 {
		return fmt.Errorf("codegen: <For> has no children")
	}

	inExpr, err := pathExpr(nf.In, "v.vm", "<For In>")
	if err != nil {
		return err
	}

	b.WriteString(indent + "{\n")
	b.WriteString(indent + "\titems := " + inExpr + "\n")
	// Index 变量只在循环体**真的引用**它时才生成。
	// Go 对 `for i, item := range` 中未使用的 i 会报 "declared and not used"，
	// 而 Index 是可选的，声明了却不引用是完全合法的写法。
	if nf.Index != "" && (g.forVarUsed(n.Children, nf.Index) || pathRootsAt(nf.Key, nf.Index)) {
		b.WriteString(indent + "\tfor " + nf.Index + ", " + nf.Each + " := range items {\n")
		// Event arguments and keys may use the index only in the polling scope.
		b.WriteString(indent + "\t\t_ = " + nf.Index + "\n")
	} else {
		b.WriteString(indent + "\tfor _, " + nf.Each + " := range items {\n")
	}
	// 显式遮蔽：闭包捕获的是**本轮**的循环变量。
	// （Go 1.22 起 range 变量本就每轮独立，这里显式写出来是为了让生成的
	// 代码在任何阅读者眼里都不依赖那个语言细节。）
	b.WriteString(indent + "\t\t" + nf.Each + " := " + nf.Each + "\n")
	b.WriteString(indent + "\t\t_ = " + nf.Each + "\n")

	// 循环体内不分配显示缓存槽位：槽位按节点分配，每行复用会互相覆盖
	// （<For> 列表契约 §6.2）。
	prevInFor := g.inFor
	prevFor := g.currentFor
	prevAxis := g.curMainAxis
	g.curMainAxis = mainIsHorizontal
	g.inFor = true
	g.currentFor = n
	for _, c := range n.Children {
		if isForNode(c) {
			g.inFor = prevInFor
			g.currentFor = prevFor
			return fmt.Errorf("codegen: nested <For> is not supported in this slice")
		}
		// 循环体里的 <If> 也要内联展开（If 输出契约 §4.1）。
		if isIfNode(c) {
			if err := g.emitIfChildren(b, c, indent+"\t\t", mainIsHorizontal); err != nil {
				g.inFor = prevInFor
				g.currentFor = prevFor
				return err
			}
			continue
		}
		inner, err := g.nodeExpr(c)
		if err != nil {
			g.inFor = prevInFor
			g.currentFor = prevFor
			return err
		}
		// 逐项 append 与静态子项共用 sizeWrap：循环内的尺寸语义不另起一套。
		b.WriteString(indent + "\t\tchildren = append(children, " + sizeWrap(g, c, inner, mainIsHorizontal) + ")\n")
	}
	g.inFor = prevInFor
	g.currentFor = prevFor
	g.curMainAxis = prevAxis

	b.WriteString(indent + "\t}\n")
	b.WriteString(indent + "}\n")
	return nil
}

// isForNode 报告节点是否为 <For> 结构节点。
func isForNode(n *contracts.NodeIR) bool {
	if n == nil {
		return false
	}
	return n.Kind == contracts.KindFor || n.For != nil
}

// hasForChild 报告直接子节点中是否含 <For>。
func hasForChild(children []*contracts.NodeIR) bool {
	for _, c := range children {
		if isForNode(c) {
			return true
		}
	}
	return false
}

// isIfNode 报告节点是否为 <If> 结构节点。
func isIfNode(n *contracts.NodeIR) bool {
	if n == nil {
		return false
	}
	return n.Kind == contracts.KindIf || n.If != nil
}

// hasIfChild 报告直接子节点中是否含 <If>。
func hasIfChild(children []*contracts.NodeIR) bool {
	for _, c := range children {
		if isIfNode(c) {
			return true
		}
	}
	return false
}

// checkLoopVarName 拒绝与生成代码标识符冲突的循环变量名。
func checkLoopVarName(name string) error {
	switch name {
	case "v", "th", "gtx", "items", "children", "rec", "k", "ops",
		// R15-B：`append` 是循环体作用域内生成代码**实际调用**的内置函数——
		// For 内联展开会生成 `children = append(children, sizeWrap(...))`，
		// 循环变量同名时该调用解析到循环变量，go build 失败
		//（cannot call append (variable of struct type Row)）。
		// 判据仍是契约 §6.1 的「与生成代码使用的标识符冲突」，不是内置函数
		// 一刀切：len/make/new 等在该作用域内未被生成代码使用，保持合法。
		"append":
		return fmt.Errorf(
			"codegen: <For> variable %q collides with an identifier used by generated code; rename it", name)
	}
	return nil
}

// nodeExpr 生成单个节点的渲染**表达式**（返回 layout.Dimensions）。
//
// localStaticSubtree 报告 n 是否为"动态父容器内最大纯静态子树"的根。
//
// 静态判据**唯一依据** ADR-0006 §2.1：不含 {Binding}、事件、<If>、<For>、
// 交互控件（Button/Input），布局结果只依赖 renderContextKey 已纳入的上下文。
// 本函数不复制该定义——直接复用 hasDynamic 的否定（同一条规则的否定形式），
// 避免第二份定义漂移（契约 §16.1"本条不另立定义"）。
func (g *generator) localStaticSubtree(n *contracts.NodeIR) bool {
	return n != nil && !hasDynamic(n)
}

// localStaticCacheExpr 为一个最大纯静态子树生成"局部缓存"包装表达式
// （契约 §16.2-16.4：View 自持持久 Ops/CallOp/Dimensions/key，惰性录制、
// key 未变只回放）。key 取该节点**实际收到**的 Constraints/Metric/Theme/
// Locale（包装闭包的 gtx 已经过 sizeWrap 的约束改写），浮点按位比较
// （§16.5）。
//
// 录制次数验收仪表不在生产输出内（R11-B B1：验收计数由测试在外部生成
// 副本注入，见 local_static_subtree_test.go 的 injectProbeRecs）。
//
// 槽位字段 static*<slot> 由结构体发射段生成；子节点不再各自分配槽位
// （外层槽位已整体覆盖——"不重复固化"）。
func (g *generator) localStaticCacheExpr(n *contracts.NodeIR) (string, error) {
	slot := g.staticSlots
	g.staticSlots++
	g.inLocalStatic++
	inner, err := g.nodeExpr(n)
	g.inLocalStatic--
	if err != nil {
		return "", err
	}
	s := fmt.Sprint(slot)
	var b strings.Builder
	ql := g.q("gioui.org/layout", "layout")
	qop := g.q("gioui.org/op", "op")
	b.WriteString("func(gtx " + ql + ".Context) " + ql + ".Dimensions {\n")
	b.WriteString("\tkS" + s + " := " + g.keyType + "{constraints: gtx.Constraints, metric: gtx.Metric, theme: th, locale: gtx.Locale}\n")
	b.WriteString("\tif !v.staticCached" + s + " || !v.staticKey" + s + ".equal(kS" + s + ") {\n")
	b.WriteString("\t\tv.staticOps" + s + ".Reset()\n")
	b.WriteString("\t\tmS" + s + " := " + qop + ".Record(&v.staticOps" + s + ")\n")
	b.WriteString("\t\trecS" + s + " := gtx\n")
	b.WriteString("\t\trecS" + s + ".Ops = &v.staticOps" + s + "\n")
	b.WriteString("\t\tv.staticDims" + s + " = func(gtx " + ql + ".Context) " + ql + ".Dimensions {\n")
	b.WriteString("\t\t\treturn " + inner + "\n")
	b.WriteString("\t\t}(recS" + s + ")\n")
	b.WriteString("\t\tv.staticCall" + s + " = mS" + s + ".Stop()\n")
	b.WriteString("\t\tv.staticKey" + s + " = kS" + s + "\n")
	b.WriteString("\t\tv.staticCached" + s + " = true\n")
	b.WriteString("\t}\n")
	b.WriteString("\tv.staticCall" + s + ".Add(gtx.Ops)\n")
	b.WriteString("\treturn v.staticDims" + s + "\n")
	b.WriteString("}(gtx)")
	return b.String(), nil
}

// 与语句形态的区别：闭包内必须是表达式，不能是赋值语句。
func (g *generator) nodeExpr(n *contracts.NodeIR) (string, error) {
	if n == nil {
		return "", fmt.Errorf("codegen: nil node")
	}

	// R10-B：动态父容器内的最大纯静态子树 → 局部缓存槽位（契约 §16、
	// ADR-0006 §2.1）。判据复用 hasDynamic 的否定（不另立定义，避免第二份
	// 静态定义漂移）；静态页由整页缓存覆盖（usesVM=false）、<For> 体内
	// 沿用既有路径（§6.2）、局部缓存内部不嵌套（外层槽位已覆盖子节点）。
	// If 分支内的纯静态后代同样适用（emitBranchAppends 亦经 nodeExpr），
	// 各分支天然独占槽位。
	if g.usesVM && !g.inFor && g.inLocalStatic == 0 && !hasDynamic(n) {
		return g.localStaticCacheExpr(n)
	}

	switch n.Tag {
	case "Text":
		if len(n.Events) > 0 {
			return "", fmt.Errorf("codegen: <Text> events are not supported in this slice")
		}
		if len(n.Children) > 0 {
			return "", fmt.Errorf("codegen: <Text> must not have children")
		}
		g.imports.add("gioui.org/widget/material", "material")

		// 优先按绑定处理。绑定信息**只**来自 Facts；查不到就报错，
		// 绝不回退成字符串常量（那会把 "{Title}" 当成字面文本）。
		//
		// 绑定判定与「是否占槽」走**同一条规则** textBindSlot（slots.go），
		// 预检的 CountBindSlots 用的也是它——不允许在这里另写一份条件。
		var inner string
		if ra, isBinding, takesSlot := textBindSlot(n, g.facts, g.inFor); isBinding {
			expr, err := bindingExpr(ra, "v.vm")
			if err != nil {
				return "", err
			}
			g.usesVM = true
			if !takesSlot {
				inner = fmt.Sprintf(g.q("gioui.org/widget/material", "material")+".Body1(th, %s).Layout(gtx)", expr)
			} else {
				// 分配显示缓存槽位；闭包内通过 v.n<i> 读写缓存。
				slot := g.bindSlots
				g.bindSlots++
				inner = fmt.Sprintf("v.bindText(gtx, th, %d, %s)", slot, expr)
			}
		} else {
			value, ok := staticAttr(n, "Value")
			if !ok {
				return "", fmt.Errorf(
					"codegen: <Text> needs a static Value; data binding is not supported in this slice")
			}
			inner = fmt.Sprintf(g.q("gioui.org/widget/material", "material")+".Body1(th, %s).Layout(gtx)", quote(value))
		}
		// 叶子装饰（Padding 子集）：静态 Padding 包 layout.Inset。
		return leafDecorationExpr(g, n, inner), nil

	case "Button":
		inner, err := g.buttonExpr(n)
		if err != nil {
			return "", err
		}
		return leafDecorationExpr(g, n, inner), nil

	case "Input":
		inner, err := g.inputExpr(n)
		if err != nil {
			return "", err
		}
		return leafDecorationExpr(g, n, inner), nil

	case "Image":
		return g.imageExpr(n)

	case "Column":
		// 嵌套容器在闭包内，使用闭包的 gtx（其 Ops 已是帧/cacheOps）。
		fields, err := flexFieldsExpr(g, n.Tag, n)
		if err != nil {
			return "", err
		}
		inner, err := g.containerExpr(n.Children, false, "gtx", fields)
		if err != nil {
			return "", err
		}
		return paddingInsetExpr(g, n, inner), nil

	case "Row":
		fields, err := flexFieldsExpr(g, n.Tag, n)
		if err != nil {
			return "", err
		}
		inner, err := g.containerExpr(n.Children, true, "gtx", fields)
		if err != nil {
			return "", err
		}
		return paddingInsetExpr(g, n, inner), nil

	case "Grid":
		// 列定义见 Contracts.GridColumn；生成形态与规范推演见 grid.go 文件头。
		inner, err := g.gridExpr(n)
		if err != nil {
			return "", err
		}
		return paddingInsetExpr(g, n, inner), nil

	case "Spacer":
		return g.spacerExpr(n)

	case "Expanded":
		// R25-R1 F-B1 修复：包装节点与子节点**各自尺寸职责**分离——
		//   - 弹性角色：父容器对 Expanded 节点的 sizeWrap 生成 Flexed(1)
		//     （sizePlanFor 特例；Expanded 自身显式尺寸仍优先为 Exact）；
		//   - 子节点自身尺寸：Exact/Fill 约束改写在弹性 cell 内、渲染前
		//     生效（IIFE 注入，gtx 影子同值），不再直通丢失
		//     （R22 复核 F-B1：Width=12 与无 Width 产物相同的缺陷）。
		// 绑定/事件/静态缓存接缝经 nodeExpr(child) 全保留；不重复包装
		// FlexChild（子约束是语句注入，不是第二层 FlexChild）。
		if len(n.Children) != 1 {
			return "", fmt.Errorf("codegen: <Expanded> 恰好一个子节点，实际 %d", len(n.Children))
		}
		if !n.Padding.IsZero() {
			return "", fmt.Errorf("codegen: <Expanded> 不支持自身 Padding（装饰语义未定义，R25-R1 F-B2 显式拒绝）")
		}
		if g.inGridCell {
			return "", fmt.Errorf("codegen: <Expanded> 不支持 Grid 单元格内使用（准入语义未定义，R25-R1 F-B2 显式拒绝）")
		}
		child := n.Children[0]
		inner, err := g.nodeExpr(child)
		if err != nil {
			return "", err
		}
		pre := sizeConstraintsExpr(g, child, g.curMainAxis)
		if pre.Len() == 0 {
			return inner, nil
		}
		ql := g.q("gioui.org/layout", "layout")
		return "func(gtx " + ql + ".Context) " + ql + ".Dimensions {\n" + pre.String() + "\t\t\treturn " + inner + "\n\t\t}(gtx)", nil

	default:
		return "", fmt.Errorf("codegen: <%s> is not supported in this slice", n.Tag)
	}
}

// spacerExpr 生成 `<Spacer>` 的渲染表达式（TASK-CODEGEN-001-1、规范 §3.1）。
//
// 尺寸**不写进** Spacer 字面量：全部由 `sizeWrap` 改写约束，再由
// `layout.Spacer.Layout` 的 `Constraints.Constrain` 落成实际占位
// （gioui.org@v0.10.3/layout/layout.go:242）。理由是与其它节点保持同一事实来源——
// 若这里再写一份 `Width: unit.Dp(8)`，`sizeWrap` 的精确约束与字面量就成了
// 两个来源，改一处不改另一处会得到「约束 8、占位 12」这种只错一半的结果，
// 而且 `<Spacer Width="Fill"/>` 根本无法用 `unit.Dp` 表达。
//
// 因此本函数只回答一件事：**空白占位用哪个 Gio 原语**。
func (g *generator) spacerExpr(n *contracts.NodeIR) (string, error) {
	// Parser 已拒绝这两种形态（`<Spacer> cannot contain children`、
	// `<Spacer> only accepts Width and Height`）。这里做防御性二次校验：
	// 上游不变式若被破坏，必须显式失败，而不是生成一个静默忽略属性的占位。
	if len(n.Children) > 0 {
		return "", fmt.Errorf("codegen: <Spacer> must not have children; Parser should have rejected this")
	}
	if len(n.Attrs) > 0 {
		return "", fmt.Errorf(
			"codegen: <Spacer> accepts only Width and Height, but %d other attribute(s) survived the frontend", len(n.Attrs))
	}
	g.imports.add("gioui.org/layout", "layout")
	return g.q("gioui.org/layout", "layout") + ".Spacer{}.Layout(gtx)", nil
}

// buttonExpr 生成 <Button> 的渲染表达式（事件处理输出契约 §6）。
//
// MVP 范围：
//   - 事件：仅无参 Click；
//   - 属性：Text（静态或绑定）；Enabled 明确报错。
func (g *generator) buttonExpr(n *contracts.NodeIR) (string, error) {
	if len(n.Children) > 0 {
		return "", fmt.Errorf("codegen: <Button> must not have children")
	}
	g.imports.add("gioui.org/widget/material", "material")
	g.imports.add("gioui.org/widget", "widget")

	// Enabled 需要 gtx.Disabled() 语义，不在 MVP 范围。
	// 明确报错而非静默忽略——忽略会让「禁用」变成可点击。
	if _, ok := staticAttr(n, "Enabled"); ok {
		return "", fmt.Errorf("codegen: <Button Enabled> is not supported in this slice")
	}
	for _, a := range n.Attrs {
		if a.Name == "Enabled" {
			return "", fmt.Errorf("codegen: <Button Enabled> is not supported in this slice")
		}
	}

	// 控件状态槽位：每个 Button 一个，跨帧稳定（契约 §1）。
	// 循环内的按钮改用行状态池，idx 仍分配但不用于绘制。
	idx := g.clickSlots
	g.clickSlots++
	// rowKey 是行状态的 Key 表达式（g.inFor 时有效），如 item.ID。
	// rowPool 是所属池编号。
	var rowKey string
	rowPool := -1

	// 事件校验（MVP：仅无参 Click）。
	for _, ev := range n.Events {
		if ev.Name != "Click" {
			return "", fmt.Errorf(
				"codegen: <Button> event %q is not supported in this slice; only Click", ev.Name)
		}
		if ev.Method == "" {
			return "", fmt.Errorf("codegen: Click has no method name")
		}
		// 实参**只**取自已验证的 Facts，不回读原始文本。
		resolved, ok := lookupEvent(n, ev.Name, g.facts)
		if !ok {
			return "", fmt.Errorf(
				"codegen: event %q on <%s> has no resolved facts; the analyzer result is inconsistent",
				ev.Name, n.Tag)
		}
		// 经通用层组装实参（TASK-EVENT-PAYLOAD-001）：
		// Button 的 Click 无载荷，因此不提供载荷表达式；若 Schema 将来给
		// Click 加载荷，这里会因 payload==nil 报内部错误——即"控件未接线"，
		// 而不是静默生成少参数的调用。
		args, err := g.renderInvocationArgs(resolved, nil)
		if err != nil {
			return "", err
		}
		slot := clickSlot{index: idx, method: ev.Method, args: args, guards: append([]guardCond(nil), g.guards...)}
		// 循环内的按钮：**必须**有 Key（<For> 列表契约 §3.1——Parser 的
		// SCOPE-003 已强制，这里做防御性二次校验），行状态从池取。
		if g.inFor {
			// Key 必须存在（<For> 列表契约 §3.1——Parser 的 SCOPE-003 已强制，
			// 这里做防御性二次校验，防上游放行）。
			if g.currentFor == nil || g.currentFor.For == nil || !g.currentFor.For.HasKey {
				return "", fmt.Errorf("codegen: <Button> inside <For> requires a Key on <For> to keep per-row state stable")
			}
			rf, ok := lookupFor(g.currentFor, g.facts)
			if !ok || rf.Key == nil {
				return "", fmt.Errorf("codegen: <For> Key is required for row state but no resolved key path is available")
			}
			keyExpr, err := pathExpr(rf.Key, "v.vm", "<For Key>")
			if err != nil {
				return "", err
			}
			slot.inFor = true
			slot.keyExpr = keyExpr
			rowKey = keyExpr
			slot.poolIndex, err = g.registerRowClick(rf, resolved)
			if err != nil {
				return "", err
			}
			rowPool = slot.poolIndex
		}
		g.clicks = append(g.clicks, slot)
	}

	// 标签：绑定优先（经 Facts），否则静态字面量；缺省为空标签（Schema 非必选）。
	label := `""`
	if ra, ok := lookupAttr(n, "Text", g.facts); ok && ra.Path != nil {
		expr, err := bindingExpr(ra, "v.vm")
		if err != nil {
			return "", err
		}
		g.usesVM = true
		label = expr
	} else if raw, ok := staticAttr(n, "Text"); ok {
		label = quote(raw)
	}

	if g.inFor {
		return fmt.Sprintf(g.q("gioui.org/widget/material", "material")+".Button(th, v.rowClick%d(%s), %s).Layout(gtx)", rowPool, rowKey, label), nil
	}
	return fmt.Sprintf(g.q("gioui.org/widget/material", "material")+".Button(th, &v.click%d, %s).Layout(gtx)", idx, label), nil
}

// staticAttr 取静态属性值；绑定属性返回 false。
func staticAttr(n *contracts.NodeIR, name string) (string, bool) {
	for _, a := range n.Attrs {
		if a.Name != name {
			continue
		}
		if a.Value.IsBinding {
			return "", false
		}
		return a.Value.Raw, true
	}
	return "", false
}

// assemble 拼装完整源文件。
//
// import 由 importSet 统一收集并按契约 §7 排序，只在真正被引用时出现。
// assemble 拼装完整源文件（含静态子树缓存，契约 §16）。
func (g *generator) assemble(body string) (string, error) {
	// 签名始终需要 layout。
	g.imports.add("gioui.org/layout", "layout")
	// 签名始终是 `Layout(gtx layout.Context, th *material.Theme)`（契约 §4.3.1），
	// 因此 material **无条件**需要——即使整页只有布局标签、没有任何文本。
	// 早前它在生成 Text/Button 时才登记，`<Page><Spacer/></Page>` 这类页面
	// 会生成「签名引用 material、import 里却没有」的代码，编译直接失败。
	g.imports.add("gioui.org/widget/material", "material")
	g.imports.add("gioui.org/io/system", "system")
	g.imports.add("math", "math")
	g.imports.add("gioui.org/unit", "unit")
	// op 只在真正用到时导入：
	//   静态页 —— op.Record / op.CallOp 的整页固化；
	//   动态页 —— 绑定缓存槽位（op.Ops/op.CallOp）或事件失效（op.InvalidateCmd）。
	// 只为展示型 <For> 的页面两者都没有，无条件导入会编译失败。
	if !g.usesVM || g.bindSlots > 0 || len(g.clicks) > 0 || g.staticSlots > 0 {
		g.imports.add("gioui.org/op", "op")
	}
	if g.usesVM {
		// 构造函数的 nil 校验使用 fmt.Errorf。
		g.imports.add("fmt", "fmt")
	}
	if len(g.assets) > 0 {
		// 构造期从 embed.FS 读取并解码一次；Layout 只回放 paint.ImageOp。
		g.imports.add("bytes", "bytes")
		g.imports.add("embed", "embed")
		g.imports.add("image", "image")
		g.imports.add("gioui.org/op/paint", "paint")
		g.imports.addBlank("image/jpeg")
		g.imports.addBlank("image/png")
	}

	// vm 类型：仅当页面含绑定时需要（构造函数参数与 View 字段）。
	//
	// 注意：vmTypeExpr 会登记跨包 import，必须在 import render 之前调用。
	if g.usesVM {
		if _, err := g.vmTypeExpr(); err != nil {
			return "", err
		}
	}

	var b strings.Builder
	b.WriteString(headerFor(g.opts.SourcePath))
	b.WriteString("package " + g.opts.PackageName + "\n\n")
	b.WriteString(g.imports.render())
	b.WriteString("\n")
	if len(g.assets) > 0 {
		if g.assetVar == "" {
			return "", fmt.Errorf("codegen: assets were registered without an embed variable name")
		}
		for _, p := range g.assets {
			b.WriteString("//go:embed " + quote(p) + "\n")
		}
		b.WriteString("var " + g.assetVar + " " + g.q("embed", "embed") + ".FS\n\n")
	}
	b.WriteString("// " + g.view + " 是 " + baseName(g.opts.SourcePath) + " 的生成视图。\n")
	b.WriteString("type " + g.view + " struct {\n")
	if g.usesVM {
		// 含绑定：**不**生成整页静态缓存（契约 §16.7、红线 2），
		// 但按绑定节点生成**显示缓存槽位**（契约 §05.2/05.3.1），
		// 并持有 vm 引用（状态更新契约 §1、ADR-0010）。
		b.WriteString("\tvm *" + g.vmTypeExprStr() + "\n")
		// 仅在确有绑定槽位时生成：纯事件页没有 textCache 类型声明
		// （bindCacheDecl 在 slots==0 时不输出），否则编译失败。
		if g.bindSlots > 0 {
			b.WriteString("\tslots []" + g.cacheType + "\n")
		}
		// 交互控件状态：每个 <Button> 一个，跨帧地址不变（契约 §1.3）。
		for i := 0; i < g.clickSlots; i++ {
			b.WriteString(fmt.Sprintf("\tclick%d %s.Clickable\n", i, g.q("gioui.org/widget", "widget")))
		}
		// Input 的编辑器实例：每个 <Input> 一个，跨帧稳定（契约 §6.3）。
		// applied<n> 是 lastApplied 占位——D4-B 实现同步算法时使用。
		for i := 0; i < g.inputSlots; i++ {
			b.WriteString(fmt.Sprintf("\tinput%d %s.Editor\n", i, g.q("gioui.org/widget", "widget")))
			b.WriteString(fmt.Sprintf("\tapplied%d string\n", i))
		}
		// R10-B：动态父容器内局部静态子树缓存（契约 §16、ADR-0006 §2.1）。
		// 每个"最大纯静态子树"一个独立槽位：View 自持持久 Ops（永不 Reset
		// 之外的复用）、CallOp 区间、Dimensions 与上下文 key。
		// R11-B：录制次数验收仪表已移出生产输出（测试经外部副本注入）。
		for i := 0; i < g.staticSlots; i++ {
			b.WriteString(fmt.Sprintf("\tstaticOps%d %s.Ops\n", i, g.q("gioui.org/op", "op")))
			b.WriteString(fmt.Sprintf("\tstaticCall%d %s.CallOp\n", i, g.q("gioui.org/op", "op")))
			b.WriteString(fmt.Sprintf("\tstaticDims%d %s.Dimensions\n", i, g.q("gioui.org/layout", "layout")))
			b.WriteString(fmt.Sprintf("\tstaticKey%d %s\n", i, g.keyType))
			b.WriteString(fmt.Sprintf("\tstaticCached%d bool\n", i))
		}
		// 行状态池：每个含交互控件的 <For> 一个（<For> 列表契约 §3.2）。
		// map 元素不可寻址，必须存指针。
		for pi, rc := range g.rowClicks {
			kt, err := rc.keyTypeExpr()
			if err != nil {
				return "", err
			}
			b.WriteString(fmt.Sprintf("\trowClicks%d map[%s]*%s.Clickable\n", pi, kt, g.q("gioui.org/widget", "widget")))
		}
	} else {
		for _, line := range g.cacheFieldLines() {
			b.WriteString(line + "\n")
		}
	}
	// 静态 Image 资产：构造期解码一次，Layout 只回放 ImageOp。
	for i, p := range g.assets {
		b.WriteString(fmt.Sprintf("\t// img%d 是 <Image Src=%q> 的解码结果。\n", i, p))
		b.WriteString(fmt.Sprintf("\timg%d %s.ImageOp\n", i, g.q("gioui.org/op/paint", "paint")))
	}
	b.WriteString("}\n\n")
	// 构造函数：按页面类型分两种形态（状态更新契约 §1.4）。
	//
	//   静态页面：NewXxxView()            —— 与历史形态一致，不变；
	//   绑定页面：NewXxxView(vm *T) (*X, error) —— 持有 vm 引用。
	//
	// nil vm 是调用方配置错误，必须显式拒绝（ADR-0010 §3.4）：
	// 不静默转空串、不忽略绑定、不允许难定位的深层 panic。
	// 返回 error 而非 panic：nil 是**调用方输入错误**（可恢复），
	// 与内部不变式破坏（panic，如 Facts freeze）性质不同；
	// 且仓库已有 NewTypeEnv(...) (*T, error) 先例。
	b.WriteString("// New" + g.view + " 创建视图状态。\n")
	if g.usesVM {
		b.WriteString("//\n")
		b.WriteString("// vm 由调用方创建并管理生命周期；View 只持有引用，\n")
		b.WriteString("// 不拥有、不销毁，第一版不支持隐式替换（ADR-0010）。\n")
		b.WriteString("// vm 为 nil 时返回错误——这是调用方配置错误，明确拒绝。\n")
		b.WriteString("//\n")
		b.WriteString("// ⚠️ 失效通知的并发安全（Runtime Invalidate）不等于 vm 字段\n")
		b.WriteString("// 读写的并发安全；跨 goroutine 修改 vm 由调用方负责同步。\n")
		b.WriteString("func New" + g.view + "(vm *" + g.vmTypeExprStr() + ") (*" + g.view + ", error) {\n")
		b.WriteString("\tif vm == nil {\n")
		b.WriteString("\t\treturn nil, " + g.q("fmt", "fmt") + ".Errorf(\"goxml: New" + g.view + " requires a non-nil ViewModel; a binding page cannot render without state\")\n")
		b.WriteString("\t}\n")
		if len(g.assets) > 0 {
			b.WriteString("\tv := &" + g.view + "{vm: vm}\n")
			g.writeImageDecode(&b, "\t", true)
			b.WriteString("\treturn v, nil\n")
		} else {
			b.WriteString("\treturn &" + g.view + "{vm: vm}, nil\n")
		}
		b.WriteString("}\n\n")
		b.WriteString("// Layout 渲染页面（统一 View 接口，状态更新契约 §1）。\n")
		b.WriteString("//\n")
		b.WriteString("// 绑定节点按槽位缓存显示结果：显示串与上下文未变时回放，\n")
		b.WriteString("// 变化时重录（契约 §05.2/§05.3.1）。\n")
		b.WriteString("//\n")
		b.WriteString("// 含绑定，因此**不**走静态子树固化（契约 §16.7）。\n")
		if len(g.clicks) > 0 {
			b.WriteString("//\n")
			b.WriteString("// 事件轮询置于一切绘制之前（事件处理输出契约 §2.2）：\n")
			b.WriteString("// 保证所有状态变更发生在任何节点渲染之前，同帧强一致。\n")
		}
		ql := g.q("gioui.org/layout", "layout")
		qm := g.q("gioui.org/widget/material", "material")
		b.WriteString("func (v *" + g.view + ") Layout(gtx " + ql + ".Context, th *" + qm + ".Theme) " + ql + ".Dimensions {\n")
		// 事件消费：必须在绘制之前（契约 §2.1/§2.2）。
		// 普通按钮逐个轮询；行状态按钮数据驱动（<For> 列表契约 §5）。
		for _, cs := range g.clicks {
			if cs.inFor {
				continue
			}
			// 条件守卫（If 输出契约 §2.2）：只在分支会被渲染时才轮询。
			if gd := guardExpr(cs.guards); gd != "" {
				b.WriteString("\tif " + gd + " {\n")
			}
			ind := "\t"
			if guardExpr(cs.guards) != "" {
				ind = "\t\t"
			}
			b.WriteString(fmt.Sprintf(ind+"for v.click%d.Clicked(gtx) {\n", cs.index))
			b.WriteString(ind + "\t v.vm." + cs.method + "(" + cs.args + ")\n")
			b.WriteString(ind + "\t gtx.Execute(" + g.q("gioui.org/op", "op") + ".InvalidateCmd{})\n")
			b.WriteString(ind + "}\n")
			if guardExpr(cs.guards) != "" {
				b.WriteString("\t}\n")
			}
		}
		// 行状态轮询（<For> 列表契约 §5）：数据驱动。
		// 与渲染用**同一数据源表达式**（同源）与**同一顺序**（range 切片），
		// 防止并发修改列表时两处错位。
		for _, rc := range g.rowClicks {
			b.WriteString(rc.pollCode(g.q("gioui.org/op", "op")))
		}
		// 键清理（<For> 列表契约 §4）：轮询之后、渲染之前。
		// 快速跳过：池不比列表大就不可能有失效键——稳定帧零分配。
		for _, rc := range g.rowClicks {
			b.WriteString(rc.cleanupCode())
		}
		if len(g.clicks) > 0 {
			b.WriteString("\n")
		}
		b.WriteString("\treturn " + strings.ReplaceAll(body, "\n", "\n\t") + "\n")
		b.WriteString("}\n")
		// 行状态池辅助方法（<For> 列表契约 §3.3）：惰性创建，跨帧稳定。
		for pi, rc := range g.rowClicks {
			kt, err := rc.keyTypeExpr()
			if err != nil {
				return "", err
			}
			qw := g.q("gioui.org/widget", "widget")
			b.WriteString(fmt.Sprintf(`
// rowClick%d 返回 Key 对应的行控件状态；不存在则创建（惰性）。
func (v *`+g.view+`) rowClick%d(key %s) *`+qw+`.Clickable {
	if v.rowClicks%d == nil {
		v.rowClicks%d = make(map[%s]*`+qw+`.Clickable)
	}
	c := v.rowClicks%d[key]
	if c == nil {
		c = new(`+qw+`.Clickable)
		v.rowClicks%d[key] = c
	}
	return c
}
`, pi, pi, kt, pi, pi, kt, pi, pi))
		}
		// 绑定页面同样需要 renderKey 与绑定缓存声明。
		b.WriteString(g.renderKeyDecl())
		b.WriteString(g.bindCacheDecl())
		return b.String(), nil
	}
	if len(g.assets) > 0 {
		b.WriteString("func New" + g.view + "() *" + g.view + " {\n")
		b.WriteString("\tv := &" + g.view + "{}\n")
		g.writeImageDecode(&b, "\t", false)
		b.WriteString("\treturn v\n")
		b.WriteString("}\n\n")
	} else {
		b.WriteString("func New" + g.view + "() *" + g.view + " { return &" + g.view + "{} }\n\n")
	}

	ql := g.q("gioui.org/layout", "layout")
	qm := g.q("gioui.org/widget/material", "material")
	qop := g.q("gioui.org/op", "op")
	b.WriteString("// 首个 key 生效时录制，之后 key 未变只回放（契约 §16.4）。\n")
	b.WriteString("func (v *" + g.view + ") Layout(gtx " + ql + ".Context, th *" + qm + ".Theme) " + ql + ".Dimensions {\n")
	b.WriteString("\tk := v.currentKey(gtx, th)\n")
	b.WriteString("\tif v.cached && v.cacheKey.equal(k) {\n")
	b.WriteString("\t\tv.cacheCall.Add(gtx.Ops)\n")
	b.WriteString("\t\treturn v.cacheDims\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\tv.cacheOps.Reset()\n")
	b.WriteString("\tm := " + qop + ".Record(&v.cacheOps)\n")
	b.WriteString("\trec := gtx\n")
	b.WriteString("\trec.Ops = &v.cacheOps\n")
	b.WriteString("\t" + strings.ReplaceAll(body, "\n", "\n\t") + "\n")
	b.WriteString("\tv.cacheCall = m.Stop()\n")
	b.WriteString("\tv.cacheKey = k\n")
	b.WriteString("\tv.cached = true\n\n")
	b.WriteString("\tv.cacheCall.Add(gtx.Ops)\n")
	b.WriteString("\treturn v.cacheDims\n")
	b.WriteString("}\n")
	b.WriteString(g.renderKeyDecl())
	if g.usesVM {
		b.WriteString(g.bindCacheDecl())
	}
	return b.String(), nil
}

// q 登记并返回 path 的有效限定符（R14-B）。
//
// 首次调用时按默认名登记 import（默认名与目标包已有包级符号或已登记名冲突时，
// 取第一个空闲名 `pkg_2`、`pkg_3`……并强制写别名）；后续调用返回同一名字。
// 发射点一律经它取限定符并拼接引用，保证 import 块与实际引用同步——
// 不是对生成源做文本替换，用户字符串与事件实参天然不受影响。
func (g *generator) q(path, defaultName string) string {
	g.imports.add(path, defaultName)
	return g.imports.nameOf(path)
}

// vmTypeExpr 生成 ViewModel 参数的类型表达式，并按需登记 import。
//
// 同包（PkgDir 为空）→ Name，不需要 import。
// 其他包 → <pkg>.Name，需要 ModulePath 拼出 import 路径。
func (g *generator) vmTypeExpr() (string, error) {
	if g.vmRef.Name == "" {
		return "", fmt.Errorf("codegen: page is dynamic (binding or event) but no ViewModel type is available; add a ViewModel declaration")
	}
	// VM 实际所在包目录（相对模块根）：
	//   - 显式跨包：vmRef.PkgDir 非空，直接用它。
	//   - 同包声明（PkgDir==""）：VM 与**源 .gxml** 同包，源目录由 ViewModelPackageDir 给出。
	//     `--out-dir` 搬到别的包（OutputPackageDir）后，与产物已不同包，必须 import 源目录。
	vmPkgDir := g.vmRef.PkgDir
	if vmPkgDir == "" {
		vmPkgDir = g.opts.ViewModelPackageDir
	}
	normalize := func(p string) string { return strings.Trim(filepath.ToSlash(p), "/") }
	sameAsOutput := normalize(vmPkgDir) == normalize(g.opts.OutputPackageDir)
	if vmPkgDir == "" || sameAsOutput {
		// 与产物同包（或 VM 目录未知且无可区分）：裸类型名，不需要 import。
		return g.vmRef.Name, nil
	}
	if g.opts.ModulePath == "" {
		return "", fmt.Errorf(
			"codegen: ViewModel %s is in package %q but Options.ModulePath is empty",
			g.vmRef.Name, vmPkgDir)
	}
	alias := g.vmRef.PackageName
	if alias == "" && (g.vmRef.PkgDir == "" || normalize(g.vmRef.PkgDir) == normalize(g.opts.ViewModelPackageDir)) {
		alias = g.opts.ViewModelPackageName
	}
	if alias == "" {
		base := filepath.Base(vmPkgDir)
		if !isValidGoIdent(base) {
			return "", fmt.Errorf(
				"codegen: ViewModel 目录 %q 的目录名不是合法 Go 标识符且未提供包名，无法确定限定符",
				vmPkgDir)
		}
		alias = base
	}
	if !isValidGoIdent(alias) {
		return "", fmt.Errorf("codegen: ViewModel 包名 %q 不是合法 Go 标识符", alias)
	}
	// 强制写显式别名：Codegen 不读盘、不知目标包真实包名，显式写出 `alias "import/path"`
	// 使限定符与别名绑定一致（无论真实包名如何）。别名=真实包名（由调用方提供）时
	// 仍显式写出，纯为绑定确定性（与裸 import 语义等价）。
	importPath := g.opts.ModulePath
	if dir := normalize(vmPkgDir); dir != "." {
		importPath += "/" + dir
	}
	// Render must not rename an already emitted Gio qualifier. Pick the VM's
	// private alias before registering it, after body imports are collected.
	if existing, ok := g.imports.byPath[importPath]; ok {
		alias = existing
	} else {
		// Reserve generated names even when sibling outputs are not part of this batch.
		// Otherwise a warm sibling alias can conflict with a newly generated declaration.
		if (strings.HasPrefix(alias, "Goxml") || strings.HasPrefix(alias, "NewGoxml")) && strings.HasSuffix(alias, "View") ||
			strings.HasPrefix(alias, "goxmlRenderKey") || strings.HasPrefix(alias, "goxmlTextCache") ||
			strings.HasPrefix(alias, "goxmlAssets") {
			alias = "vm_" + alias
		}
		preferred := alias
		for suffix := 2; ; suffix++ {
			_, declared := g.opts.PackageNames[alias]
			used := declared || alias == "init" || types.Universe.Lookup(alias) != nil
			for _, n := range g.imports.byPath {
				if n == alias {
					used = true
					break
				}
			}
			if !used {
				break
			}
			alias = fmt.Sprintf("%s_vm%d", preferred, suffix)
		}
	}
	g.imports.addForcedAlias(importPath, alias)
	return alias + "." + g.vmRef.Name, nil
}

// isValidGoIdent validates import qualifiers, including Unicode package names.
