// importSet 按需收集 import，去重并按确定性别名规则渲染。
//
// 契约 §7 的要求：只为实际使用的符号生成、按路径去重、读取真实包名、
// 冲突时按路径字典序分配 `pkg`、`pkg_2`……、输出前经过 go/format。
type importSet struct {
	byPath map[string]string // 路径 → 优先包名
}

func newImportSet() *importSet {
	return &importSet{byPath: make(map[string]string)}
}

// add 记录一个需要的导入。path 为导入路径，pkgName 为该包的默认名。
func (s *importSet) add(path, pkgName string) {
	if _, ok := s.byPath[path]; !ok {
		s.byPath[path] = pkgName
	}
}

// render 生成 import 块。
//
// 排序规则：先按别名（空别名视为包名），再按路径——保证相同输入
// 产生逐字节相同的输出（契约 §6 确定性）。
func (s *importSet) render() string {
	if len(s.byPath) == 0 {
		return ""
	}

	type entry struct {
		path string
		name string // 最终使用的名字；等于默认包名时不写别名
		orig string
	}
	entries := make([]entry, 0, len(s.byPath))
	for p, n := range s.byPath {
		entries = append(entries, entry{path: p, name: n, orig: n})
	}

	// 按默认包名分组，检测冲突。
	used := make(map[string]int)
	byName := make(map[string][]int)
	for i, e := range entries {
		byName[e.orig] = append(byName[e.orig], i)
	}
	for name, idxs := range byName {
		if len(idxs) == 1 {
			used[name] = 1
			continue
		}
		// 冲突：按导入路径字典序分配 name、name_2、name_3……
		sort.Slice(idxs, func(a, b int) bool {
			return entries[idxs[a]].path < entries[idxs[b]].path
		})
		for k, i := range idxs {
			if k == 0 {
				entries[i].name = name
			} else {
				entries[i].name = fmt.Sprintf("%s_%d", name, k+1)
			}
		}
	}

	sort.Slice(entries, func(a, b int) bool {
		if entries[a].name != entries[b].name {
			return entries[a].name < entries[b].name
		}
		return entries[a].path < entries[b].path
	})

	var b strings.Builder
	b.WriteString("import (\n")
	for _, e := range entries {
		if e.name != e.orig {
			b.WriteString("\t" + e.name + " " + quote(e.path) + "\n")
		} else {
			b.WriteString("\t" + quote(e.path) + "\n")
		}
	}
	b.WriteString(")\n")
	return b.String()
}

// ============================================================================
// 符号推导（契约 §4.2）
// ============================================================================

// viewSymbol 由源路径推导视图类型名。
//
// 规则：取相对包目录的路径、逐段 PascalCase、非标识符字符转 `_`、
// 加 `Goxml` 前缀并以 `View` 结尾。
func viewSymbol(sourcePath string) (string, error) {
	p := strings.TrimSuffix(sourcePath, ".gxml")
	if p == "" {
		return "", fmt.Errorf("codegen: SourcePath %q yields an empty symbol", sourcePath)
	}
	// 去掉扩展名后按 / 与 \ 与 . 切段。
	segs := strings.FieldsFunc(p, func(r rune) bool {
		return r == '/' || r == '\\' || r == '.'
	})
	var b strings.Builder
	b.WriteString("Goxml")
	for _, s := range segs {
		b.WriteString(pascal(s))
	}
	b.WriteString("View")
	if !isGoIdent(b.String()) {
		return "", fmt.Errorf("codegen: SourcePath %q yields an invalid symbol %q", sourcePath, b.String())
	}
	return b.String(), nil
}

// pascal 把一段转为 PascalCase；非字母数字字符替换为 `_`。
func pascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z':
			if up {
				b.WriteRune(r - 'a' + 'A')
				up = false
			} else {
				b.WriteRune(r)
			}
		case r >= 'A' && r <= 'Z':
			if up {
				b.WriteRune(r)
				up = false
			} else {
				b.WriteRune(r)
			}
		case r >= '0' && r <= '9':
			b.WriteRune(r)
			up = false
		default:
			b.WriteByte('_')
			up = true // 分隔符之后重新大写
		}
	}
	return b.String()
}

// baseName 返回路径的最后一段，用于注释。
func baseName(p string) string {
	p = strings.ReplaceAll(p, "\\", "/")
	if i := strings.LastIndexByte(p, '/'); i >= 0 {
		return p[i+1:]
	}
	return p
}

// isGoIdent 报告是否为合法 Go 标识符。
func isGoIdent(s string) bool {
	if s == "" || s == "_" {
		return false
	}
	for i, r := range s {
		switch {
		case r == '_':
		case r >= 'a' && r <= 'z':
		case r >= 'A' && r <= 'Z':
		case r >= '0' && r <= '9':
			if i == 0 {
				return false
			}
		default:
			return false
		}
	}
	return true
}

// quote 生成 Go 字符串字面量。
func quote(s string) string {
	return fmt.Sprintf("%q", s)
}
