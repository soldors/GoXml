// importSet 按需收集 import，去重并按确定性别名规则渲染。
//
// 契约 §7 的要求：只为实际使用的符号生成、按路径去重、读取真实包名、
// 冲突时按路径字典序分配 `pkg`、`pkg_2`……、输出前经过 go/format。
//
// R14-B：导入名（文件块）不得与本包**任何**包级标识符同名（Go 规范：
// 同名标识符不能同时出现在文件块与包块）——目标包的用户 Go 文件可以合法
// 声明 `layout`/`material`/`op` 等。登记时按 taken 集合与已登记名取第一个
// 空闲名（`pkg`、`pkg_2`、`pkg_3`……，升序确定性），重命名即强制写出别名；
// 限定符的**实际引用**由发射点经 nameOf/g.q 取同一名字，不做文本替换。
type importSet struct {
	byPath map[string]string // 路径 → 有效限定符
	blanks map[string]bool   // 仅执行 init 的导入（如 image/png 注册解码器）
	forced map[string]bool   // 路径 → 是否强制写出别名（R4-A 片2 / R14-B 重命名）
	// taken 是目标包已有包级符号名（编排层传入的事实；nil = 无冲突）。
	taken map[string]bool
}

func newImportSet() *importSet {
	return &importSet{byPath: make(map[string]string), blanks: make(map[string]bool), forced: make(map[string]bool)}
}

// newImportSetWithTaken 构造带目标包已有符号事实的 importSet（R14-B）。
func newImportSetWithTaken(taken map[string]bool) *importSet {
	s := newImportSet()
	s.taken = taken
	return s
}

// freeName 返回 default、default_2、default_3……中第一个既不在 taken、
// 也不与已登记限定符重名的名字（升序，确定性）。
func (s *importSet) freeName(defaultName string) string {
	name := defaultName
	for suffix := 2; ; suffix++ {
		if !s.taken[name] && !s.nameRegistered(name) {
			return name
		}
		name = fmt.Sprintf("%s_%d", defaultName, suffix)
	}
}

// nameRegistered 报告某个限定符名是否已被其他路径占用。
func (s *importSet) nameRegistered(name string) bool {
	for _, n := range s.byPath {
		if n == name {
			return true
		}
	}
	return false
}

// add 记录一个需要的导入。path 为导入路径，pkgName 为该包的默认名。
// 默认名与 taken/已登记名冲突时改用第一个空闲名并强制写出别名（R14-B）。
func (s *importSet) add(path, pkgName string) {
	if _, ok := s.byPath[path]; ok {
		return
	}
	name := s.freeName(pkgName)
	s.byPath[path] = name
	if name != pkgName {
		s.forced[path] = true
	}
}

// addBlank 记录一个 `_ "path"` 导入（只为注册 init 副作用，如 image/png）。
func (s *importSet) addBlank(path string) {
	if s.blanks == nil {
		s.blanks = make(map[string]bool)
	}
	s.blanks[path] = true
}

// nameOf 返回路径的有效限定符（登记后的稳定名）。
func (s *importSet) nameOf(path string) string {
	return s.byPath[path]
}

// addForcedAlias 记录一个**强制使用别名**的导入（R4-A 片2）。
//
// 用途：`--out-dir` 跨包时，Codegen 只知道 VM 的**目录名**（`filepath.Base`），
// 但该目录内 Go 包名可能与目录名不同（包名≠目录名）。若只写裸路径 import，
// Go 会按真实包名（≠目录名）绑定默认名，而生成物却用目录名作限定符 → 不一致。
// Codegen 不读盘、不加载包，无法得知真实包名；因此显式写出 `dir "import/path"`，
// 使限定符与别名绑定一致（无论目标包真实包名是什么），编译期自洽。
func (s *importSet) addForcedAlias(path, alias string) {
	if _, ok := s.byPath[path]; !ok {
		s.byPath[path] = alias
	}
	s.forced[path] = true
}

// render 生成 import 块。
//
// 排序规则：先按别名（空别名视为包名），再按路径——保证相同输入
// 产生逐字节相同的输出（契约 §6 确定性）。blank 导入单独排序并置于最前。
func (s *importSet) render() string {
	if len(s.byPath) == 0 && len(s.blanks) == 0 {
		return ""
	}

	var blanks []string
	for p := range s.blanks {
		blanks = append(blanks, p)
	}
	sort.Strings(blanks)

	type entry struct {
		path string
		name string // 最终使用的名字；等于默认包名时不写别名
		orig string
	}
	entries := make([]entry, 0, len(s.byPath))
	for p, n := range s.byPath {
		entries = append(entries, entry{path: p, name: n, orig: n})
	}

	// 按默认包名分组，检测冲突。
	used := make(map[string]int)
	byName := make(map[string][]int)
	for i, e := range entries {
		byName[e.orig] = append(byName[e.orig], i)
	}
	for name, idxs := range byName {
		if len(idxs) == 1 {
			used[name] = 1
			continue
		}
		// 冲突：按导入路径字典序分配 name、name_2、name_3……
		sort.Slice(idxs, func(a, b int) bool {
			return entries[idxs[a]].path < entries[idxs[b]].path
		})
		for k, i := range idxs {
			if k == 0 {
				entries[i].name = name
			} else {
				entries[i].name = fmt.Sprintf("%s_%d", name, k+1)
			}
		}
	}

	sort.Slice(entries, func(a, b int) bool {
		if entries[a].name != entries[b].name {
			return entries[a].name < entries[b].name
		}
		return entries[a].path < entries[b].path
	})

	var b strings.Builder
	b.WriteString("import (\n")
	for _, p := range blanks {
		b.WriteString("\t_ " + quote(p) + "\n")
	}
	for _, e := range entries {
		if e.name != e.orig || s.forced[e.path] {
			b.WriteString("\t" + e.name + " " + quote(e.path) + "\n")
		} else {
			b.WriteString("\t" + quote(e.path) + "\n")
		}
	}
	b.WriteString(")\n")
	return b.String()
}

