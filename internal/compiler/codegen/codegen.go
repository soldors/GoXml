// 符号推导（契约 §4.2）
// ============================================================================

// viewSymbol 由源路径推导视图类型名。
//
// 规则：取相对包目录的路径、逐段 PascalCase、非标识符字符转 `_`、
// 加 `Goxml` 前缀并以 `View` 结尾。
func viewSymbol(sourcePath string) (string, error) {
	p := strings.TrimSuffix(sourcePath, ".gxml")
	if p == "" {
		return "", fmt.Errorf("codegen: SourcePath %q yields an empty symbol", sourcePath)
	}
	// 去掉扩展名后按 / 与 \ 与 . 切段。
	segs := strings.FieldsFunc(p, func(r rune) bool {
		return r == '/' || r == '\\' || r == '.'
	})
	var b strings.Builder
	b.WriteString("Goxml")
	for _, s := range segs {
		b.WriteString(pascal(s))
	}
	b.WriteString("View")
	if !isGoIdent(b.String()) {
		return "", fmt.Errorf("codegen: SourcePath %q yields an invalid symbol %q", sourcePath, b.String())
	}
	return b.String(), nil
}

// pascal 把一段转为 PascalCase；非字母数字字符替换为 `_`。
func pascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z':
			if up {
				b.WriteRune(r - 'a' + 'A')
				up = false
			} else {
				b.WriteRune(r)
			}
		case r >= 'A' && r <= 'Z':
			if up {
				b.WriteRune(r)
				up = false
			} else {
				b.WriteRune(r)
			}
		case r >= '0' && r <= '9':
			b.WriteRune(r)
			up = false
		default:
			b.WriteByte('_')
			up = true // 分隔符之后重新大写
		}
	}
	return b.String()
}

// baseName 返回路径的最后一段，用于注释。
func baseName(p string) string {
	p = strings.ReplaceAll(p, "\\", "/")
	if i := strings.LastIndexByte(p, '/'); i >= 0 {
		return p[i+1:]
	}
	return p
}

// isGoIdent 报告是否为合法 Go 标识符。
func isGoIdent(s string) bool {
	if s == "" || s == "_" {
		return false
	}
	for i, r := range s {
		switch {
		case r == '_':
		case r >= 'a' && r <= 'z':
		case r >= 'A' && r <= 'Z':
		case r >= '0' && r <= '9':
			if i == 0 {
				return false
			}
		default:
			return false
		}
	}
	return true
}

// quote 生成 Go 字符串字面量。
func quote(s string) string {
	return fmt.Sprintf("%q", s)
}

// vmTypeExprStr 返回构造函数参数的 ViewModel 类型表达式。
//
// 前提：usesVM 为 true 且 vmTypeExpr 已在 import 阶段成功执行。
// 该阶段失败时 Generate 已返回错误，不会走到这里；
// 万一走到，返回裸类型名让编译错误显式暴露而非静默。
func (g *generator) vmTypeExprStr() string {
	t, err := g.vmTypeExpr()
	if err != nil {
		// 构造函数生成阶段无法失败（imports 仍需登记），
		// 这里吞掉错误会让 Generate 返回错误（vmTypeExpr 已登记失败原因）。
		// 为安全起见返回类型名，让编译错误显式暴露而不是静默。
		return g.vmRef.Name
	}
	return t
}
