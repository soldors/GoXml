// viewSymbol 由源路径推导视图类型名。
//
// 规则：取相对包目录的路径、逐段 PascalCase、非标识符字符转 `_`、
// 加 `Goxml` 前缀并以 `View` 结尾。
func viewSymbol(sourcePath string) (string, error) {
	p := strings.TrimSuffix(sourcePath, ".gxml")
	if p == "" {
		return "", fmt.Errorf("codegen: SourcePath %q yields an empty symbol", sourcePath)
	}
	// 去掉扩展名后按 / 与 \ 与 . 切段。
	segs := strings.FieldsFunc(p, func(r rune) bool {
		return r == '/' || r == '\\' || r == '.'
	})
	var b strings.Builder
	b.WriteString("Goxml")
	for _, s := range segs {
		b.WriteString(pascal(s))
	}
	b.WriteString("View")
	if !isGoIdent(b.String()) {
		return "", fmt.Errorf("codegen: SourcePath %q yields an invalid symbol %q", sourcePath, b.String())
	}
	return b.String(), nil
}

// pascal 把一段转为 PascalCase；非字母数字字符替换为 `_`。
func pascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z':
			if up {
				b.WriteRune(r - 'a' + 'A')
				up = false
			} else {
				b.WriteRune(r)
			}
		case r >= 'A' && r <= 'Z':
			if up {
				b.WriteRune(r)
				up = false
			} else {
				b.WriteRune(r)
			}
		case r >= '0' && r <= '9':
			b.WriteRune(r)
			up = false
		default:
			b.WriteByte('_')
			up = true // 分隔符之后重新大写
		}
	}
	return b.String()
}

// baseName 返回路径的最后一段，用于注释。
func baseName(p string) string {
	p = strings.ReplaceAll(p, "\\", "/")
	if i := strings.LastIndexByte(p, '/'); i >= 0 {
		return p[i+1:]
	}
	return p
}

// isGoIdent 报告是否为合法 Go 标识符。
func isGoIdent(s string) bool {
	if s == "" || s == "_" {
		return false
	}
	for i, r := range s {
		switch {
		case r == '_':
		case r >= 'a' && r <= 'z':
		case r >= 'A' && r <= 'Z':
		case r >= '0' && r <= '9':
			if i == 0 {
				return false
			}
		default:
			return false
		}
	}
	return true
}

// quote 生成 Go 字符串字面量。
func quote(s string) string {
	return fmt.Sprintf("%q", s)
}

// vmTypeExprStr 返回构造函数参数的 ViewModel 类型表达式。
//
// 前提：usesVM 为 true 且 vmTypeExpr 已在 import 阶段成功执行。
// 该阶段失败时 Generate 已返回错误，不会走到这里；
// 万一走到，返回裸类型名让编译错误显式暴露而非静默。
func (g *generator) vmTypeExprStr() string {
	t, err := g.vmTypeExpr()
	if err != nil {
		// 构造函数生成阶段无法失败（imports 仍需登记），
		// 这里吞掉错误会让 Generate 返回错误（vmTypeExpr 已登记失败原因）。
		// 为安全起见返回类型名，让编译错误显式暴露而不是静默。
		return g.vmRef.Name
	}
	return t
}

// registerRowClick 把循环内按钮的事件登记到所属 <For> 的行状态池。
//
// 同一 <For> 内的多个按钮共享一个池与一份轮询循环。
func (g *generator) registerRowClick(rf analyzer.ResolvedFor, method, args, keyExpr string) int {
	inExpr, err := pathExpr(rf.In, "v.vm", "<For In>")
	if err != nil {
		// In 已在 For 展开时用过一次；到这里失败说明事实被破坏。
		panic("codegen: <For In> path failed on second use: " + err.Error())
	}
	// **每按钮一池**：同一行的两个按钮必须各自持有独立的 Clickable。
	// 若共享一个 Clickable，两个按钮的悬停/按下状态会互相串，
	// 且点击只会命中声明顺序里的第一个处理器（实测确认）。
	g.rowClicks = append(g.rowClicks, rowClickSlot{
		inExpr:     inExpr,
		keyExpr:    keyExpr,
		keyType:    rf.Key.Type,
		each:       rf.Each,
		index:      rf.Index,
		method:     method,
		args:       args,
		fieldIndex: len(g.rowClicks),
		guards:     append([]guardCond(nil), g.guards...),
	})
	return len(g.rowClicks) - 1
}

// pollCode 生成一个行状态池的顶部轮询块（<For> 列表契约 §5）。
//
// 关键：遍历的是**数据源本身**（与渲染同源同序）；Key 与实参都在
// 轮询变量 rowItem 上求值——渲染期变量是 item，两者语义一致但作用域不同。
func (s rowClickSlot) pollCode() string {
	var b strings.Builder
	b.WriteString("\t{\n")
	b.WriteString("\t\trowItems := " + s.inExpr + "\n")
	b.WriteString("\t\tfor _, rowItem := range rowItems {\n")
	b.WriteString("\t\t\trowItem := rowItem\n")
	if gd := s.guardRef(); gd != "" {
		b.WriteString("\t\t\tif " + gd + " {\n")
	}
	ind := "\t\t\t"
	if s.guardRef() != "" {
		ind = "\t\t\t\t"
	}
	b.WriteString(ind + fmt.Sprintf("if c := v.rowClicks%d[%s]; c != nil {\n", s.fieldIndex, s.keyRef()))
	b.WriteString(ind + "\tfor c.Clicked(gtx) {\n")
	b.WriteString(ind + "\t\tv.vm." + s.method + "(" + s.rewriteRoot(s.args) + ")\n")
	b.WriteString(ind + "\t\tgtx.Execute(op.InvalidateCmd{})\n")
	b.WriteString(ind + "\t}\n")
	b.WriteString(ind + "}\n")
	if s.guardRef() != "" {
		b.WriteString("\t\t\t}\n")
	}
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	return b.String()
}

// keyRef 把 Key 表达式改写到轮询变量 rowItem 上（每段路径根名替换）。
func (s rowClickSlot) keyRef() string {
	return s.rewriteRoot(s.keyExpr)
}

// rewriteRoot 把表达式里以循环变量（item）为根的路径改写为 rowItem。
//
// 渲染期与轮询期是两个作用域，变量名不同但数据相同——同一份 items 的
// 同一个元素。改写是纯文本的根段替换，安全边界：表达式由本文件生成，
// 根名必为 Each 名。
func (s rowClickSlot) rewriteRoot(expr string) string {
	if expr == "" || s.each == "" {
		return expr
	}
	if expr == s.each {
		return "rowItem"
	}
	if strings.HasPrefix(expr, s.each+".") {
		return "rowItem." + expr[len(s.each)+1:]
	}
	// 复合实参（如 "f(item.ID)" 不会出现；逗号分隔的多实参）：
	// 逐段替换每个以 each. 开头的路径段。
	parts := strings.Split(expr, ", ")
	for i, p := range parts {
		parts[i] = s.rewriteSingle(p)
	}
	return strings.Join(parts, ", ")
}

// rewriteSingle 改写单个实参表达式的根。
func (s rowClickSlot) rewriteSingle(expr string) string {
	if expr == s.each {
		return "rowItem"
	}
	if strings.HasPrefix(expr, s.each+".") {
		return "rowItem." + expr[len(s.each)+1:]
	}
	return expr
}

// cleanupCode 生成键清理块（<For> 列表契约 §4）。
//
// 行删除后其 Key 残留在池里会造成无界增长；清理放在轮询之后、渲染之前。
// 快速跳过条件保证未发生删除的稳定帧零分配。
func (s rowClickSlot) cleanupCode() string {
	var b strings.Builder
	b.WriteString("\t{\n")
	b.WriteString("\t\trowItems := " + s.inExpr + "\n")
	if gd := s.scopeGuardRef(); gd != "" {
		// 外层分支隐藏时**不清理**：条件恢复后行状态仍可用。
		// 行级条件不参与——清理是键集合的函数，与单行是否渲染无关。
		b.WriteString("\t\tif " + gd + " && ")
	} else {
		b.WriteString("\t\tif ")
	}
	b.WriteString(fmt.Sprintf("len(v.rowClicks%d) > len(rowItems) {\n", s.fieldIndex))
	b.WriteString("\t\t\tkeep := make(map[" + s.keyTypeExprMust() + "]struct{}, len(rowItems))\n")
	b.WriteString("\t\t\tfor _, rowItem := range rowItems {\n")
	b.WriteString("\t\t\t\tkeep[" + s.keyRef() + "] = struct{}{}\n")
	b.WriteString("\t\t\t}\n")
	b.WriteString(fmt.Sprintf("\t\t\tfor k := range v.rowClicks%d {\n", s.fieldIndex))
	b.WriteString(fmt.Sprintf("\t\t\t\tif _, ok := keep[k]; !ok {\n\t\t\t\t\tdelete(v.rowClicks%d, k)\n\t\t\t\t}\n", s.fieldIndex))
	b.WriteString("\t\t\t}\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	return b.String()
}

// keyTypeExprMust 是 keyTypeExpr 的无错版本（登记时已校验过可比性）。
func (s rowClickSlot) keyTypeExprMust() string {
	t, err := s.keyTypeExpr()
	if err != nil {
		panic("codegen: row key type was validated at registration but failed here: " + err.Error())
	}
	return t
}

// emitIfChildren 把一个 <If> 内联展开为「条件 + 分支 append」的语句块。
//
// 结构（If 输出契约 §1/§5）：
//
//	{
//		cond := <condition>
//		if cond {
//			children = append(children, ...)   // Then
//		} else {
//			children = append(children, ...)   // Else（可无）
//		}
//	}
//
// Then/Else 自身不产生节点——它们是分组标记。
func (g *generator) emitIfChildren(b *strings.Builder, n *contracts.NodeIR, indent string) error {
	if n.If == nil {
		return fmt.Errorf("codegen: <If> has no If clause; the analyzer result is inconsistent")
	}
	condExpr, err := g.ifConditionExpr(n)
	if err != nil {
		return err
	}
	if len(n.If.Then) == 0 {
		// Parser 保证 <Then> 存在；空 Then 是合法但无意义的写法。
		// 不报错——只要求不生成坏代码。
	}

	b.WriteString(indent + "{\n")
	b.WriteString(indent + "\tcond := " + condExpr + "\n")
	b.WriteString(indent + "\tif cond {\n")

	// Then 分支：轮询守卫即条件本身。
	prev := g.guards
	g.guards = append(prev, guardCond{expr: condExpr, rowScoped: g.inFor})
	err = g.emitBranchAppends(b, n.If.Then, indent+"\t\t")
	g.guards = prev
	if err != nil {
		return err
	}

	if len(n.If.Else) > 0 {
		b.WriteString(indent + "\t} else {\n")
		// Else 分支：守卫是条件的否定（读同一表达式，同一帧内等价）。
		g.guards = append(prev, guardCond{expr: "!(" + condExpr + ")", rowScoped: g.inFor})
		err = g.emitBranchAppends(b, n.If.Else, indent+"\t\t")
		g.guards = prev
		if err != nil {
			return err
		}
	}
	b.WriteString(indent + "\t}\n")
	b.WriteString(indent + "}\n")
	return nil
}

// guardCond 是一条轮询守卫条件。
type guardCond struct {
	// expr 是条件的 Go 表达式（渲染作用域）。
	expr string
	// rowScoped 表示该条件在循环作用域内求值（含循环变量）。
	//
	// 行级条件只能逐行守卫轮询，**不能**用于整池清理——清理是
	// 键集合的函数，与某一行是否渲染无关（否则 rowItem 在
	// 循环外不可见，生成的代码无法编译）。
	rowScoped bool
}

// guardExpr 把若干守卫条件合并为单个 Go 表达式；无守卫返回空串。
func guardExpr(guards []guardCond) string {
	if len(guards) == 0 {
		return ""
	}
	out := make([]string, 0, len(guards))
	for _, gd := range guards {
		out = append(out, gd.expr)
	}
	return strings.Join(out, " && ")
}

// emitBranchAppends 生成一个分支内每个子节点的 append 语句。
func (g *generator) emitBranchAppends(b *strings.Builder, nodes []*contracts.NodeIR, indent string) error {
	for _, c := range nodes {
		// 分支内再嵌套 For/If 也走内联展开（契约 §4.3）。
		if isForNode(c) {
			if err := g.emitForChildren(b, c, indent); err != nil {
				return err
			}
			continue
		}
		if isIfNode(c) {
			if err := g.emitIfChildren(b, c, indent); err != nil {
				return err
			}
			continue
		}
		inner, err := g.nodeExpr(c)
		if err != nil {
			return err
		}
		b.WriteString(indent + "children = append(children, layout.Rigid(func(gtx layout.Context) layout.Dimensions {\n")
		b.WriteString(indent + "\treturn " + inner + "\n")
		b.WriteString(indent + "}))\n")
	}
	return nil
}

// ifConditionExpr 渲染 <If Condition> 的布尔表达式。
//
// 事实来源：Analyzer 已把 Condition 解析为 ResolvedAttr{Target: PropBool}，
// 因此直接复用绑定取值渲染（If 输出契约 §0.1）。
func (g *generator) ifConditionExpr(n *contracts.NodeIR) (string, error) {
	ra, ok := lookupAttr(n, "Condition", g.facts)
	if !ok || ra.Path == nil {
		return "", fmt.Errorf("codegen: <If> has no resolved Condition path; the analyzer result is inconsistent")
	}
	g.usesVM = true
	return pathExpr(ra.Path, "v.vm", "<If Condition>")
}

// guardRef 把该池的守卫条件改写到轮询变量 rowItem 上（轮询用）。
func (s rowClickSlot) guardRef() string {
	if len(s.guards) == 0 {
		return ""
	}
	out := make([]string, 0, len(s.guards))
	for _, gd := range s.guards {
		out = append(out, s.rewriteRoot(gd.expr))
	}
	return strings.Join(out, " && ")
}

// scopeGuardRef 只保留**非行级**守卫（清理用）。
func (s rowClickSlot) scopeGuardRef() string {
	out := make([]string, 0, len(s.guards))
	for _, gd := range s.guards {
		if gd.rowScoped {
			continue
		}
		out = append(out, gd.expr)
	}
	return strings.Join(out, " && ")
}
