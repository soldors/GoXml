// Package codegen 把 Analyzer 验证过的语义 IR 生成为 Go 源码。
//
// 职责边界（契约 §2.1–§2.3、§4.4）：
//   - 入口只接受 *analyzer.VerifiedDoc，未验证的 IR 在类型层面传不进来；
//   - 只返回 []byte，**不写文件**——写入与原子替换由编排层负责；
//   - 只消费已验证的事实，不重新推导布局语义、不重新判断兼容性。
//
// 当前实现范围：静态 Page/Text 缓存、Column/Row 多子节点布局、
// <Text> 字段/零参方法绑定读取及绑定节点显示缓存。
// 事件、If/For、交互控件与 Grid 尚未实现，见输出契约 §4.6。
package codegen

import (
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strings"

	"github.com/goxml/goxml/contracts"
	"github.com/goxml/goxml/internal/compiler/analyzer"
)

// Options 是生成所需的全部外部输入。
//
// Codegen 不读磁盘、不加载包：包名与源路径由编排层确定后传入（契约 §4.4）。
type Options struct {
	// PackageName 是生成文件的 package 子句。
	//
	// 由调用方按契约 §4.1 从目标目录的 Go package 解析得到。
	// Codegen 不推导、不猜测；为空时生成失败。
	PackageName string
	// ModulePath 是 go.mod 的 module 路径。
	//
	// 仅当 ViewModel 位于**其他包**时需要：用于拼出该包的 import 路径。
	// 同包 ViewModel（或纯静态页面）不需要设置。
	ModulePath string

	// SourcePath 是 .gxml 相对目标包目录的路径（如 "ui/dashboard.gxml"），
	// 用于按契约 §4.2 推导符号名。
	SourcePath string
}

// goxmlVersion 是保护头里的语言版本字段（契约 §3.1）。
//
// 它是 GXML 语言版本，不是编译器构建版本——同一语言版本的不同构建
// 必须产生逐字节相同的保护头（契约 §6 确定性）。
const goxmlVersion = "1"

// headerFor 生成文件的保护头（契约 §3.1，三行格式）：
//
//	// Code generated by goxml. DO NOT EDIT.
//	// Source: ui/dashboard.gxml
//	// Goxml-Version: 1
//
// Source 使用项目相对路径，统一 `/` 分隔；禁止绝对路径、机器名与时间戳。
// 首行必须匹配 Go 工具链的 `^// Code generated .* DO NOT EDIT\.$`。
func headerFor(sourcePath string) string {
	return "// Code generated by goxml. DO NOT EDIT.\n" +
		"// Source: " + normalizeSourcePath(sourcePath) + "\n" +
		"// Goxml-Version: " + goxmlVersion + "\n\n"
}

// normalizeSourcePath 把 Source 路径规范为契约 §3.1 要求的形态：
// 统一 `/` 分隔。路径的相对性与边界由调用方（Pipeline/CLI）保证；
// 这里只做展示形态的规范化，避免同一输入因平台分隔符差异而输出不同。
func normalizeSourcePath(p string) string {
	return strings.ReplaceAll(p, "\\", "/")
}

// HasProtectedHeader 报告一段源码是否带**本工具**的保护头。
//
// 用途：`--clean` 的所有权判定（契约 §10）——只删除「Manifest 登记
// 且仍带保护头」的文件。判定与 headerFor 使用**同一规范**：
// 逐字节比较三行，不做宽松子串匹配。
//
// 判定规则：
//   - 第 1 行逐字节等于 `// Code generated by goxml. DO NOT EDIT.`
//   - 第 2 行以 `// Source: ` 开头（路径内容不作校验——所有权由
//     Manifest 登记 + 本头共同证明，路径本身不参与判定）
//   - 第 3 行逐字节等于 `// Goxml-Version: 1`
func HasProtectedHeader(src []byte) bool {
	lines := strings.Split(string(src), "\n")
	if len(lines) < 3 {
		return false
	}
	if lines[0] != "// Code generated by goxml. DO NOT EDIT." {
		return false
	}
	if !strings.HasPrefix(lines[1], "// Source: ") {
		return false
	}
	return lines[2] == "// Goxml-Version: "+goxmlVersion
}

// Generate 生成单个 Go 源文件。
//
// 成功返回已格式化的源码；失败返回 error 且**不返回部分代码**——
// 部分产物可能被调用方误写出去，破坏「失败不覆盖旧文件」的保证（契约 §2.3）。
func Generate(v *analyzer.VerifiedDoc, opts Options) ([]byte, error) {
	if v == nil {
		return nil, fmt.Errorf("codegen: nil VerifiedDoc")
	}
	if v.Document() == nil {
		return nil, fmt.Errorf("codegen: VerifiedDoc has no document")
	}
	if opts.PackageName == "" {
		return nil, fmt.Errorf("codegen: Options.PackageName is required; it is not derived from the source path")
	}
	if !isGoIdent(opts.PackageName) {
		return nil, fmt.Errorf("codegen: PackageName %q is not a valid Go identifier", opts.PackageName)
	}
	if opts.SourcePath == "" {
		return nil, fmt.Errorf("codegen: Options.SourcePath is required to derive the view symbol")
	}

	view, err := viewSymbol(opts.SourcePath)
	if err != nil {
		return nil, err
	}

	vmRef, _ := v.ViewModel()

	g := &generator{
		opts:    opts,
		view:    view,
		imports: newImportSet(),
		facts:   v.Facts(),
		vmRef:   vmRef,
	}

	// 页面是生成的主体。没有 Page 时不应走到这里——Parser 保证存在，
	// 但 VerifiedDoc 不变量若被破坏，这里必须明确失败而不是产出空文件。
	page := v.Document().Page
	if page == nil {
		return nil, fmt.Errorf("codegen: document has no <Page>; nothing to generate")
	}

	body, err := g.page(page)
	if err != nil {
		return nil, err
	}

	src, err := g.assemble(body)
	if err != nil {
		return nil, err
	}
	out, err := format.Source([]byte(src))
	if err != nil {
		// 格式化失败说明生成器有缺陷。返回错误并附上原文，便于定位，
		// 但绝不把未格式化的源码当作成功结果返回。
		return nil, fmt.Errorf("codegen: generated source does not parse: %w\n--- source ---\n%s", err, src)
	}
	return out, nil
}

// generator 是单次生成的状态。
type generator struct {
	opts    Options
	view    string
	imports *importSet
	// facts 是 Analyzer 已验证的语义事实。绑定路径与目标类型都取自此处，
	// Codegen **不得**自行解析绑定路径。
	facts *analyzer.Facts
	// usesVM 表示页面**动态**（含绑定或事件）：需要 vm 参数，且**不得**整页静态固化。
	usesVM bool
	// opsName 是顶层容器布局所用的 Ops 变量名。
	//
	// 静态页面为 "rec"（录制到 cacheOps）；含绑定页面为 "gtx"（直接布局到帧）。
	opsName string
	// vmRef 是 ViewModel 类型引用（不含 go/types）。
	vmRef analyzer.ViewModelRef
	// bindSlots 是页面中绑定 <Text> 的数量（用于生成显示缓存槽位）。
	bindSlots int
	// clickSlots 是页面中 <Button> 的数量（用于生成 widget.Clickable 字段）。
	clickSlots int
	// clicks 记录需要轮询的事件槽位（事件处理输出契约 §2）。
	clicks []clickSlot
	// inFor 表示当前正在生成 <For> 循环体内部。
	//
	// 循环体内**不得**分配显示缓存槽位：槽位是按节点分配的，
	// 每行复用同一槽位会互相覆盖（<For> 列表契约 §6.2）。
	inFor bool
	// rowClicks 汇总循环内需要行状态池的按钮（<For> 列表契约 §3）。
	rowClicks []rowClickSlot
	// currentFor 是当前正在生成的 <For> 节点（nodeExpr 没有祖先链，
	// 用生成时的作用域标记传递）。
	currentFor *contracts.NodeIR
	// guards 是当前所处的 <If> 分支条件（由外到内）。
	guards []guardCond
}

// clickSlot 是一个待轮询的控件状态槽位。
type clickSlot struct {
	// index 对应生成字段 click<index>。
	index int
	// method 是 ViewModel 上的方法名。
	method string
	// args 是已渲染的实参列表（逗号分隔，可为空）。
	//
	// 实参来自 Analyzer 的 ResolvedArg（事件处理输出契约 §5.4），
	// Codegen 只负责渲染语法。
	args string
	// inFor 表示该按钮位于 <For> 循环体内，行状态从池中取。
	inFor bool
	// keyExpr 是行状态的 Key 表达式（inFor 时有效），如 item.ID。
	keyExpr string
	// poolIndex 是所属行状态池的编号（inFor 时有效）。
	poolIndex int
	// guards 是轮询时必须同时成立的条件表达式（If 输出契约 §2.2）。
	// 由外到内排列；空表示无条件。
	guards []guardCond
}

// rowClickSlot 记录一个 <For> 的行状态池（<For> 列表契约 §3）。
//
// 一个 <For> 一个池（而不是每按钮一个）：同一行的多个按钮共享同一份
// 行身份，池的生命周期也由同一把清理逻辑管理。
type rowClickSlot struct {
	// inExpr 是数据源表达式（如 v.vm.Items），轮询与渲染共用。
	inExpr string
	// keyExpr 是 Key 表达式（如 item.ID）。
	keyExpr string
	// keyType 是 Key 的类型信息（用于生成 map 的键类型）。
	keyType analyzer.TypeInfo
	// each 是循环变量名。
	each string
	// index 是索引变量名（可为空）。
	index string
	// method 是该行按钮的处理器方法名。
	method string
	// args 是已渲染的实参。
	args string
	// fieldIndex 是该池在生成结构体里的编号（rowClicks<N>）。
	fieldIndex int
	// guards 是轮询与清理时必须成立的条件（If 输出契约 §4.1）。
	guards []guardCond
}

// keyTypeExpr 渲染 map 的键类型；不可比较类型显式报错（契约 §3.2）。
func (s rowClickSlot) keyTypeExpr() (string, error) {
	switch s.keyType.Kind {
	case analyzer.ValueString, analyzer.ValueBool, analyzer.ValueInt,
		analyzer.ValueUint, analyzer.ValueFloat, analyzer.ValuePointer:
		return s.keyType.Display, nil
	case analyzer.ValueStruct:
		// 结构体的可比性取决于字段，Analyzer 的 Display 不够判；
		// 走到这里说明上游未拦截，显式拒绝而不是生成可能编译失败的代码。
		return "", fmt.Errorf(
			"codegen: <For> Key of struct type %q is not supported; use a comparable scalar key", s.keyType.Display)
	default:
		return "", fmt.Errorf(
			"codegen: <For> Key type %q is not comparable and cannot index row state", s.keyType.Display)
	}
}

// page 生成页面根节点的渲染体。
//
// `<Page>` 等价于无 Gap/Padding 的 `<Column>`（规范 §3.1），因此按垂直容器生成。
func (g *generator) page(n *contracts.NodeIR) (string, error) {
	// Parser 保证 <Page> 至少有一个渲染子节点（GXML-ROOT-001），
	// 因此这里不必再判空；若真为空是上游不变式被破坏。
	if len(n.Children) == 0 {
		return "", fmt.Errorf("codegen: <Page> has no children; Parser should have rejected this")
	}

	// 预扫描：先确定是否含绑定，因为 ops 与返回形态都取决于它。
	g.usesVM = hasDynamic(n)

	ops := "rec"
	if g.usesVM {
		// 含绑定：直接布局到帧 Ops，且**不**赋给 cacheDims
		// （没有静态缓存，也不得把动态结果固化）。
		ops = "gtx"
	}
	expr, err := g.containerExpr(n.Children, "layout.Vertical", ops)
	if err != nil {
		return "", err
	}
	if g.usesVM {
		return expr, nil
	}
	// 静态：录制发生在 cacheOps 上（rec），不是帧 Ops。
	return "v.cacheDims = " + expr, nil
}

// containerExpr 生成一个 Flex 容器的表达式（契约 §4.7.2）。
//
// 子节点顺序严格等于声明顺序；每个直接子节点一个 layout.Rigid。
//
// 含 <For> 时子项数编译期不可知，必须先运行时组装 `[]layout.FlexChild`
// （<For> 列表契约 §2：内联展开，不引入嵌套 Flex）。
func (g *generator) containerExpr(children []*contracts.NodeIR, axis, ops string) (string, error) {
	g.imports.add("gioui.org/layout", "layout")

	if hasForChild(children) || hasIfChild(children) {
		return g.dynamicContainerExpr(children, axis, ops)
	}

	var b strings.Builder
	b.WriteString("layout.Flex{Axis: " + axis + "}.Layout(" + ops)
	for _, c := range children {
		inner, err := g.nodeExpr(c)
		if err != nil {
			return "", err
		}
		b.WriteString(",\n\t\tlayout.Rigid(func(gtx layout.Context) layout.Dimensions {\n\t\t\treturn ")
		b.WriteString(inner)
		b.WriteString("\n\t\t})")
	}
	b.WriteString(")")
	return b.String(), nil
}

// dynamicContainerExpr 生成「运行时组装子项」的容器表达式。
//
// 形态是立即调用的闭包，因此仍是表达式，可直接放进既有 `return <expr>` 位置：
//
//	func() layout.Dimensions {
//		children := make([]layout.FlexChild, 0, <静态子项数>)
//		children = append(children, layout.Rigid(...))   // 静态子项
//		{ items := ...; for _, item := range items { ... } }  // <For> 内联展开
//		return layout.Flex{Axis: ...}.Layout(gtx, children...)
//	}()
func (g *generator) dynamicContainerExpr(children []*contracts.NodeIR, axis, ops string) (string, error) {
	// 初始容量取静态子项数；<For> 的项数编译期不可知，由 append 增长。
	static := 0
	for _, c := range children {
		if !isForNode(c) && !isIfNode(c) {
			static++
		}
	}

	var b strings.Builder
	b.WriteString("func() layout.Dimensions {\n")
	b.WriteString(fmt.Sprintf("\t\t\tchildren := make([]layout.FlexChild, 0, %d)\n", static))

	for _, c := range children {
		if isForNode(c) {
			if err := g.emitForChildren(&b, c, "\t\t\t"); err != nil {
				return "", err
			}
			continue
		}
		if isIfNode(c) {
			if err := g.emitIfChildren(&b, c, "\t\t\t"); err != nil {
				return "", err
			}
			continue
		}
		inner, err := g.nodeExpr(c)
		if err != nil {
			return "", err
		}
		b.WriteString("\t\t\tchildren = append(children, layout.Rigid(func(gtx layout.Context) layout.Dimensions {\n")
		b.WriteString("\t\t\t\treturn " + inner + "\n")
		b.WriteString("\t\t\t}))\n")
	}

	b.WriteString("\t\t\treturn layout.Flex{Axis: " + axis + "}.Layout(" + ops + ", children...)\n")
	b.WriteString("\t\t}()")
	return b.String(), nil
}

// emitForChildren 把一个 <For> 内联展开为「循环 + 逐项 append」的语句块。
//
// 关键一致性（<For> 列表契约 §5）：数据源只求值一次并存入局部变量 items，
// 供后续事件轮询与渲染共用——两处各写一遍取数表达式会在并发修改下串位。
func (g *generator) emitForChildren(b *strings.Builder, n *contracts.NodeIR, indent string) error {
	nf, ok := lookupFor(n, g.facts)
	if !ok {
		return fmt.Errorf("codegen: <%s> has no resolved for-clause facts; the analyzer result is inconsistent", n.Tag)
	}
	if nf.In == nil {
		return fmt.Errorf("codegen: <For> has no resolved In path")
	}
	if nf.Each == "" {
		return fmt.Errorf("codegen: <For> has no Each variable")
	}
	// 循环变量名不得与生成代码使用的标识符冲突（契约 §6.1）。
	// 静默覆盖会生成语法正确但语义错误的代码，因此显式报错。
	if err := checkLoopVarName(nf.Each); err != nil {
		return err
	}
	if nf.Index != "" {
		if err := checkLoopVarName(nf.Index); err != nil {
			return err
		}
		if nf.Index == nf.Each {
			return fmt.Errorf("codegen: <For> Each and Index must differ (both %q)", nf.Each)
		}
	}
	if len(n.Children) == 0 {
		return fmt.Errorf("codegen: <For> has no children")
	}

	inExpr, err := pathExpr(nf.In, "v.vm", "<For In>")
	if err != nil {
		return err
	}

	b.WriteString(indent + "{\n")
	b.WriteString(indent + "\titems := " + inExpr + "\n")
	// Index 变量只在循环体**真的引用**它时才生成。
	// Go 对 `for i, item := range` 中未使用的 i 会报 "declared and not used"，
	// 而 Index 是可选的，声明了却不引用是完全合法的写法。
	if nf.Index != "" && g.forVarUsed(n.Children, nf.Index) {
		b.WriteString(indent + "\tfor " + nf.Index + ", " + nf.Each + " := range items {\n")
	} else {
		b.WriteString(indent + "\tfor _, " + nf.Each + " := range items {\n")
	}
	// 显式遮蔽：闭包捕获的是**本轮**的循环变量。
	// （Go 1.22 起 range 变量本就每轮独立，这里显式写出来是为了让生成的
	// 代码在任何阅读者眼里都不依赖那个语言细节。）
	b.WriteString(indent + "\t\t" + nf.Each + " := " + nf.Each + "\n")

	// 循环体内不分配显示缓存槽位：槽位按节点分配，每行复用会互相覆盖
	// （<For> 列表契约 §6.2）。
	prevInFor := g.inFor
	prevFor := g.currentFor
	g.inFor = true
	g.currentFor = n
	for _, c := range n.Children {
		if isForNode(c) {
			g.inFor = prevInFor
			g.currentFor = prevFor
			return fmt.Errorf("codegen: nested <For> is not supported in this slice")
		}
		// 循环体里的 <If> 也要内联展开（If 输出契约 §4.1）。
		if isIfNode(c) {
			if err := g.emitIfChildren(b, c, indent+"\t\t"); err != nil {
				g.inFor = prevInFor
				g.currentFor = prevFor
				return err
			}
			continue
		}
		inner, err := g.nodeExpr(c)
		if err != nil {
			g.inFor = prevInFor
			g.currentFor = prevFor
			return err
		}
		b.WriteString(indent + "\t\tchildren = append(children, layout.Rigid(func(gtx layout.Context) layout.Dimensions {\n")
		b.WriteString(indent + "\t\t\treturn " + inner + "\n")
		b.WriteString(indent + "\t\t}))\n")
	}
	g.inFor = prevInFor
	g.currentFor = prevFor

	b.WriteString(indent + "\t}\n")
	b.WriteString(indent + "}\n")
	return nil
}

// isForNode 报告节点是否为 <For> 结构节点。
func isForNode(n *contracts.NodeIR) bool {
	if n == nil {
		return false
	}
	return n.Kind == contracts.KindFor || n.For != nil
}

// hasForChild 报告直接子节点中是否含 <For>。
func hasForChild(children []*contracts.NodeIR) bool {
	for _, c := range children {
		if isForNode(c) {
			return true
		}
	}
	return false
}

// isIfNode 报告节点是否为 <If> 结构节点。
func isIfNode(n *contracts.NodeIR) bool {
	if n == nil {
		return false
	}
	return n.Kind == contracts.KindIf || n.If != nil
}

// hasIfChild 报告直接子节点中是否含 <If>。
func hasIfChild(children []*contracts.NodeIR) bool {
	for _, c := range children {
		if isIfNode(c) {
			return true
		}
	}
	return false
}

// checkLoopVarName 拒绝与生成代码标识符冲突的循环变量名。
func checkLoopVarName(name string) error {
	switch name {
	case "v", "th", "gtx", "items", "children", "rec", "k", "ops":
		return fmt.Errorf(
			"codegen: <For> variable %q collides with an identifier used by generated code; rename it", name)
	}
	return nil
}

// nodeExpr 生成单个节点的渲染**表达式**（返回 layout.Dimensions）。
//
// 与语句形态的区别：闭包内必须是表达式，不能是赋值语句。
func (g *generator) nodeExpr(n *contracts.NodeIR) (string, error) {
	if n == nil {
		return "", fmt.Errorf("codegen: nil node")
	}

	switch n.Tag {
	case "Text":
		if len(n.Events) > 0 {
			return "", fmt.Errorf("codegen: <Text> events are not supported in this slice")
		}
		if len(n.Children) > 0 {
			return "", fmt.Errorf("codegen: <Text> must not have children")
		}
		g.imports.add("gioui.org/widget/material", "material")

		// 优先按绑定处理。绑定信息**只**来自 Facts；查不到就报错，
		// 绝不回退成字符串常量（那会把 "{Title}" 当成字面文本）。
		if ra, ok := lookupAttr(n, "Value", g.facts); ok && ra.Path != nil {
			expr, err := bindingExpr(ra, "v.vm")
			if err != nil {
				return "", err
			}
			g.usesVM = true
			// 循环体内**不**分配显示缓存槽位：槽位按节点分配，
			// N 行复用同一槽位会在同一帧内互相覆写，命中率恒为 0
			// （<For> 列表契约 §6.2）。直接布局。
			if g.inFor {
				g.imports.add("gioui.org/widget/material", "material")
				return fmt.Sprintf("material.Body1(th, %s).Layout(gtx)", expr), nil
			}
			// 分配显示缓存槽位；闭包内通过 v.n<i> 读写缓存。
			slot := g.bindSlots
			g.bindSlots++
			return fmt.Sprintf(
				"v.bindText(gtx, th, %d, %s)", slot, expr), nil
		}

		value, ok := staticAttr(n, "Value")
		if !ok {
			return "", fmt.Errorf(
				"codegen: <Text> needs a static Value; data binding is not supported in this slice")
		}
		return fmt.Sprintf("material.Body1(th, %s).Layout(gtx)", quote(value)), nil

	case "Button":
		return g.buttonExpr(n)

	case "Column":
		// 嵌套容器在闭包内，使用闭包的 gtx（其 Ops 已是帧/cacheOps）。
		return g.containerExpr(n.Children, "layout.Vertical", "gtx")

	case "Row":
		return g.containerExpr(n.Children, "layout.Horizontal", "gtx")

	default:
		return "", fmt.Errorf("codegen: <%s> is not supported in this slice", n.Tag)
	}
}

// buttonExpr 生成 <Button> 的渲染表达式（事件处理输出契约 §6）。
//
// MVP 范围：
//   - 事件：仅无参 Click；
//   - 属性：Text（静态或绑定）；Enabled 明确报错。
func (g *generator) buttonExpr(n *contracts.NodeIR) (string, error) {
	if len(n.Children) > 0 {
		return "", fmt.Errorf("codegen: <Button> must not have children")
	}
	g.imports.add("gioui.org/widget/material", "material")
	g.imports.add("gioui.org/widget", "widget")

	// Enabled 需要 gtx.Disabled() 语义，不在 MVP 范围。
	// 明确报错而非静默忽略——忽略会让「禁用」变成可点击。
	if _, ok := staticAttr(n, "Enabled"); ok {
		return "", fmt.Errorf("codegen: <Button Enabled> is not supported in this slice")
	}
	for _, a := range n.Attrs {
		if a.Name == "Enabled" {
			return "", fmt.Errorf("codegen: <Button Enabled> is not supported in this slice")
		}
	}

	// 控件状态槽位：每个 Button 一个，跨帧稳定（契约 §1）。
	// 循环内的按钮改用行状态池，idx 仍分配但不用于绘制。
	idx := g.clickSlots
	g.clickSlots++
	// rowKey 是行状态的 Key 表达式（g.inFor 时有效），如 item.ID。
	// rowPool 是所属池编号。
	var rowKey string
	rowPool := -1

	// 事件校验（MVP：仅无参 Click）。
	for _, ev := range n.Events {
		if ev.Name != "Click" {
			return "", fmt.Errorf(
				"codegen: <Button> event %q is not supported in this slice; only Click", ev.Name)
		}
		if ev.Method == "" {
			return "", fmt.Errorf("codegen: Click has no method name")
		}
		// 实参**只**取自已验证的 Facts，不回读原始文本。
		resolved, ok := lookupEvent(n, ev.Name, g.facts)
		if !ok {
			return "", fmt.Errorf(
				"codegen: event %q on <%s> has no resolved facts; the analyzer result is inconsistent",
				ev.Name, n.Tag)
		}
		args, err := g.renderEventArgs(resolved.CallArgs)
		if err != nil {
			return "", err
		}
		slot := clickSlot{index: idx, method: ev.Method, args: args, guards: append([]guardCond(nil), g.guards...)}
		// 循环内的按钮：**必须**有 Key（<For> 列表契约 §3.1——Parser 的
		// SCOPE-003 已强制，这里做防御性二次校验），行状态从池取。
		if g.inFor {
			// Key 必须存在（<For> 列表契约 §3.1——Parser 的 SCOPE-003 已强制，
			// 这里做防御性二次校验，防上游放行）。
			if g.currentFor == nil || g.currentFor.For == nil || !g.currentFor.For.HasKey {
				return "", fmt.Errorf("codegen: <Button> inside <For> requires a Key on <For> to keep per-row state stable")
			}
			rf, ok := lookupFor(g.currentFor, g.facts)
			if !ok || rf.Key == nil {
				return "", fmt.Errorf("codegen: <For> Key is required for row state but no resolved key path is available")
			}
			keyExpr, err := pathExpr(rf.Key, "v.vm", "<For Key>")
			if err != nil {
				return "", err
			}
			slot.inFor = true
			slot.keyExpr = keyExpr
			rowKey = keyExpr
			slot.poolIndex = g.registerRowClick(rf, ev.Method, args, keyExpr)
			rowPool = slot.poolIndex
		}
		g.clicks = append(g.clicks, slot)
	}

	// 标签：绑定优先（经 Facts），否则静态字面量；缺省为空标签（Schema 非必选）。
	label := `""`
	if ra, ok := lookupAttr(n, "Text", g.facts); ok && ra.Path != nil {
		expr, err := bindingExpr(ra, "v.vm")
		if err != nil {
			return "", err
		}
		g.usesVM = true
		label = expr
	} else if raw, ok := staticAttr(n, "Text"); ok {
		label = quote(raw)
	}

	if g.inFor {
		return fmt.Sprintf("material.Button(th, v.rowClick%d(%s), %s).Layout(gtx)", rowPool, rowKey, label), nil
	}
	return fmt.Sprintf("material.Button(th, &v.click%d, %s).Layout(gtx)", idx, label), nil
}

// staticAttr 取静态属性值；绑定属性返回 false。
func staticAttr(n *contracts.NodeIR, name string) (string, bool) {
	for _, a := range n.Attrs {
		if a.Name != name {
			continue
		}
		if a.Value.IsBinding {
			return "", false
		}
		return a.Value.Raw, true
	}
	return "", false
}

// assemble 拼装完整源文件。
//
// import 由 importSet 统一收集并按契约 §7 排序，只在真正被引用时出现。
// assemble 拼装完整源文件（含静态子树缓存，契约 §16）。
func (g *generator) assemble(body string) (string, error) {
	// 签名始终需要 layout。
	g.imports.add("gioui.org/layout", "layout")
	g.imports.add("gioui.org/io/system", "system")
	g.imports.add("math", "math")
	g.imports.add("gioui.org/unit", "unit")
	// op 只在真正用到时导入：
	//   静态页 —— op.Record / op.CallOp 的整页固化；
	//   动态页 —— 绑定缓存槽位（op.Ops/op.CallOp）或事件失效（op.InvalidateCmd）。
	// 只为展示型 <For> 的页面两者都没有，无条件导入会编译失败。
	if !g.usesVM || g.bindSlots > 0 || len(g.clicks) > 0 {
		g.imports.add("gioui.org/op", "op")
	}
	if g.usesVM {
		// 构造函数的 nil 校验使用 fmt.Errorf。
		g.imports.add("fmt", "fmt")
	}

	// vm 类型：仅当页面含绑定时需要（构造函数参数与 View 字段）。
	//
	// 注意：vmTypeExpr 会登记跨包 import，必须在 import render 之前调用。
	if g.usesVM {
		if _, err := g.vmTypeExpr(); err != nil {
			return "", err
		}
	}

	var b strings.Builder
	b.WriteString(headerFor(g.opts.SourcePath))
	b.WriteString("package " + g.opts.PackageName + "\n\n")
	b.WriteString(g.imports.render())
	b.WriteString("\n")
	b.WriteString("// " + g.view + " 是 " + baseName(g.opts.SourcePath) + " 的生成视图。\n")
	b.WriteString("type " + g.view + " struct {\n")
	if g.usesVM {
		// 含绑定：**不**生成整页静态缓存（契约 §16.7、红线 2），
		// 但按绑定节点生成**显示缓存槽位**（契约 §05.2/05.3.1），
		// 并持有 vm 引用（状态更新契约 §1、ADR-0010）。
		b.WriteString("\tvm *" + g.vmTypeExprStr() + "\n")
		// 仅在确有绑定槽位时生成：纯事件页没有 textCache 类型声明
		// （bindCacheDecl 在 slots==0 时不输出），否则编译失败。
		if g.bindSlots > 0 {
			b.WriteString("\tslots []textCache\n")
		}
		// 交互控件状态：每个 <Button> 一个，跨帧地址不变（契约 §1.3）。
		for i := 0; i < g.clickSlots; i++ {
			b.WriteString(fmt.Sprintf("\tclick%d widget.Clickable\n", i))
		}
		// 行状态池：每个含交互控件的 <For> 一个（<For> 列表契约 §3.2）。
		// map 元素不可寻址，必须存指针。
		for pi, rc := range g.rowClicks {
			kt, err := rc.keyTypeExpr()
			if err != nil {
				return "", err
			}
			b.WriteString(fmt.Sprintf("\trowClicks%d map[%s]*widget.Clickable\n", pi, kt))
		}
	} else {
		for _, line := range cacheFieldLines(g.view) {
			b.WriteString(line + "\n")
		}
	}
	b.WriteString("}\n\n")
	// 构造函数：按页面类型分两种形态（状态更新契约 §1.4）。
	//
	//   静态页面：NewXxxView()            —— 与历史形态一致，不变；
	//   绑定页面：NewXxxView(vm *T) (*X, error) —— 持有 vm 引用。
	//
	// nil vm 是调用方配置错误，必须显式拒绝（ADR-0010 §3.4）：
	// 不静默转空串、不忽略绑定、不允许难定位的深层 panic。
	// 返回 error 而非 panic：nil 是**调用方输入错误**（可恢复），
	// 与内部不变式破坏（panic，如 Facts freeze）性质不同；
	// 且仓库已有 NewTypeEnv(...) (*T, error) 先例。
	b.WriteString("// New" + g.view + " 创建视图状态。\n")
	if g.usesVM {
		b.WriteString("//\n")
		b.WriteString("// vm 由调用方创建并管理生命周期；View 只持有引用，\n")
		b.WriteString("// 不拥有、不销毁，第一版不支持隐式替换（ADR-0010）。\n")
		b.WriteString("// vm 为 nil 时返回错误——这是调用方配置错误，明确拒绝。\n")
		b.WriteString("//\n")
		b.WriteString("// ⚠️ 失效通知的并发安全（Runtime Invalidate）不等于 vm 字段\n")
		b.WriteString("// 读写的并发安全；跨 goroutine 修改 vm 由调用方负责同步。\n")
		b.WriteString("func New" + g.view + "(vm *" + g.vmTypeExprStr() + ") (*" + g.view + ", error) {\n")
		b.WriteString("\tif vm == nil {\n")
		b.WriteString("\t\treturn nil, fmt.Errorf(\"goxml: New" + g.view + " requires a non-nil ViewModel; a binding page cannot render without state\")\n")
		b.WriteString("\t}\n")
		b.WriteString("\treturn &" + g.view + "{vm: vm}, nil\n")
		b.WriteString("}\n\n")
		b.WriteString("// Layout 渲染页面（统一 View 接口，状态更新契约 §1）。\n")
		b.WriteString("//\n")
		b.WriteString("// 绑定节点按槽位缓存显示结果：显示串与上下文未变时回放，\n")
		b.WriteString("// 变化时重录（契约 §05.2/§05.3.1）。\n")
		b.WriteString("//\n")
		b.WriteString("// 含绑定，因此**不**走静态子树固化（契约 §16.7）。\n")
		if len(g.clicks) > 0 {
			b.WriteString("//\n")
			b.WriteString("// 事件轮询置于一切绘制之前（事件处理输出契约 §2.2）：\n")
			b.WriteString("// 保证所有状态变更发生在任何节点渲染之前，同帧强一致。\n")
		}
		b.WriteString("func (v *" + g.view + ") Layout(gtx layout.Context, th *material.Theme) layout.Dimensions {\n")
		// 事件消费：必须在绘制之前（契约 §2.1/§2.2）。
		// 普通按钮逐个轮询；行状态按钮数据驱动（<For> 列表契约 §5）。
		for _, cs := range g.clicks {
			if cs.inFor {
				continue
			}
			// 条件守卫（If 输出契约 §2.2）：只在分支会被渲染时才轮询。
			if gd := guardExpr(cs.guards); gd != "" {
				b.WriteString("\tif " + gd + " {\n")
			}
			ind := "\t"
			if guardExpr(cs.guards) != "" {
				ind = "\t\t"
			}
			b.WriteString(fmt.Sprintf(ind+"for v.click%d.Clicked(gtx) {\n", cs.index))
			b.WriteString(ind + "\t v.vm." + cs.method + "(" + cs.args + ")\n")
			b.WriteString(ind + "\t gtx.Execute(op.InvalidateCmd{})\n")
			b.WriteString(ind + "}\n")
			if guardExpr(cs.guards) != "" {
				b.WriteString("\t}\n")
			}
		}
		// 行状态轮询（<For> 列表契约 §5）：数据驱动。
		// 与渲染用**同一数据源表达式**（同源）与**同一顺序**（range 切片），
		// 防止并发修改列表时两处错位。
		for _, rc := range g.rowClicks {
			b.WriteString(rc.pollCode())
		}
		// 键清理（<For> 列表契约 §4）：轮询之后、渲染之前。
		// 快速跳过：池不比列表大就不可能有失效键——稳定帧零分配。
		for _, rc := range g.rowClicks {
			b.WriteString(rc.cleanupCode())
		}
		if len(g.clicks) > 0 {
			b.WriteString("\n")
		}
		b.WriteString("\treturn " + strings.ReplaceAll(body, "\n", "\n\t") + "\n")
		b.WriteString("}\n")
		// 行状态池辅助方法（<For> 列表契约 §3.3）：惰性创建，跨帧稳定。
		for pi, rc := range g.rowClicks {
			kt, err := rc.keyTypeExpr()
			if err != nil {
				return "", err
			}
			b.WriteString(fmt.Sprintf(`
// rowClick%d 返回 Key 对应的行控件状态；不存在则创建（惰性）。
func (v *`+g.view+`) rowClick%d(key %s) *widget.Clickable {
	if v.rowClicks%d == nil {
		v.rowClicks%d = make(map[%s]*widget.Clickable)
	}
	c := v.rowClicks%d[key]
	if c == nil {
		c = new(widget.Clickable)
		v.rowClicks%d[key] = c
	}
	return c
}
`, pi, pi, kt, pi, pi, kt, pi, pi))
		}
		// 绑定页面同样需要 renderKey 与绑定缓存声明。
		b.WriteString(renderKeyDecl(g.view))
		b.WriteString(bindCacheDecl(g.view, g.bindSlots))
		return b.String(), nil
	}
	b.WriteString("func New" + g.view + "() *" + g.view + " { return &" + g.view + "{} }\n\n")

	b.WriteString("// 首个 key 生效时录制，之后 key 未变只回放（契约 §16.4）。\n")
	b.WriteString("func (v *" + g.view + ") Layout(gtx layout.Context, th *material.Theme) layout.Dimensions {\n")
	b.WriteString("\tk := v.currentKey(gtx, th)\n")
	b.WriteString("\tif v.cached && v.cacheKey.equal(k) {\n")
	b.WriteString("\t\tv.cacheCall.Add(gtx.Ops)\n")
	b.WriteString("\t\treturn v.cacheDims\n")
	b.WriteString("\t}\n\n")
	b.WriteString("\tv.cacheOps.Reset()\n")
	b.WriteString("\tm := op.Record(&v.cacheOps)\n")
	b.WriteString("\trec := gtx\n")
	b.WriteString("\trec.Ops = &v.cacheOps\n")
	b.WriteString("\t" + strings.ReplaceAll(body, "\n", "\n\t") + "\n")
	b.WriteString("\tv.cacheCall = m.Stop()\n")
	b.WriteString("\tv.cacheKey = k\n")
	b.WriteString("\tv.cached = true\n\n")
	b.WriteString("\tv.cacheCall.Add(gtx.Ops)\n")
	b.WriteString("\treturn v.cacheDims\n")
	b.WriteString("}\n")
	b.WriteString(renderKeyDecl(g.view))
	if g.usesVM {
		b.WriteString(bindCacheDecl(g.view, g.bindSlots))
	}
	return b.String(), nil
}

// vmTypeExpr 生成 ViewModel 参数的类型表达式，并按需登记 import。
//
// 同包（PkgDir 为空）→ Name，不需要 import。
// 其他包 → <pkg>.Name，需要 ModulePath 拼出 import 路径。
func (g *generator) vmTypeExpr() (string, error) {
	if g.vmRef.Name == "" {
		return "", fmt.Errorf("codegen: page is dynamic (binding or event) but no ViewModel type is available; add a ViewModel declaration")
	}
	if g.vmRef.PkgDir == "" {
		return g.vmRef.Name, nil
	}
	if g.opts.ModulePath == "" {
		return "", fmt.Errorf(
			"codegen: ViewModel %s is in package %q but Options.ModulePath is empty",
			g.vmRef.Name, g.vmRef.PkgDir)
	}
	pkg := filepath.Base(g.vmRef.PkgDir)
	g.imports.add(g.opts.ModulePath+"/"+g.vmRef.PkgDir, pkg)
	return pkg + "." + g.vmRef.Name, nil
}

// renderKeyDecl 生成私有 renderKey 类型（契约 §16.5.1 方案 A）。
//
// 注意：这是**生成产物**，不要手改。字段变更必须先改契约 §16.5 再重新生成。
func renderKeyDecl(view string) string {
	return `
// renderKey 复制自 代码生成输出契约 §16.5。
//
// ⚠️ 本类型是生成产物，不要手改。
// 字段变更必须先改契约 §16.5，再重新生成——已生成文件不会自动跟随。
type renderKey struct {
	constraints layout.Constraints
	metric      unit.Metric
	theme       *material.Theme
	locale      system.Locale
}

// equal 按位比较浮点字段，避免 float32 精度造成的误判（契约 §16.5）。
func (k renderKey) equal(o renderKey) bool {
	return k.constraints == o.constraints &&
		math.Float32bits(k.metric.PxPerDp) == math.Float32bits(o.metric.PxPerDp) &&
		math.Float32bits(k.metric.PxPerSp) == math.Float32bits(o.metric.PxPerSp) &&
		k.theme == o.theme &&
		k.locale == o.locale
}

// currentKey 采集当前帧的上下文指纹。
func (v *` + view + `) currentKey(gtx layout.Context, th *material.Theme) renderKey {
	return renderKey{
		constraints: gtx.Constraints,
		metric:      gtx.Metric,
		theme:       th,
		locale:      gtx.Locale,
	}
}
`
}

// cacheFieldLines 返回 View 结构体的缓存字段（契约 §16.2）。
func cacheFieldLines(view string) []string {
	return []string{
		"\t// cacheOps 是持久操作列表，仅由本视图持有，永不 Reset 之外的复用。",
		"\t// 必须与每帧的帧 Ops 分离：帧 Ops 每帧被 Reset，而 CallOp 引用 cacheOps 的数据。",
		"\tcacheOps op.Ops",
		"",
		"\t// cacheCall 指向 cacheOps 中的录制区间。",
		"\tcacheCall op.CallOp",
		"",
		"\t// cacheDims 是录制时的布局结果。CallOp.Add 不返回尺寸，必须一并缓存。",
		"\tcacheDims layout.Dimensions",
		"",
		"\t// cacheKey 是录制时的上下文指纹，用于判断失效。",
		"\tcacheKey renderKey",
		"",
		"\t// cached 表示 cacheCall 是否已有效录制。",
		"\tcached bool",
	}
}

// ============================================================================
// import 管理（契约 §7）
// ============================================================================

// importSet 按需收集 import，去重并按确定性别名规则渲染。
//
// 契约 §7 的要求：只为实际使用的符号生成、按路径去重、读取真实包名、
// 冲突时按路径字典序分配 `pkg`、`pkg_2`……、输出前经过 go/format。
type importSet struct {
	byPath map[string]string // 路径 → 优先包名
}

func newImportSet() *importSet {
	return &importSet{byPath: make(map[string]string)}
}

// add 记录一个需要的导入。path 为导入路径，pkgName 为该包的默认名。
func (s *importSet) add(path, pkgName string) {
	if _, ok := s.byPath[path]; !ok {
		s.byPath[path] = pkgName
	}
}

// render 生成 import 块。
//
// 排序规则：先按别名（空别名视为包名），再按路径——保证相同输入
// 产生逐字节相同的输出（契约 §6 确定性）。
func (s *importSet) render() string {
	if len(s.byPath) == 0 {
		return ""
	}

	type entry struct {
		path string
		name string // 最终使用的名字；等于默认包名时不写别名
		orig string
	}
	entries := make([]entry, 0, len(s.byPath))
	for p, n := range s.byPath {
		entries = append(entries, entry{path: p, name: n, orig: n})
	}

	// 按默认包名分组，检测冲突。
	used := make(map[string]int)
	byName := make(map[string][]int)
	for i, e := range entries {
		byName[e.orig] = append(byName[e.orig], i)
	}
	for name, idxs := range byName {
		if len(idxs) == 1 {
			used[name] = 1
			continue
		}
		// 冲突：按导入路径字典序分配 name、name_2、name_3……
		sort.Slice(idxs, func(a, b int) bool {
			return entries[idxs[a]].path < entries[idxs[b]].path
		})
		for k, i := range idxs {
			if k == 0 {
				entries[i].name = name
			} else {
				entries[i].name = fmt.Sprintf("%s_%d", name, k+1)
			}
		}
	}

	sort.Slice(entries, func(a, b int) bool {
		if entries[a].name != entries[b].name {
			return entries[a].name < entries[b].name
		}
		return entries[a].path < entries[b].path
	})

	var b strings.Builder
	b.WriteString("import (\n")
	for _, e := range entries {
		if e.name != e.orig {
			b.WriteString("\t" + e.name + " " + quote(e.path) + "\n")
		} else {
			b.WriteString("\t" + quote(e.path) + "\n")
		}
	}
	b.WriteString(")\n")
	return b.String()
}

