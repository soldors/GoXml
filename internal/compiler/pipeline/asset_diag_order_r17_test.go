package pipeline

// R17-A A1 判别回归：绑定页在「旧生成文件 //go:embed 指向已删除资产」时，
// 必须在 **Analyzer 之前**得到 CODEGEN-ASSET-*（准确归属），而不是被 Go 包加载
// 失败抢先报成 GXML-ROOT-002；与资产无关的 VM/Go 加载错误仍报 GXML-ROOT-002
// 并保留真实 Go cause（不得被误改成资产诊断）。
//
// 变异红：若移除 frontEnd 的 validateAssetsDoc 前置（仅靠 RunPrepared 内 validateAssets），
// 绑定页热删除用例会重新变回 GXML-ROOT-002，本测试失败。

import (
	"bytes"
	"image"
	"image/color"
	"image/png"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/goxml/goxml/contracts"
)

// p17Project 建最小模块：vm.go（合法 VM）+ 目标页。
func p17Project(t *testing.T, binding bool) string {
	t.Helper()
	root := t.TempDir()
	mustWriteFile(t, filepath.Join(root, "go.mod"), "module example.com/p17\n\ngo 1.26\n")
	mustWriteFile(t, filepath.Join(root, "vm.go"), "package ui\n\ntype VM struct{ Title string }\n\nfunc (v *VM) Inc() {}\n")
	if binding {
		mustWriteFile(t, filepath.Join(root, "home.gxml"),
			`<Goxml Version="1" ViewModel="VM"><Page Route="/"><Image Src="a/logo.png"/><Text Value="{Title}"/></Page></Goxml>`)
	} else {
		mustWriteFile(t, filepath.Join(root, "home.gxml"),
			`<Goxml Version="1"><Page Route="/"><Image Src="a/logo.png"/><Text Value="s"/></Page></Goxml>`)
	}
	return root
}

func mustWriteFile(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func codesOf(diags []contracts.CompilerError) []string {
	out := make([]string, 0, len(diags))
	for _, d := range diags {
		out = append(out, d.Code)
	}
	return out
}

// TestAssetGateBeforeAnalyzer_BindingPageDeletedAsset 绑定页 + 旧 embed 悬空 =>
// 资产门禁先报 CODEGEN-ASSET-*，而非 GXML-ROOT-002。
func TestAssetGateBeforeAnalyzer_BindingPageDeletedAsset(t *testing.T) {
	root := p17Project(t, true)
	src, err := os.ReadFile(filepath.Join(root, "home.gxml"))
	if err != nil {
		t.Fatal(err)
	}
	// 模拟"旧生成文件 //go:embed a/logo.png"指向已删除资产：目标包内放一个
	// 带 //go:embed 的旧产物，但磁盘上 a/logo.png 不存在。
	mustWriteFile(t, filepath.Join(root, "home_gen.go"),
		"// Code generated by goxml. DO NOT EDIT.\n// Source: home.gxml\n// Goxml-Version: 1\n\npackage ui\n\nimport \"embed\"\n\n//go:embed a/logo.png\nvar goxmlAssetsHome embed.FS\n")
	if _, err := os.Stat(filepath.Join(root, "a", "logo.png")); !os.IsNotExist(err) {
		t.Fatal("前置条件：资产应不存在")
	}
	cfg := Config{ModuleRoot: root, SourceDir: root, TargetDir: root, PackageName: "ui", SourcePath: "home.gxml"}
	p := Prepare("home.gxml", src, cfg, Hooks{})
	res := RunPrepared(p, Hooks{})
	got := strings.Join(codesOf(res.Diags), ",")
	if !strings.Contains(got, "CODEGEN-ASSET-002") {
		t.Fatalf("应报 CODEGEN-ASSET-002（资产缺失），实际诊断: %v", codesOf(res.Diags))
	}
	if strings.Contains(got, "GXML-ROOT-002") {
		t.Fatalf("不得被旧 embed 的 Go 包加载失败抢先报成 GXML-ROOT-002，实际: %v", codesOf(res.Diags))
	}
}

// TestAssetGateBeforeAnalyzer_UnrelatedVMErrorPreserved 与资产无关的 VM 编译错误
// 仍报 GXML-ROOT-002 且保留真实 Go cause（不得改成资产诊断）。
func TestAssetGateBeforeAnalyzer_UnrelatedVMErrorPreserved(t *testing.T) {
	root := p17Project(t, true)
	// 资产存在（通过门禁），但 VM 有类型错误。
	mustWriteFile(t, filepath.Join(root, "a", "logo.png"), string(p17PNG(t, 2, 2)))
	mustWriteFile(t, filepath.Join(root, "vm.go"), "package ui\n\ntype VM struct{ Title string }\n\nfunc (v *VM) Inc() { var _ int = \"bad\" }\n")
	src, _ := os.ReadFile(filepath.Join(root, "home.gxml"))
	cfg := Config{ModuleRoot: root, SourceDir: root, TargetDir: root, PackageName: "ui", SourcePath: "home.gxml"}
	p := Prepare("home.gxml", src, cfg, Hooks{})
	res := RunPrepared(p, Hooks{})
	got := strings.Join(codesOf(res.Diags), ",")
	if !strings.Contains(got, "GXML-ROOT-002") {
		t.Fatalf("无关 VM 错误应报 GXML-ROOT-002，实际: %v", codesOf(res.Diags))
	}
	if strings.Contains(got, "CODEGEN-ASSET") {
		t.Fatalf("无关 VM 错误不得被改成资产诊断，实际: %v", codesOf(res.Diags))
	}
	// 真实 Go cause 必须保留。
	joined := ""
	for _, d := range res.Diags {
		joined += d.Message + "\n"
	}
	if !strings.Contains(joined, "cannot use") && !strings.Contains(joined, "bad") {
		t.Fatalf("应保留真实 Go 编译原因，实际消息: %s", joined)
	}
}

func TestAssetGateBeforeAnalyzer_AssetAndVMErrors(t *testing.T) {
	root := p17Project(t, true)
	mustWriteFile(t, filepath.Join(root, "vm.go"), "package ui\n\ntype VM struct{ Title string }\n\nfunc (v *VM) Inc() { var _ int = \"bad\" }\n")
	src, err := os.ReadFile(filepath.Join(root, "home.gxml"))
	if err != nil {
		t.Fatal(err)
	}
	cfg := Config{ModuleRoot: root, SourceDir: root, TargetDir: root, PackageName: "ui", SourcePath: "home.gxml"}
	prepared := Prepare("home.gxml", src, cfg, Hooks{})
	got := codesOf(RunPrepared(prepared, Hooks{}).Diags)
	if len(got) != 1 || got[0] != "CODEGEN-ASSET-002" {
		t.Fatalf("资产和 VM 同时出错时应先报资产错误，实际诊断：%v", got)
	}
}

// p17PNG 生成一张最小合法 PNG。
func p17PNG(t *testing.T, w, h int) []byte {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			img.Set(x, y, color.RGBA{R: 0x11, G: 0x66, B: 0x99, A: 0xff})
		}
	}
	var b bytes.Buffer
	if err := png.Encode(&b, img); err != nil {
		t.Fatal(err)
	}
	return b.Bytes()
}
