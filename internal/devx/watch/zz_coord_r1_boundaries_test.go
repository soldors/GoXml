type coordR1Builder struct {
	path     string
	entered  chan string
	release  chan struct{}
	calls    int
	deadline bool
}

func (b *coordR1Builder) Build(ctx context.Context, gen int, paths []string) GenerationResult {
	b.deadline = false
	if _, ok := ctx.Deadline(); ok {
		b.deadline = true
	}
	b.calls++
	if b.path != "" && b.calls == 1 {
		data, _ := os.ReadFile(b.path)
		b.entered <- string(data)
		select {
		case <-b.release:
		case <-ctx.Done():
			return GenerationResult{Stage: "canceled"}
		}
	}
	return GenerationResult{OK: true, Gen: gen}
}

type coordR1Observer struct{ events chan bool }

func (o *coordR1Observer) OnGeneration(_ int, _ GenerationResult, p bool) { o.events <- p }
func TestCoordR1RunDiscardsChangeDuringBuild(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "page.gxml")
	if e := os.WriteFile(path, []byte("base"), 0600); e != nil {
		t.Fatal(e)
	}
	b := &coordR1Builder{path: path, entered: make(chan string, 1), release: make(chan struct{})}
	o := &coordR1Observer{events: make(chan bool, 8)}
	w, e := New(Config{ProjectDir: dir, PollIntervalMS: 5, DebounceMS: 1}, b, &fakeSwapper{}, o)
	if e != nil {
		t.Fatal(e)
	}
	ctx, cancel := context.WithCancel(context.Background())
	done := make(chan error, 1)
	defer cancel()
	go func() { done <- w.Run(ctx) }()
	defer func() {
		cancel()
		select {
		case <-done:
		case <-time.After(5 * time.Second):
			t.Error("Run failed to exit")
		}
	}()
	if e = os.WriteFile(path, []byte("first"), 0600); e != nil {
		t.Fatal(e)
	}
	select {
	case got := <-b.entered:
		if got != "first" {
			t.Fatalf("builder snapshot=%q", got)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("Run never built changed input")
	}
	if e = os.WriteFile(path, []byte("second"), 0600); e != nil {
		t.Fatal(e)
	}
	close(b.release)
	select {
	case published := <-o.events:
		if published {
			t.Fatal("stale first generation published after input changed during Build; Run did not scan while building or revalidate before swap")
		}
	case <-time.After(5 * time.Second):
		t.Fatal("no generation result")
	}
}
func TestCoordR1ConfigTimeoutReachesBuilder(t *testing.T) {
	b := &coordR1Builder{}
	w, e := New(Config{ProjectDir: mkProj(t), BuildTimeoutMS: 20, DebounceMS: 1}, b, &fakeSwapper{}, nil)
	if e != nil {
		t.Fatal(e)
	}
	if _, e = w.NotifyChange(context.Background(), 0, []string{"ui/home.gxml"}); e != nil {
		t.Fatal(e)
	}
	w.Tick(context.Background(), 1)
	if !b.deadline {
		t.Fatal("Config.BuildTimeoutMS did not set any deadline on Builder context")
	}
}
func TestCoordR1SourceMismatchRemainsUserOwned(t *testing.T) {
	dir := mkProj(t)
	mustWrite(t, filepath.Join(dir, ".goxml", "generate-manifest.json"), `{"version":1,"entries":[{"source":"ui/home.gxml","output":"ui/home_gen.go"}]}`)
	mustWrite(t, filepath.Join(dir, "ui", "home_gen.go"), "// Code generated by goxml. DO NOT EDIT.\n// Source: other.gxml\n// Goxml-Version: 1\npackage ui\n")
	s, e := Scan(Config{ProjectDir: dir})
	if e != nil {
		t.Fatal(e)
	}
	cs, e := ClassifyChanges(dir, s, []string{"ui/home_gen.go"})
	if e != nil {
		t.Fatal(e)
	}
	if len(cs.Trigger) != 1 || len(cs.Owned) != 0 {
		t.Fatalf("mismatched Source suppressed user change: trigger=%v owned=%v", cs.Trigger, cs.Owned)
	}
}
