// R26-A A3 端到端判别：初始成功 → 突发变更合并 → 新代启动 → 非法 GXML/坏入口不重启 →
// 修复恢复 → 变更中取消 → 进程树全收口。真实进程用 console helper（无窗口），Watch 核心
// 与 ProcessManager 为真实实现；generate/build 以受控 fake 注入（写 _gen.go / 产出 helper 二进制），
// 完整驱动真实生命周期并记录生成/build 调用次数与 argv（次数由 fake 计数，不用墙钟推断）。

import (
	"context"
	"path/filepath"
	"strings"
	"sync/atomic"
	"testing"
)

// e2eBuilder 是受控生成/构建：成功时把 helper 二进制路径返回给 ProcessManager 用；失败可控。
type e2eBuilder struct {
	binPath   string      // console helper 二进制
	genFails  func() bool // 是否让 generate 失败（模拟非法 GXML）
	buildFail func() bool // 是否让 build 失败（模拟坏入口）
	genCalls  int32
	bldCalls  int32
	outBin    map[int]string
}

func (b *e2eBuilder) Build(ctx context.Context, gen int, changed []string) GenerationResult {
	atomic.AddInt32(&b.genCalls, 1)
	if b.genFails != nil && b.genFails() {
		return GenerationResult{OK: false, Stage: "generate", Detail: "invalid gxml", Gen: gen}
	}
	atomic.AddInt32(&b.bldCalls, 1)
	if b.buildFail != nil && b.buildFail() {
		return GenerationResult{OK: false, Stage: "build", Detail: "bad entry", Gen: gen}
	}
	if b.outBin == nil {
		b.outBin = map[int]string{}
	}
	b.outBin[gen] = b.binPath
	return GenerationResult{OK: true, Gen: gen, Detail: b.binPath}
}

func (b *e2eBuilder) binFor(gen int) string { return b.outBin[gen] }

// buildConsoleAppForA3 复用 buildConsoleApp。
func buildConsoleAppForA3(t *testing.T) string { return buildConsoleApp(t) }

// e2e 主流程。
func TestE2EWatchLifecycle(t *testing.T) {
	bin := buildConsoleAppForA3(t)
	dir := mkProj(t)
	eb := &e2eBuilder{binPath: bin}
	pm := NewProcessManager(eb.binFor)
	pm.StopTimeout = 2 * 1e9 // 2s
	obs := &recordObs{}
	w, err := New(Config{ProjectDir: dir}, eb, pm, obs)
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()

	// 1) 初始成功：一次变更 -> 窗口到期 -> gen1 构建并发布并启动真实子进程
	w.NotifyChange(ctx, 0, []string{"ui/home.gxml"})
	if did, _ := w.Tick(ctx, 120); !did {
		t.Fatal("初始应触发 gen1")
	}
	if w.LastPublishedGen() != 1 || pm.Current() == nil || !pm.Current().Running() {
		t.Fatal("gen1 应发布并运行真实子进程")
	}
	pid1 := pm.Current().PID

	// 2) 突发变更合并：同窗口多次 -> 仅一次新构建（发布最新代次，final-wins）
	for _, ms := range []int{200, 210, 220, 230} {
		w.NotifyChange(ctx, ms, []string{"ui/vm.go"})
	}
	// 未到期不构建
	if did, _ := w.Tick(ctx, 300); did {
		t.Fatal("未到 deadline(230+100=330) 不得构建")
	}
	if did, _ := w.Tick(ctx, 330); !did {
		t.Fatal("330ms 到期应触发一次构建")
	}
	// 发布的是最新代次（4 次突发合并 => 发布 latestGen）
	gen2 := w.Debouncer().LatestGen()
	if w.LastPublishedGen() != gen2 {
		t.Fatalf("突发合并应发布最新代 gen%d，实际 %d", gen2, w.LastPublishedGen())
	}
	if pm.Current().PID == pid1 {
		t.Fatal("gen2 PID 必须不同于 gen1（真实替换）")
	}
	curAfterBurst := w.LastPublishedGen()

	// 3) 非法 GXML：generate 失败 -> 不重启（旧代继续服务），已发布代次不变
	eb.genFails = func() bool { return true }
	w.NotifyChange(ctx, 400, []string{"ui/home.gxml"})
	w.Tick(ctx, 520)
	if w.LastPublishedGen() != curAfterBurst {
		t.Fatal("generate 失败不得更新已发布代次")
	}
	if pm.Current() == nil || !pm.Current().Running() {
		t.Fatal("generate 失败时旧进程必须继续服务")
	}
	cur2 := pm.Current().PID
	if pm.Current().Gen != curAfterBurst {
		t.Fatalf("失败后当前应仍是已发布代 gen%d，实际 gen%d", curAfterBurst, pm.Current().Gen)
	}

	// 4) 坏入口：build 失败 -> 同样不重启
	eb.genFails = func() bool { return false }
	eb.buildFail = func() bool { return true }
	w.NotifyChange(ctx, 600, []string{"ui/home.gxml"})
	w.Tick(ctx, 720)
	if w.LastPublishedGen() != curAfterBurst || pm.Current().PID != cur2 {
		t.Fatal("build 失败不得替换旧进程")
	}

	// 5) 修复恢复：build 成功 -> 发布新代
	eb.buildFail = func() bool { return false }
	w.NotifyChange(ctx, 800, []string{"ui/home.gxml"})
	w.Tick(ctx, 920)
	if w.LastPublishedGen() == curAfterBurst {
		t.Fatal("修复后应发布更新的代次")
	}
	recovered := w.LastPublishedGen()
	if pm.Current().Gen != recovered || !pm.Current().Running() {
		t.Fatalf("恢复代 gen%d 应运行", recovered)
	}

	// 6) 变更中取消：进入构建后取消 -> 不发布
	w.NotifyChange(ctx, 1000, []string{"ui/vm.go"})
	gen := w.Debouncer().Pump(1120)
	if gen == 0 {
		t.Fatal("应进入构建")
	}
	w.Debouncer().Cancel()
	if publish, _ := w.Debouncer().BuildFinished(gen, true); publish {
		t.Fatal("取消后代次不得发布")
	}
	if w.LastPublishedGen() != recovered {
		t.Fatal("取消不得改变已发布代次")
	}

	// 7) 进程树全收口：shutdown 后无幸存
	if err := pm.Shutdown(); err != nil {
		t.Fatalf("shutdown: %v", err)
	}
	if pm.ActiveAfter() != 0 {
		t.Fatalf("收口后不得有幸存子进程，实际 %d", pm.ActiveAfter())
	}

	// 记录真实 generate/build 次数（fake 计数，非墙钟）
	t.Logf("E2E genCalls=%d buildCalls=%d history=%d", eb.genCalls, eb.bldCalls, len(pm.History()))
	if eb.genCalls == 0 || eb.bldCalls == 0 {
		t.Fatal("必须记录真实 generate/build 调用")
	}
}

// 生成产物写入不触发自激：写 owned home_gen.go（保护头+Manifest）不产生构建。
func TestE2EGeneratedWriteNoSelfTrigger(t *testing.T) {
	bin := buildConsoleAppForA3(t)
	dir := mkProj(t)
	// 建立 owned 产物
	gen := "// Code generated by goxml. DO NOT EDIT.\n// Source: home.gxml\n// Goxml-Version: 1\n\npackage ui\n"
	mustWrite(t, filepath.Join(dir, "ui", "home_gen.go"), gen)
	mustWrite(t, filepath.Join(dir, ".goxml", "generate-manifest.json"),
		`{"version":1,"entries":[{"source":"ui/home.gxml","output":"ui/home_gen.go"}]}`)
	eb := &e2eBuilder{binPath: bin}
	pm := NewProcessManager(eb.binFor)
	w, _ := New(Config{ProjectDir: dir}, eb, pm, nil)
	ctx := context.Background()
	// 模拟监视器发现 home_gen.go “变化”（内容仍是 owned）
	cs, _ := w.NotifyChange(ctx, 0, []string{"ui/home_gen.go"})
	if len(cs.Trigger) != 0 {
		t.Fatalf("owned 生成物写入不得触发: %v", cs.Trigger)
	}
	if did, _ := w.Tick(ctx, 200); did {
		t.Fatal("自激：owned 写入不得触发构建")
	}
	if atomic.LoadInt32(&eb.genCalls) != 0 {
		t.Fatalf("不得有任何生成调用，实际 %d", eb.genCalls)
	}
}

// 并发/多次变更末代获胜：连续多代变更，最终发布最新代。
func TestE2EConcurrentChangesLastWins(t *testing.T) {
	bin := buildConsoleAppForA3(t)
	dir := mkProj(t)
	eb := &e2eBuilder{binPath: bin}
	pm := NewProcessManager(eb.binFor)
	w, _ := New(Config{ProjectDir: dir}, eb, pm, nil)
	ctx := context.Background()
	// 快速多轮：每轮变更并在构建"之前"叠加更多变更，最终只发布最新代
	w.NotifyChange(ctx, 0, []string{"ui/home.gxml"})
	w.NotifyChange(ctx, 10, []string{"ui/vm.go"})
	w.NotifyChange(ctx, 20, []string{"go.mod"})
	if did, _ := w.Tick(ctx, 120); !did {
		t.Fatal("应触发一次构建（最新代 gen3）")
	}
	if w.LastPublishedGen() != 3 {
		t.Fatalf("末代获胜应发布 gen3，实际 %d", w.LastPublishedGen())
	}
	_ = pm.Shutdown()
	_ = strings.TrimSpace("")
}
