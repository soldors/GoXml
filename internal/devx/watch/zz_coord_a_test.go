func TestCoordActualProtectedHeaderOwnership(t *testing.T) {
	for _, tc := range []struct {
		name, header string
		want         FileClass
	}{
		{"real-output", "// Code generated by goxml. DO NOT EDIT.\n// Source: home.gxml\n// Goxml-Version: 1\n\npackage ui\n", ClassOwned},
		{"not-protected", "// Goxml-Version: 1\n// Source: home.gxml\npackage ui\n", ClassUser},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := mkProj(t)
			mustWrite(t, filepath.Join(dir, ".goxml", "generate-manifest.json"), `{"version":1,"entries":[{"source":"ui/home.gxml","output":"ui/home_gen.go"}]}`)
			mustWrite(t, filepath.Join(dir, "ui", "home_gen.go"), tc.header)
			if codegen.HasProtectedHeader([]byte(tc.header)) != (tc.want == ClassOwned) {
				t.Fatal("bad coordinator control")
			}
			s, e := Scan(Config{ProjectDir: dir})
			if e != nil {
				t.Fatal(e)
			}
			cs, e := ClassifyChanges(dir, s, []string{"ui/home_gen.go"})
			if e != nil {
				t.Fatal(e)
			}
			got := ClassUser
			if len(cs.Owned) == 1 {
				got = ClassOwned
			}
			if got != tc.want {
				t.Fatalf("owned classification=%v want=%v (protected=%v); trigger=%v owned=%v", got, tc.want, codegen.HasProtectedHeader([]byte(tc.header)), cs.Trigger, cs.Owned)
			}
		})
	}
}

func TestCoordRealBuilderUsesProjectDirectory(t *testing.T) {
	dir := t.TempDir()
	mustWrite(t, filepath.Join(dir, "go.mod"), "module example.com/watch-coord\n\ngo 1.26.0\n")
	mustWrite(t, filepath.Join(dir, "main.go"), "package main\nfunc main(){}\n")
	out := filepath.Join(t.TempDir(), "expected-user-main.exe")
	b := RealBuilder{ProjectDir: dir, EntryPkg: ".", OutBinary: out, Generate: func(context.Context, string) (int, string) { return 0, "" }}
	result := b.Build(context.Background(), 1, nil)
	if !result.OK {
		t.Fatalf("build: %+v", result)
	}
	data, e := os.ReadFile(out)
	if e != nil {
		t.Fatal(e)
	}
	if len(data) < 2 || string(data[:2]) != "MZ" {
		t.Fatalf("build reported OK but output is not user Windows main; prefix=%q (cwd was not ProjectDir)", data[:min(16, len(data))])
	}
}

func TestCoordChangedPathsSurvivePump(t *testing.T) {
	b := &fakeBuilder{}
	s := &fakeSwapper{}
	w, e := New(Config{ProjectDir: mkProj(t)}, b, s, nil)
	if e != nil {
		t.Fatal(e)
	}
	if _, e = w.NotifyChange(context.Background(), 0, []string{"ui/home.gxml"}); e != nil {
		t.Fatal(e)
	}
	w.Tick(context.Background(), 100)
	if len(b.paths) != 1 || len(b.paths[0]) != 1 || b.paths[0][0] != "ui/home.gxml" {
		t.Fatalf("builder received paths=%v, want [[ui/home.gxml]]", b.paths)
	}
}

func TestCoordCanceledContextCannotPublish(t *testing.T) {
	b := &fakeBuilder{}
	s := &fakeSwapper{}
	w, e := New(Config{ProjectDir: mkProj(t)}, b, s, nil)
	if e != nil {
		t.Fatal(e)
	}
	w.NotifyChange(context.Background(), 0, []string{"ui/home.gxml"})
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	w.Tick(ctx, 100)
	if len(s.swapped) != 0 || w.LastPublishedGen() != 0 {
		t.Fatalf("canceled context still published gen=%d swaps=%v", w.LastPublishedGen(), s.swapped)
	}
}
