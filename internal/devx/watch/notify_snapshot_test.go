package watch

import (
	"context"
	"path/filepath"
	"strings"
	"testing"
)

// The polling loop can detect an owned output, then a user saves another file
// before NotifyChange rescans. Advancing the baseline must not absorb that save.
func TestNotifyOwnedOutputDoesNotAbsorbLaterUserSave(t *testing.T) {
	dir := mkProj(t)
	calls := 0
	b := failureBuild(func(context.Context, int, []string) GenerationResult {
		calls++
		return GenerationResult{OK: false, Stage: "generate", Detail: "bad user source observed"}
	})
	w, e := New(Config{ProjectDir: dir, DebounceMS: 1}, b, new(fakeSwapper), nil)
	if e != nil {
		t.Fatal(e)
	}
	mustWrite(t, filepath.Join(dir, "ui", "home_gen.go"), "// Code generated by goxml. DO NOT EDIT.\n// Source: home.gxml\n// Goxml-Version: 1\npackage ui\n")
	mustWrite(t, filepath.Join(dir, ".goxml", "generate-manifest.json"), `{"version":1,"entries":[{"source":"ui/home.gxml","output":"ui/home_gen.go"}]}`)
	// First scan reports only generated output. Save happens after this scan.
	first, e := Scan(w.cfg)
	if e != nil {
		t.Fatal(e)
	}
	detected := Diff(w.prev, first)
	control, e := ClassifyChanges(dir, first, detected)
	if e != nil || len(control.Owned) != 1 || len(control.Trigger) != 0 {
		t.Fatalf("owned-only setup invalid: %+v %v", control, e)
	}
	mustWrite(t, filepath.Join(dir, "ui", "home.gxml"), "<broken-user-input>")
	cs, e := w.NotifyChange(context.Background(), 0, detected)
	if e != nil {
		t.Fatal(e)
	}
	if !strings.Contains(strings.Join(cs.Trigger, "|"), "ui/home.gxml") {
		t.Fatalf("user save absorbed by owned-only notification: trigger=%v", cs.Trigger)
	}
	ran, e := w.Tick(context.Background(), 2)
	if e != nil || !ran || calls != 1 {
		t.Fatalf("latest user save did not reach generation: ran=%v calls=%d err=%v", ran, calls, e)
	}
}
