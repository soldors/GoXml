package preview

import (
	"os"
	"path/filepath"
	"testing"
)

func TestCoordOwnedAssetOutputOptionIsEnforced(t *testing.T) {
	proj := copyProject(t)
	f := filepath.Join(proj, "owned.gxml")
	imageBytes := readFile(t, filepath.Join(proj, "assets", "logo.png"))
	asset := filepath.Join(proj, "owned_gen.go")
	if e := os.WriteFile(asset, []byte("// Code generated by goxml. DO NOT EDIT.\n// Source: owned.gxml\n// Goxml-Version: 1\npackage ui\n"), 0600); e != nil {
		t.Fatal(e)
	}
	effective := filepath.Join(t.TempDir(), "effective.png")
	os.WriteFile(effective, imageBytes, 0600)
	os.WriteFile(f, []byte(`<Goxml Version="1"><Page><Image Src="owned_gen.go"/></Page></Goxml>`), 0600)
	res, e := Run(Options{File: f, SkipHost: true, AssetOverlay: map[string]string{asset: effective}, AssetOutputPaths: map[string]bool{asset: true}})
	if e != nil {
		t.Fatalf("unexpected operation error: %v", e)
	}
	if res.OK() {
		t.Fatalf("AssetOutputPaths declared owned output, but Run accepted it: phase=%s (option not forwarded into pipeline.Config)", res.Phase)
	}
}

func TestCoordHostArrangementFailureDoesNotLoseDirectory(t *testing.T) {
	proj := copyProject(t)
	tool := t.TempDir()
	tmp := t.TempDir()
	os.WriteFile(filepath.Join(tool, "go.mod"), []byte("module github.com/goxml/goxml\n\ngo 1.26.0\n"), 0600)
	t.Setenv("TMP", tmp)
	t.Setenv("TEMP", tmp)
	res, e := Run(Options{File: filepath.Join(proj, "static_basic.gxml"), ToolRoot: tool})
	if e == nil {
		t.Fatal("expected missing go.sum arrangement error")
	}
	dirs, _ := filepath.Glob(filepath.Join(tmp, "goxml-preview-*"))
	if len(dirs) > 0 && res.HostDir == "" {
		t.Fatalf("host arrangement failed but leaked unreported directory=%v result.HostDir=%q err=%v", dirs, res.HostDir, e)
	}
}
