// TestRunDynamicBindingRejectedByStandardFrontend 负例：无 VM 的动态绑定
// 由**标准前端**先拒（GXML-BIND-*），预览不重复判——证明预览没有在
// 标准准入之外造第二套绑定校验。
func TestRunDynamicBindingRejectedByStandardFrontend(t *testing.T) {
	proj := copyProject(t)
	res := runOn(t, proj, "dynamic_bind.gxml")

	if res.Phase != PhaseFrontend {
		t.Fatalf("应停在 PhaseFrontend，实得 %s（诊断 %v）", res.Phase, res.Diags)
	}
	if len(res.Diags) == 0 {
		t.Fatal("标准前端应给出绑定诊断")
	}
	for _, d := range res.Diags {
		if strings.HasPrefix(d.Code, "PREVIEW-") {
			t.Fatalf("标准准入应先于预览范围拒绝，实得预览诊断：%v", d)
		}
	}
	hasBind := false
	for _, d := range res.Diags {
		if strings.HasPrefix(d.Code, "GXML-BIND") {
			hasBind = true
		}
	}
	if !hasBind {
		t.Fatalf("应含 GXML-BIND-* 标准诊断，实得：%v", res.Diags)
	}
}

