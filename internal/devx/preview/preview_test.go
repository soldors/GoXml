// TestRunInputErrors 输入边界：文件缺失/后缀错误/空文件/不在 module 内。
func TestRunInputErrors(t *testing.T) {
	proj := copyProject(t)

	cases := []struct {
		name string
		file string
		want string
	}{
		{"缺失", filepath.Join(proj, "nope.gxml"), "nope.gxml"},
		{"后缀", filepath.Join(proj, "static_basic.txt"), ".gxml"},
		{"空文件", "", "输入文件为空"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			res, err := Run(Options{File: tc.file, WorkDir: proj})
			if err == nil {
				t.Fatalf("应返回操作错误（res=%+v）", res)
			}
			if res == nil || res.Phase != PhaseResolve {
				t.Fatalf("Phase 应为 resolve，实得 %+v", res)
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("错误 %q 应包含 %q", err.Error(), tc.want)
			}
		})
	}

	// 空文件（0 字节）。
	empty := filepath.Join(proj, "empty.gxml")
	if err := os.WriteFile(empty, nil, 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Run(Options{File: empty, WorkDir: proj}); err == nil || !strings.Contains(err.Error(), "空文件") {
		t.Fatalf("空文件应被拒：%v", err)
	}

	// 不在任何 Go module 内。
	bare := t.TempDir()
	if err := os.WriteFile(filepath.Join(bare, "lonely.gxml"),
		[]byte(`<Goxml Version="1"><Page><Column><Text Value="x"/></Column></Page></Goxml>`), 0o644); err != nil {
		t.Fatal(err)
	}
	_, err := Run(Options{File: filepath.Join(bare, "lonely.gxml"), WorkDir: bare})
	if err == nil || !strings.Contains(err.Error(), "go mod init") {
		t.Fatalf("module 外输入应给出可执行修复动作：%v", err)
	}
}

