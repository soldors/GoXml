// copyProject 把 testdata/proj 复制到临时目录（故意带空格与中文），
// 并在临时副本里合成 assets/logo.png（夹具目录不进二进制）。
//
// 预览是只读输入的：夹具本体绝不能被测试改写，所有资产/临时状态
// 都发生在副本里——这正是 C2「不改用户 .gxml/资产」的形态。
func copyProject(t *testing.T) string {
	t.Helper()
	repo, err := filepath.Abs(filepath.Join("..", "..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	src := filepath.Join(repo, "internal", "devx", "preview", "testdata", "proj")
	// 临时目录故意带空格与中文：Windows 路径拼接缺陷只在这种路径下暴露。
	dst := filepath.Join(t.TempDir(), "预览 工程")
	if err := os.MkdirAll(filepath.Join(dst, "assets"), 0o755); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(src)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		data, err := os.ReadFile(filepath.Join(src, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dst, e.Name()), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	// 合成 4x4 PNG 与 4x4 JPEG（两种门禁批准格式）：内容不重要，
	// 门禁只认「合法格式且在预算内」；字节一致性断言用原始字节比对。
	img := image.NewRGBA(image.Rect(0, 0, 4, 4))
	for y := 0; y < 4; y++ {
		for x := 0; x < 4; x++ {
			img.Set(x, y, color.RGBA{R: 90, G: 160, B: 220, A: 255})
		}
	}
	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dst, "assets", "logo.png"), buf.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	var jbuf bytes.Buffer
	if err := jpeg.Encode(&jbuf, img, &jpeg.Options{Quality: 80}); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dst, "assets", "photo.jpg"), jbuf.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	return dst
}

func runOn(t *testing.T, proj, name string) *Result {
	t.Helper()
	res, err := Run(Options{File: filepath.Join(proj, name), WorkDir: proj})
	if err != nil {
		t.Fatalf("Run(%s) 操作故障（不该发生）: %v", name, err)
	}
	return res
}

// TestRunGeneratesStaticPage 正例：批准范围内的纯静态页（布局/Def/Slot/
// Image/Expanded）走完整前端 + Codegen，产出可解析的生成 View。
// SkipHost：宿主构建在 host_test.go 的 TestRunBuildsRealHost 单独验收。
func TestRunGeneratesStaticPage(t *testing.T) {
	proj := copyProject(t)
	res, err := Run(Options{
		File:     filepath.Join(proj, "static_basic.gxml"),
		WorkDir:  proj,
		SkipHost: true,
	})
	if err != nil {
		t.Fatalf("Run 操作故障（不该发生）: %v", err)
	}

	if res.Phase != PhaseGenerated || !res.OK() {
		t.Fatalf("应生成成功（PhaseGenerated），实到 Phase=%s，诊断 %d 条：%v", res.Phase, len(res.Diags), res.Diags)
	}
	src := string(res.Source)
	if res.PkgName != "preview" {
		t.Fatalf("包名应为 preview，实得 %q", res.PkgName)
	}
	if res.OutputName != "static_basic_gen.go" {
		t.Fatalf("输出名应为 static_basic_gen.go，实得 %q", res.OutputName)
	}
	// 生成源码必须是语法合法的 Go（与 pipeline.Commit 的校验同判据）。
	if _, err := parser.ParseFile(token.NewFileSet(), res.OutputName, res.Source, 0); err != nil {
		t.Fatalf("生成源码不可解析: %v\n%s", err, head(res.Source, 30))
	}
	for _, want := range []struct{ frag, note string }{
		{"package preview\n", "包子句"},
		{"func NewGoxmlStatic_BasicView()", "静态页零参构造（契约 §4.3；basename 的 _ 按符号规则保留）"},
		{`material.Body1(th, "静态预览实验台")`, "静态文本烙进产物"},
		{`material.Body1(th, "带插槽")`, "Def prop 替换后的静态标题"},
		{`material.Body1(th, "空插槽")`, "第二个 Def 实例的标题"},
		{`material.Body1(th, "插槽内容")`, "Slot 替换内容"},
		{`material.Body1(th, "占满剩余宽度")`, "Expanded 子内容"},
		{`//go:embed "assets/logo.png"`, "Image 资产 embed 指令"},
	} {
		if !strings.Contains(src, want.frag) {
			t.Fatalf("生成产物缺少 %s（%q）:\n%s", want.note, want.frag, head(res.Source, 40))
		}
	}
	// 静态页不该有绑定缓存/VM 引用。
	for _, banned := range []string{"v.vm", "v.slots", "bindText"} {
		if strings.Contains(src, banned) {
			t.Fatalf("静态页产物不应出现 %q:\n%s", banned, head(res.Source, 40))
		}
	}
	// 生成头 + 不泄漏机器路径（契约 §3.1）。
	if !bytes.HasPrefix(res.Source, []byte("// Code generated by goxml. DO NOT EDIT.")) {
		t.Fatalf("产物缺少生成保护头:\n%s", head(res.Source, 6))
	}
	if strings.Contains(src, proj) || strings.Contains(src, `\Users\`) || strings.Contains(src, "/Users/") {
		t.Fatalf("产物泄漏了机器路径:\n%s", head(res.Source, 10))
	}
	t.Logf("OBS 生成 %d 字节，符号 NewGoxmlStaticBasicView，资产 embed 1 处", len(res.Source))
}

// TestRunRejectsViewModelEarly 负例：声明 ViewModel 的页面在 pre-parse
// 阶段被拒（PREVIEW-001），不进入 Analyzer（不加载用户 VM 包）。
func TestRunRejectsViewModelEarly(t *testing.T) {
	proj := copyProject(t)
	res := runOn(t, proj, "with_vm.gxml")

	if res.Phase != PhaseScope {
		t.Fatalf("应停在 PhaseScope，实得 %s（诊断 %v）", res.Phase, res.Diags)
	}
	if len(res.Diags) != 1 || res.Diags[0].Code != CodePreviewVM {
		t.Fatalf("应恰 1 条 PREVIEW-001，实得 %d 条：%v", len(res.Diags), res.Diags)
	}
	d := res.Diags[0]
	if !strings.Contains(d.Message, "vm.Model") {
		t.Fatalf("诊断应点名声明的 ViewModel：%v", d)
	}
	if d.File != filepath.Join(proj, "with_vm.gxml") {
		t.Fatalf("诊断 File 应为输入路径，实得 %q", d.File)
	}
	if d.Line == 0 {
		t.Fatalf("诊断应带源码位置：%v", d)
	}
	if res.Source != nil {
		t.Fatal("被拒页面不应有生成产物")
	}
}

