package cli

import (
	"os"
	"path/filepath"
	"testing"
)

func TestReviewProtectedHeaderNeedsManifestOwnership(t *testing.T) {
	root := newScratchModule(t)
	dir := filepath.Join(root, "ui")
	writeGoFile(t, dir, "base.go", "package actual\n")
	writeGoFile(t, dir, "user.go", "// Code generated by goxml. DO NOT EDIT.\n// Source: other.gxml\n// Goxml-Version: 1\n\npackage userpkg\n")
	t.Setenv("GOFLAGS", "")
	if name, err := packageDirName(dir); err == nil {
		t.Fatalf("unregistered user file was ignored: package=%s", name)
	}
	// Registration plus the same exact header is the existing ownership contract.
	t.Setenv("GOFLAGS", "")
	if err := saveManifest(manifestPath(root), &manifest{Version: manifestVersion, Entries: []entry{{Source: "ui/other.gxml", Output: "ui/user.go"}}}); err != nil {
		t.Fatal(err)
	}
	if name, err := packageDirName(dir); err != nil || name != "actual" {
		t.Fatalf("registered stale output: %s %v", name, err)
	}
	if err := saveManifest(manifestPath(root), &manifest{Version: manifestVersion, Entries: []entry{{Source: "ui/different.gxml", Output: "ui/user.go"}}}); err != nil {
		t.Fatal(err)
	}
	if _, err := packageDirName(dir); err == nil {
		t.Fatal("registration for another Source must not hide user-owned source")
	}
	if err := os.WriteFile(filepath.Join(dir, "user.go"), []byte("package userpkg\n"), 0600); err != nil {
		t.Fatal(err)
	}
	if _, err := packageDirName(dir); err == nil {
		t.Fatal("registration alone must not hide user-owned source")
	}
}
