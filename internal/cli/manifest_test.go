// ============================================================================
// 1-6：Manifest 与 --clean（契约 §10 + 三把安全锁）
//
//   锁 1 双重所有权：删 = Manifest 登记 ∧ 带保护头；头被改 = 用户接管
//   锁 2 Manifest 自身原子更新
//   锁 3 损坏即自锁：损坏的 Manifest 禁止任何删除
// ============================================================================

// setupCleanFixture 准备一个可清理的工程：先生成（登记 Manifest），返回根。
//
// Manifest 重定向到本用例的隔离目录——所有 tempProjectInRepo 的 moduleRoot
// 都是仓库根，若共享真实 Manifest，用例间会互相污染（实测：
// 损坏自锁用例写坏共享 Manifest 后，后续用例的生成全部被自锁拦下）。
func setupCleanFixture(t *testing.T) string {
	t.Helper()
	isolateManifest(t)
	root := tempProjectInRepo(t)
	copyFixture(t, root)

	var out, errb bytes.Buffer
	if code := Run([]string{"generate", filepath.Join(root, "home.gxml")}, &out, &errb); code != ExitOK {
		t.Fatalf("前置生成失败: %s", errb.String())
	}
	return root
}

// isolateManifest 把 Manifest 路径重定向到本用例专属文件。
func isolateManifest(t *testing.T) {
	t.Helper()
	dir := t.TempDir()
	old := manifestPathOverride
	manifestPathOverride = filepath.Join(dir, manifestName)
	t.Cleanup(func() { manifestPathOverride = old })
}

// TestManifestCreatedAfterGenerate 生成后 Manifest 存在且登记正确。
func TestManifestCreatedAfterGenerate(t *testing.T) {
	root := setupCleanFixture(t)

	data, err := os.ReadFile(manifestPath(root))
	if err != nil {
		t.Fatalf("Manifest 应存在: %v", err)
	}
	m, err := loadManifest(manifestPath(root))
	if err != nil {
		t.Fatal(err)
	}
	if m.Version != manifestVersion {
		t.Errorf("version = %d", m.Version)
	}
	if len(m.Entries) != 1 {
		t.Fatalf("应登记 1 条, 实际 %d", len(m.Entries))
	}
	e := m.Entries[0]
	// Source/Output 是**项目相对路径**（仓库根基准，/ 分隔）——
	// 断言用后缀匹配，不写死测试目录名。
	if !strings.HasSuffix(e.Source, "/home.gxml") || !strings.HasSuffix(e.Output, "/home_gen.go") {
		t.Errorf("登记不对: %+v", e)
	}
	if e.CompilerVersion != codegen.GoxmlVersion {
		t.Errorf("CompilerVersion = %q, 期望保护头同源 %q", e.CompilerVersion, codegen.GoxmlVersion)
	}
	if e.InputHash == "" {
		t.Error("InputHash 不应为空")
	}
	// Manifest 本身是合法 JSON（反序列化已证）；文件以换行结尾（确定性）。
	if !strings.HasSuffix(string(data), "\n") {
		t.Error("Manifest 应以换行结尾")
	}
}

// TestCleanRemovesOrphanWhenSourceDeleted 契约 §10 主场景：
// 删除源 .gxml 后 --clean 只删登记且带保护头的生成文件。
func TestCleanRemovesOrphanWhenSourceDeleted(t *testing.T) {
	root := setupCleanFixture(t)
	gen := filepath.Join(root, "home_gen.go")
	if _, err := os.Stat(gen); err != nil {
		t.Fatal(err)
	}

	// 删除源。
	if err := os.Remove(filepath.Join(root, "home.gxml")); err != nil {
		t.Fatal(err)
	}

	var out, errb bytes.Buffer
	code := Run([]string{"generate", filepath.Join(root, "home.gxml"), "--clean"}, &out, &errb)
	// 注意：源已删除，generate 本身会失败——--clean 的正确用法是配合仍存在的输入。
	// 这里改为直接调用 cleanOrphans（generate --clean 的完整场景见下一测试）。
	_ = code

	deleted, skipped, err := cleanOrphans(repoRoot(t), nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(deleted) != 1 || !strings.HasSuffix(deleted[0], "home_gen.go") {
		t.Fatalf("应删除 home_gen.go, 实际 deleted=%v skipped=%v", deleted, skipped)
	}
	if _, err := os.Stat(gen); !os.IsNotExist(err) {
		t.Error("孤儿文件应被删除")
	}
	// Manifest 条目同步移除。
	m, err := loadManifest(manifestPath(root))
	if err != nil {
		t.Fatal(err)
	}
	if len(m.Entries) != 0 {
		t.Errorf("已删条目应从 Manifest 移除, 剩 %d", len(m.Entries))
	}
}

// TestCleanSkipsUserModifiedHeader 安全锁 1：保护头被改动 = 用户接管，绝不删除。
func TestCleanSkipsUserModifiedHeader(t *testing.T) {
	root := setupCleanFixture(t)
	gen := filepath.Join(root, "home_gen.go")

	// 用户改掉保护头（保留内容但换头）。
	data, _ := os.ReadFile(gen)
	userVersion := strings.Replace(string(data), "// Code generated by goxml. DO NOT EDIT.", "// 我接管了这个文件", 1)
	if err := os.WriteFile(gen, []byte(userVersion), 0o644); err != nil {
		t.Fatal(err)
	}

	// 删除源 → 清理。
	if err := os.Remove(filepath.Join(root, "home.gxml")); err != nil {
		t.Fatal(err)
	}
	deleted, skipped, err := cleanOrphans(repoRoot(t), nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(deleted) != 0 {
		t.Errorf("保护头被改的文件不得删除, 实际删除 %v", deleted)
	}
	if len(skipped) != 1 || !strings.Contains(skipped[0], "保护头不符") {
		t.Errorf("应跳过并说明原因, skipped=%v", skipped)
	}
	// 文件还在。
	if _, err := os.Stat(gen); err != nil {
		t.Error("用户接管的文件不得被删除")
	}
}

// TestCleanCorruptedManifestFailsClosed 安全锁 3：Manifest 损坏 → 报错，禁止删除。
func TestCleanCorruptedManifestFailsClosed(t *testing.T) {
	root := setupCleanFixture(t)
	gen := filepath.Join(root, "home_gen.go")

	// 损坏 Manifest。
	if err := os.WriteFile(manifestPath(root), []byte("{not valid json"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(root, "home.gxml")); err != nil {
		t.Fatal(err)
	}

	_, _, err := cleanOrphans(repoRoot(t), nil)
	if err == nil {
		t.Fatal("损坏的 Manifest 应报错（fail-safe）")
	}
	if !strings.Contains(err.Error(), "损坏") {
		t.Errorf("错误应说明损坏: %v", err)
	}
	// 生成文件仍在（未执行任何删除）。
	if _, err := os.Stat(gen); err != nil {
		t.Error("损坏自锁时不得删除任何文件")
	}
}

// TestManifestAtomicUpdate 安全锁 2：保存走临时文件 + rename。
//
// 直接可观察的证据：保存后目录里没有残留的 .goxml-manifest-*.tmp。
func TestManifestAtomicUpdate(t *testing.T) {
	root := setupCleanFixture(t)

	// 再生成一次（Manifest 应被更新而非追加重复条目）。
	var out, errb bytes.Buffer
	if code := Run([]string{"generate", filepath.Join(root, "home.gxml")}, &out, &errb); code != ExitOK {
		t.Fatalf("第二次生成失败: %s", errb.String())
	}

	m, err := loadManifest(manifestPath(root))
	if err != nil {
		t.Fatal(err)
	}
	if len(m.Entries) != 1 {
		t.Errorf("重复生成不得产生重复登记, 实际 %d 条", len(m.Entries))
	}
	// 无临时残留。
	entries, _ := os.ReadDir(filepath.Dir(manifestPath(root)))
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), ".goxml-manifest-") {
			t.Errorf("Manifest 临时文件残留: %s", e.Name())
		}
	}
}

// TestCleanSkipsUnregisteredFiles 未登记文件（无 Manifest 记录）永不删除。
func TestCleanSkipsUnregisteredFiles(t *testing.T) {
	root := setupCleanFixture(t)

	// 手工放一个"长得像生成文件"的用户文件，但不在 Manifest 里。
	unreg := filepath.Join(root, "stray_gen.go")
	if err := os.WriteFile(unreg, []byte("// Code generated by goxml. DO NOT EDIT.\n// Source: stray.gxml\n// Goxml-Version: 1\n\npackage x\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	deleted, _, err := cleanOrphans(repoRoot(t), nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, d := range deleted {
		if strings.Contains(d, "stray") {
			t.Errorf("未登记文件不得删除: %s", d)
		}
	}
	if _, err := os.Stat(unreg); err != nil {
		t.Error("未登记文件被误删")
	}
}

// repoRoot 返回仓库根（生成时 Manifest 的坐标基准）。
func repoRoot(t *testing.T) string {
	t.Helper()
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	root, err := findModuleRoot(wd)
	if err != nil {
		t.Fatal(err)
	}
	return root
}
