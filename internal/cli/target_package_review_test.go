func TestTargetPackageReview386(t *testing.T) {
	for _, kind := range []string{"valid", "multi", "excluded", "empty"} {
		t.Run(kind, func(t *testing.T) {
			root := t.TempDir()
			write := func(name, text string) {
				t.Helper()
				p := filepath.Join(root, name)
				if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(p, []byte(text), 0644); err != nil {
					t.Fatal(err)
				}
			}
			write("go.mod", "module example.com/review\n\ngo 1.26\n")
			write("src/base.go", "package sourcepkg\n")
			write("src/page.gxml", `<Goxml Version="1"><Page Route="/"><Text Value="A"/></Page></Goxml>`)
			write("goenv", "GOOS=windows\nGOARCH=386\n")
			t.Setenv("GOENV", filepath.Join(root, "goenv"))
			t.Setenv("GOOS", "")
			t.Setenv("GOARCH", "")
			t.Setenv("GOEXPERIMENT", "")
			switch kind {
			case "valid":
				write("out/on.go", "//go:build goexperiment.regabiargs\n\npackage enabled\n")
				write("out/off.go", "//go:build !goexperiment.regabiargs\n\npackage disabled\n")
			case "multi":
				write("out/always.go", "package enabled\n")
				write("out/off.go", "//go:build !goexperiment.regabiargs\n\npackage disabled\n")
			case "excluded":
				write("out/on.go", "//go:build goexperiment.regabiargs\n\npackage excluded\n")
			case "empty":
				if err := os.MkdirAll(filepath.Join(root, "out"), 0755); err != nil {
					t.Fatal(err)
				}
			}
			var stdout, stderr bytes.Buffer
			rc := Run([]string{"generate", filepath.Join(root, "src/page.gxml"), "--out-dir", filepath.Join(root, "out"), "--no-cache"}, &stdout, &stderr)
			target := filepath.Join(root, "out/page_gen.go")
			if kind == "multi" || kind == "excluded" {
				if rc == 0 {
					t.Fatalf("target-invalid input accepted: %s", stdout.String())
				}
				if _, err := os.Stat(target); !os.IsNotExist(err) {
					t.Fatalf("failed target wrote generated file: %v", err)
				}
				if _, err := os.Stat(filepath.Join(root, ".goxml")); !os.IsNotExist(err) {
					t.Fatalf("failed target wrote metadata: %v", err)
				}
			} else {
				if rc != 0 {
					t.Fatalf("legal target rc=%d: %s", rc, stderr.String())
				}
				data, err := os.ReadFile(target)
				if err != nil {
					t.Fatal(err)
				}
				want := "package disabled"
				if kind == "empty" {
					want = "package sourcepkg"
				}
				if !strings.Contains(string(data), want) {
					t.Fatalf("wanted %s, got %s", want, data)
				}
			}
		})
	}
}

func TestTargetNameOverlayRequiresMatchingSource(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "x_gen.go")
	m := &manifest{Entries: []entry{{Source: "x.gxml", Output: "x_gen.go"}}}
	for _, source := range []string{"x.gxml", "someone-else.gxml"} {
		if err := os.WriteFile(path, []byte("// Code generated by goxml. DO NOT EDIT.\n// Source: "+source+"\n// Goxml-Version: 1\n\npackage p\n"), 0644); err != nil {
			t.Fatal(err)
		}
		ov, err := targetNameOverlay(root, m, root)
		if err != nil {
			t.Fatal(err)
		}
		_, hidden := ov[path]
		if hidden != (source == "x.gxml") {
			t.Fatalf("source=%s hidden=%v", source, hidden)
		}
	}
}

func TestTargetResolverIsBatchLocal(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "x.go"), []byte("package actual\n"), 0644); err != nil {
		t.Fatal(err)
	}
	one := targetPkgResolverFn(func(string) (string, bool, error) { return "first", true, nil })
	two := targetPkgResolverFn(func(string) (string, bool, error) { return "second", true, nil })
	ctxt := envBuildContext(t)
	for _, row := range []struct {
		fn   targetPkgResolverFn
		want string
	}{{one, "first"}, {two, "second"}, {one, "first"}} {
		got, err := packageDirName(dir, ctxt, row.fn)
		if err != nil || got != row.want {
			t.Fatalf("local resolver got=%s err=%v", got, err)
		}
	}
	got, err := packageDirName(dir, ctxt)
	if err != nil || got != "actual" {
		t.Fatalf("resolver leaked outside batch: %s %v", got, err)
	}
}

