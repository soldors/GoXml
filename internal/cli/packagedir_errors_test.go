// ============================================================================
// R7-B B2：包目录读取/解析错误不再被当作空目录回退。
//
// 旧代码两处 continue（风险线索，任务书点名）：ReadFile 失败 continue、
// parsePackageName 失败 continue——被构建选择命中的文件静默缺席后，
// 目录被误判「未初始化」，--out-dir 下回退源包名写出错误产物。
//
// 证明手段分层（任务书允许「可重复文件操作注入或真实文件系统反例」，
// 但注入不得标成真实 OS 故障）：
//   - 读取失败：readPackageFile 注入（真实 OS 下 Windows 无法可移植地
//     构造「ReadDir 列出但 ReadFile 拒绝」的文件；注入只证明接线，
//     不声称 OS 故障）；
//   - 解析失败 / 不回退 / 失败不写盘：真实文件系统反例（确定性），
//     并与 go list 权威对照。
// ============================================================================

// TestPackageDirNameUnreadableMatchedFileFailsClosed 注入读取失败：
// 被构建选择命中的文件读不到必须报错且保留 cause（注入证明接线）。
func TestPackageDirNameUnreadableMatchedFileFailsClosed(t *testing.T) {
	root := newScratchModule(t)
	dir := filepath.Join(root, "p")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	writeGoFile(t, dir, "a.go", "package solo\n")

	sentinel := errors.New("injected: read denied")
	orig := readPackageFile
	readPackageFile = func(string) ([]byte, error) { return nil, sentinel }
	defer func() { readPackageFile = orig }()

	_, err := packageDirName(dir, envBuildContext(t))
	if err == nil {
		t.Fatal("读取失败必须报错，不得当作空目录回退")
	}
	if !errors.Is(err, sentinel) {
		t.Errorf("错误必须保留注入的 cause（%v），实际: %v", sentinel, err)
	}
	if !strings.Contains(err.Error(), "a.go") {
		t.Errorf("错误应可定位到文件，实际: %v", err)
	}
}

// TestPackageDirNameMalformedPackageClauseFailsClosed 真实反例：
// 目录唯一被命中的文件没有合法 package 子句——go build 下该目录本来就
// 编译失败，CLI 必须 fail-closed 并与 go list 同判。
func TestPackageDirNameMalformedPackageClauseFailsClosed(t *testing.T) {
	root := newScratchModule(t)
	dir := filepath.Join(root, "broken")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	writeGoFile(t, dir, "broken.go", "this file has no package clause\n")

	_, err := packageDirName(dir, envBuildContext(t))
	if err == nil {
		t.Fatal("无 package 子句的被选中文件必须报错")
	}
	if !strings.Contains(err.Error(), "package 子句") {
		t.Errorf("错误应指明 package 子句问题，实际: %v", err)
	}
	// 权威对照：go list 对该目录同样 Incomplete。
	if _, inc := goListPackage(t, root, dir, ""); !inc {
		t.Fatal("对照前提：go list 也应报该目录不完整（fixture 前提漂移）")
	}
}

// TestResolveInputMalformedTargetDoesNotFallback 真实反例：--out-dir
// 目标目录里只有坏文件时不得回退源包名（回退只属于未初始化目录）。
func TestResolveInputMalformedTargetDoesNotFallback(t *testing.T) {
	root := newScratchModule(t)
	srcDir := filepath.Join(root, "src")
	outDir := filepath.Join(root, "out")
	if err := os.MkdirAll(srcDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		t.Fatal(err)
	}
	writeGoFile(t, srcDir, "vm.go", "package src\n\ntype VM struct{ Title string }\n")
	writeGoFile(t, outDir, "broken.go", "no package here\n")
	gxml := filepath.Join(srcDir, "home.gxml")
	if err := os.WriteFile(gxml, []byte(`<Goxml Version="1" ViewModel="src.VM"><Page Route="/home"><Text Value="{Title}"/></Page></Goxml>`), 0o644); err != nil {
		t.Fatal(err)
	}

	in := discovered{abs: gxml, rel: "home.gxml", sourceDir: srcDir}
	if _, err := resolveInput(in, root, outDir, envBuildContext(t)); err == nil {
		t.Fatal("目标目录只有坏文件时必须 fail-closed，不得回退源包名")
	}

	// 对照：目标目录确实为空（不存在）→ 仍走既有回退（兼容首建新目录）。
	empty := filepath.Join(root, "out-empty")
	r, err := resolveInput(in, root, empty, envBuildContext(t))
	if err != nil {
		t.Fatalf("不存在的目标目录应回退源包名: %v", err)
	}
	if r.pkgName != "src" {
		t.Errorf("回退应取源包名 src，实际 %q", r.pkgName)
	}
}

// TestGenerateBrokenTargetPreservesOldFiles 端到端（真实 CLI）：目标目录
// 坏文件导致定名失败时，旧产物字节/mtime 与 Manifest 必须原样保留
// （失败发生在阶段零，任何写盘都不该发生）。
func TestGenerateBrokenTargetPreservesOldFiles(t *testing.T) {
	root := newScratchModule(t)
	srcDir := filepath.Join(root, "src")
	outDir := filepath.Join(root, "out")
	if err := os.MkdirAll(srcDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		t.Fatal(err)
	}
	writeGoFile(t, srcDir, "vm.go", "package src\n\ntype VM struct{ Title string }\n")
	writeGoFile(t, outDir, "old_gen.go",
		"// Code generated by goxml. DO NOT EDIT.\n// Source: old.gxml\n// Goxml-Version: 1\n\npackage out\n")
	writeGoFile(t, outDir, "broken.go", "no package here\n")
	gxml := filepath.Join(srcDir, "home.gxml")
	if err := os.WriteFile(gxml, []byte(`<Goxml Version="1" ViewModel="src.VM"><Page Route="/home"><Text Value="{Title}"/></Page></Goxml>`), 0o644); err != nil {
		t.Fatal(err)
	}
	// 先登记旧产物，让「旧 gen/Manifest 保持」可观测。
	if err := saveManifest(manifestPath(root), &manifest{Version: manifestVersion, Entries: []entry{{
		Source: "src/old.gxml", Output: "out/old_gen.go", InputHash: "x", CompilerVersion: "1",
	}}}); err != nil {
		t.Fatal(err)
	}
	oldBytes, err := os.ReadFile(filepath.Join(outDir, "old_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	manifestBefore, err := os.ReadFile(manifestPath(root))
	if err != nil {
		t.Fatal(err)
	}

	var out, errb bytes.Buffer
	code := Run([]string{"generate", gxml, "--out-dir", outDir}, &out, &errb)
	if code == ExitOK {
		t.Fatalf("坏目标目录必须失败:\nstdout:%s\nstderr:%s", out.String(), errb.String())
	}
	if !strings.Contains(errb.String(), "package 子句") && !strings.Contains(errb.String(), "定名失败") {
		t.Errorf("错误应可消费（指向坏文件/定名），实际 stderr:\n%s", errb.String())
	}
	newBytes, err := os.ReadFile(filepath.Join(outDir, "old_gen.go"))
	if err != nil || string(newBytes) != string(oldBytes) {
		t.Fatalf("旧产物字节必须保持不变: err=%v", err)
	}
	if _, err := os.Stat(filepath.Join(outDir, "home_gen.go")); !os.IsNotExist(err) {
		t.Fatalf("失败批次不得写出新产物: err=%v", err)
	}
	manifestAfter, err := os.ReadFile(manifestPath(root))
	if err != nil || string(manifestAfter) != string(manifestBefore) {
		t.Fatalf("Manifest 必须保持不变: err=%v", err)
	}
}
