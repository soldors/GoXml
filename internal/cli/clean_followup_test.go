// 造一个最小工程 + Manifest；产物带合法保护头。返回 (moduleRoot, manifestPath)。
func cleanFixture(t *testing.T, entries []entry, existingOutputs map[string]string) (string, string) {
	t.Helper()
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.com/c\n\ngo 1.24\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	m := &manifest{Version: 1, Entries: entries}
	mp := filepath.Join(root, ".goxml", "generate-manifest.json")
	if err := os.MkdirAll(filepath.Dir(mp), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := saveManifest(mp, m); err != nil {
		t.Fatal(err)
	}
	for rel, body := range existingOutputs {
		full := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root, mp
}

func genBody(sourceRel string) string {
	return "// Code generated by goxml. DO NOT EDIT.\n// Source: " + filepath.Base(sourceRel) +
		"\n// Goxml-Version: 1\n\npackage demo\n"
}

// 缺陷A：三个孤儿，第二、三个 remove 均失败 -> 两个 cause 都要能 errors.Is/As。
func TestCleanMultiRemoveFailuresAllCausesUnwrappable(t *testing.T) {
	entries := []entry{
		{Source: "a.gxml", Output: "a_gen.go", InputHash: "h", CompilerVersion: "1"},
		{Source: "b.gxml", Output: "b_gen.go", InputHash: "h", CompilerVersion: "1"},
		{Source: "c.gxml", Output: "c_gen.go", InputHash: "h", CompilerVersion: "1"},
	}
	root, _ := cleanFixture(t, entries, map[string]string{
		"a_gen.go": genBody("a.gxml"),
		"b_gen.go": genBody("b.gxml"),
		"c_gen.go": genBody("c.gxml"),
	})
	errDenied := errors.New("access denied")
	errBusy := errors.New("sharing violation")
	ops := realCleanOps
	ops.remove = func(p string) error {
		switch filepath.Base(p) {
		case "b_gen.go":
			return errDenied
		case "c_gen.go":
			return errBusy
		}
		return os.Remove(p)
	}
	_, _, err := cleanOrphansOps(root, map[string]bool{}, ops)
	if err == nil {
		t.Fatal("两处删除失败应返回错误")
	}
	// 关键：两个失败的 cause 都必须能 errors.Is 命中（不能只留最后一个）。
	if !errors.Is(err, errDenied) {
		t.Errorf("缺陷A：首个失败 cause(errDenied) 应可 errors.Is 消费；%v", err)
	}
	if !errors.Is(err, errBusy) {
		t.Errorf("缺陷A：后续失败 cause(errBusy) 应可 errors.Is 消费；%v", err)
	}
	var cf *cleanFailure
	if !errors.As(err, &cf) {
		t.Fatalf("应为 *cleanFailure")
	}
	if len(cf.failed) != 2 {
		t.Errorf("failed 应含两项，实际 %v", cf.failed)
	}
}

