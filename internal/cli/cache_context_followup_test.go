// TestMeasuredCacheContextReadsGOENV 用临时 GOENV 文件注入 GOOS，验证
// measuredCacheContext 读到的是 go env 的实际值（含 GOENV 持久化），
// 而非父进程 os.Getenv（后者为空）。这是基线缺陷的直接判别。
func TestMeasuredCacheContextReadsGOENV(t *testing.T) {
	goExe, err := exec.LookPath("go")
	if err != nil {
		t.Skip("go 不在 PATH，跳过")
	}
	dir := t.TempDir()
	goenv := filepath.Join(dir, "goenv")
	if err := os.WriteFile(goenv, []byte("GOOS=js\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	// 确保父进程 os.Getenv("GOOS") 为空，突出「只读 env 会漏」。
	t.Setenv("GOOS", "")
	t.Setenv("GOENV", goenv)

	ctx, err := measuredCacheContext(goExe)
	if err != nil {
		t.Fatalf("measuredCacheContext: %v", err)
	}
	if !strings.Contains(ctx, `"GOOS":"js"`) {
		t.Fatalf("应读到 GOENV 持久化的 GOOS=js，实际上下文: %s", ctx)
	}
	// 反向对照：若基线用 os.Getenv("GOOS")，会得到空。这里证明新实现不依赖父 env。
	if os.Getenv("GOOS") != "" {
		t.Fatalf("前置失败：os.Getenv(GOOS) 应为空")
	}
}

// TestCacheContextDiffersAcrossGOENV：两个不同 GOENV（GOOS 不同）算出的上下文串必须不同。
func TestCacheContextDiffersAcrossGOENV(t *testing.T) {
	goExe, err := exec.LookPath("go")
	if err != nil {
		t.Skip("go 不在 PATH，跳过")
	}
	dir := t.TempDir()
	mk := func(name, content string) string {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}
	t.Setenv("GOOS", "")
	e1 := mk("e1", "GOOS=js\n")
	e2 := mk("e2", "GOOS=wasip1\n")

	run := func(goenv string) string {
		t.Setenv("GOENV", goenv)
		ctx, err := measuredCacheContext(goExe)
		if err != nil {
			t.Fatalf("ctx: %v", err)
		}
		return ctx
	}
	c1 := run(e1)
	c2 := run(e2)
	if c1 == c2 {
		t.Fatalf("不同 GOENV GOOS 却得到相同上下文（会假命中）: %s", c1)
	}
}

// TestMeasuredCacheContextGoFailure 是「go env 失败 -> 返回 error」的守卫（保守 miss 前置）。
func TestMeasuredCacheContextGoFailure(t *testing.T) {
	// 用一个不存在的 go 可执行 -> go env 失败 -> 必须返回 error（调用方据此 conservative miss）。
	if _, err := measuredCacheContext(filepath.Join(t.TempDir(), "no-such-go")); err == nil {
		t.Fatal("go 不存在时应返回 error（保守 miss 前置）")
	}
}

// TestDecideCacheHitDependencyUnsafeForcesMiss：dependencyUnsafe=true 时即便键与记录
// 看似可用也必须 miss（走正常分析），不能假命中。
func TestDecideCacheHitDependencyUnsafeForcesMiss(t *testing.T) {
	dir := t.TempDir()
	// 造一个合法保护头产物（用户未接管），使「若无 dependencyUnsafe 会尝试命中」。
	target := filepath.Join(dir, "x_gen.go")
	body := "// Code generated by goxml. DO NOT EDIT.\n// Source: x.gxml\n// Goxml-Version: 1\n\npackage demo\n"
	if err := os.WriteFile(target, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	r := &resolvedInput{target: target, outputRel: "x_gen.go", sourcePath: "x.gxml", sourceRel: "x.gxml",
		sourceHash: "abc", dependencyUnsafe: true}
	hit, reason, err := decideCacheHit(dir, r, "somekey", &manifest{}, map[string]cacheRecord{}, false)
	if err != nil {
		t.Fatalf("decideCacheHit: %v", err)
	}
	if hit {
		t.Fatal("dependencyUnsafe=true 时必须 miss，不得假命中")
	}
	if reason != reasonPackageSourcesChanged {
		t.Fatalf("保守 miss 原因应为 package-sources-changed，实际 %s", reason)
	}
}
