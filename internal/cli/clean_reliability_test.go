// ownershipProject 建一个静态双页工程（无 VM/无包加载，进程内轻量）。
func ownershipProject(t *testing.T) string {
	t.Helper()
	// 重置包级路径覆盖：前序测试（batch_failure 等）可能设置了非空值，
	// 导致 manifestPath 返回错误路径 → cleanOrphansOps 读到空 Manifest。
	manifestPathOverride = ""
	t.Setenv("GOWORK", "off")
	t.Setenv("GOPROXY", "off")
	root := filepath.Join(t.TempDir(), "维护 工程")
	if err := os.MkdirAll(root, 0o755); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"go.mod", "go.sum"} {
		data := readCLIFile(t, filepath.Join(repoRoot(t), name))
		writeCLIFile(t, filepath.Join(root, name), data)
	}
	writeCLIFile(t, filepath.Join(root, "a.gxml"), []byte(`<Goxml Version="1"><Page><Text Value="A"/></Page></Goxml>`))
	writeCLIFile(t, filepath.Join(root, "b.gxml"), []byte(`<Goxml Version="1"><Page><Text Value="B"/></Page></Goxml>`))
	writeCLIFile(t, filepath.Join(root, "vm.go"), []byte("package demo\n"))
	return root
}

// genArtifact 手工构造带合法保护头的产物（Source=基名）。
func genArtifact(t *testing.T, path, sourceBase string) {
	t.Helper()
	header := "// Code generated by goxml. DO NOT EDIT.\n// Source: " + sourceBase + "\n// Goxml-Version: 1\n\npackage p\n"
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	writeCLIFile(t, path, []byte(header))
}

// manifestJSON 构造 schema 合法的 Manifest 字节。
func manifestJSON(entries ...[2]string) []byte {
	var b strings.Builder
	b.WriteString("{\n \"version\": 1,\n \"entries\": [\n")
	for i, e := range entries {
		b.WriteString("  {\"source\": \"" + e[0] + "\", \"output\": \"" + e[1] + "\", \"inputHash\": \"x" +
			string(rune('0'+i)) + "\", \"compilerVersion\": \"1\"}")
		if i != len(entries)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString(" ]\n}")
	return []byte(b.String())
}

func writeManifest(t *testing.T, root string, entries ...[2]string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Join(root, ".goxml"), 0o755); err != nil {
		t.Fatal(err)
	}
	writeCLIFile(t, filepath.Join(root, ".goxml", "generate-manifest.json"), manifestJSON(entries...))
}

func depsContainFile(list []string, substr string) bool {
	for _, s := range list {
		if strings.Contains(s, substr) {
			return true
		}
	}
	return false
}

// 切片 1-A：保护头 Source 与登记源基名不符 → 跳过且文件原样。
func TestCleanSkipsHeaderSourceMismatch(t *testing.T) {
	root := ownershipProject(t)
	genDir := filepath.Join(root, "gen")
	genArtifact(t, filepath.Join(genDir, "orphan_gen.go"), "other.gxml")
	writeManifest(t, root, [2]string{"gone.gxml", "gen/orphan_gen.go"})
	writeCLIFile(t, filepath.Join(root, "gone.gxml"), []byte(`<Goxml Version="1"><Page/></Goxml>`))
	if err := os.Remove(filepath.Join(root, "gone.gxml")); err != nil {
		t.Fatal(err)
	}
	code, out, errs := runStandaloneCLI(t, filepath.Join(root, "b.gxml"), "--clean")
	if code != ExitOK {
		t.Fatalf("--clean 应成功返回（跳过不是失败）: %d %s %s", code, out, errs)
	}
	if !strings.Contains(out, "保护头 Source 与登记不符，归属歧义") {
		t.Fatalf("应按归属歧义跳过:\n%s", out)
	}
	requireCLIBytes(t, filepath.Join(genDir, "orphan_gen.go"), readCLIFile(t, filepath.Join(genDir, "orphan_gen.go")))
}

// 切片 1-B：同一输出被另一源仍存在的登记声称 → 跳过（所有权争议）。
// 用 cleanOrphansOps 直接测试（不经过管线 manifest 重写，隔离所有权逻辑）。
func TestCleanSkipsContestedOutputWithAliveSource(t *testing.T) {
	root := t.TempDir()
	for _, name := range []string{"go.mod", "go.sum"} {
		writeCLIFile(t, filepath.Join(root, name), readCLIFile(t, filepath.Join(repoRoot(t), name)))
	}
	manifestPathOverride = ""
	genDir := filepath.Join(root, "gen")
	genArtifact(t, filepath.Join(genDir, "shared_gen.go"), "gone.gxml")
	writeManifest(t, root,
		[2]string{"gone.gxml", "gen/shared_gen.go"},
		[2]string{"alive.gxml", "gen/shared_gen.go"})
	t.Logf("DEBUG manifestPath(root)=%q", manifestPath(root))
	t.Logf("DEBUG writeManifest target=%q", filepath.Join(root, ".goxml", "generate-manifest.json"))
	// 验证 Manifest 确实写入了
	manData, manErr := os.ReadFile(filepath.Join(root, ".goxml", "generate-manifest.json"))
	if manErr != nil {
		t.Fatalf("Manifest 文件不存在: %v", manErr)
	}
	t.Logf("DEBUG manifest bytes=%d content=%s", len(manData), string(manData)[:min(200, len(manData))])
	writeCLIFile(t, filepath.Join(root, "alive.gxml"), []byte(`<Goxml Version="1"><Page><Text Value="alive"/></Page></Goxml>`))
	writeCLIFile(t, filepath.Join(root, "gone.gxml"), []byte(`<Goxml Version="1"><Page><Text Value="gone"/></Page></Goxml>`))
	if err := os.Remove(filepath.Join(root, "gone.gxml")); err != nil {
		t.Fatal(err)
	}
	deleted, skipped, err := cleanOrphansOps(root, map[string]bool{}, realCleanOps)
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("DEBUG deleted=%v skipped=%v", deleted, skipped)
	found := false
	for _, s := range skipped {
		if strings.Contains(s, "所有权争议") {
			found = true
		}
	}
	if !found {
		t.Fatalf("应按存活源争议跳过: deleted=%v skipped=%v", deleted, skipped)
	}
	requireCLIBytes(t, filepath.Join(genDir, "shared_gen.go"), readCLIFile(t, filepath.Join(genDir, "shared_gen.go")))
}

