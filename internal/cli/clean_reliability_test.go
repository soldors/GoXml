// 切片 2-A：第二个孤儿删除失败（真实句柄占用）→ cleanFailure 携带
// 已删除/失败/未执行三类清单；已删除文件保持已删；失败项如实入账。
func TestCleanFailureCarriesStructuredAccounting(t *testing.T) {
	root := ownershipProject(t)
	genDir := filepath.Join(root, "gen")
	for _, s := range []string{"o1.gxml", "o2.gxml", "o3.gxml"} {
		writeCLIFile(t, filepath.Join(root, s), []byte(`<Goxml Version="1"><Page><Text Value="x"/></Page></Goxml>`))
	}
	genArtifact(t, filepath.Join(genDir, "o1_gen.go"), "o1.gxml")
	genArtifact(t, filepath.Join(genDir, "o2_gen.go"), "o2.gxml")
	genArtifact(t, filepath.Join(genDir, "o3_gen.go"), "o3.gxml")
	writeManifest(t, root,
		[2]string{"o1.gxml", "gen/o1_gen.go"},
		[2]string{"o2.gxml", "gen/o2_gen.go"},
		[2]string{"o3.gxml", "gen/o3_gen.go"})
	for _, s := range []string{"o1.gxml", "o2.gxml", "o3.gxml"} {
		if err := os.Remove(filepath.Join(root, s)); err != nil {
			t.Fatal(err)
		}
	}
	h := openWithoutDelete(t, filepath.Join(genDir, "o2_gen.go"))
	defer closeHandle(t, h)

	_, _, err := cleanOrphansOps(root, map[string]bool{}, realCleanOps)
	if err == nil {
		t.Fatal("o2 删除失败必须返回错误")
	}
	var cf *cleanFailure
	if !errors.As(err, &cf) {
		t.Fatalf("应为 *cleanFailure: %v", err)
	}
	// 清理逐孤儿独立：失败不阻断后续，但失败如实入账。
	if len(cf.deleted) != 2 || !depsContainFile(cf.deleted, "o1_gen.go") || !depsContainFile(cf.deleted, "o3_gen.go") {
		t.Fatalf("已删除事实（含失败后续项）: %v", cf.deleted)
	}
	if len(cf.failed) != 1 || !strings.Contains(cf.failed[0], "o2_gen.go") {
		t.Fatalf("失败项必须记录: %v", cf.failed)
	}
	if len(cf.pending) != 0 {
		t.Fatalf("继续处理后不应有未执行项: %v", cf.pending)
	}
	if !strings.Contains(err.Error(), "解除占用") {
		t.Fatalf("文案必须说明可恢复: %q", err.Error())
	}
	for _, want := range []string{"o1_gen.go", "o3_gen.go"} {
		if _, statErr := os.Stat(filepath.Join(genDir, want)); !os.IsNotExist(statErr) {
			t.Fatalf("%s 应保持已删除", want)
		}
	}
	manData := readCLIFile(t, filepath.Join(root, ".goxml", "generate-manifest.json"))
	if !strings.Contains(string(manData), "o1.gxml") {
		t.Fatal("失败路径 Manifest 不应移除已删除条目")
	}
}

// 切片 2-B：注入 remove 失败于第二个孤儿 → 已删除事实保留，重跑恢复。
// 这里用受控注入稳定覆盖重试；上面的 TestCleanFailureCarriesStructuredAccounting
// 已用真实无 FILE_SHARE_DELETE 句柄验证本机拒绝删除，不能把注入说明误读为
// Go 版本使真实 Windows 共享删除锁失效。
func TestCleanRetryAfterHandleReleaseCompletes(t *testing.T) {
	root := t.TempDir()
	for _, name := range []string{"go.mod", "go.sum"} {
		writeCLIFile(t, filepath.Join(root, name), readCLIFile(t, filepath.Join(repoRoot(t), name)))
	}
	manifestPathOverride = ""
	genDir := filepath.Join(root, "gen")
	genArtifact(t, filepath.Join(genDir, "o1_gen.go"), "o1.gxml")
	genArtifact(t, filepath.Join(genDir, "o2_gen.go"), "o2.gxml")
	writeManifest(t, root, [2]string{"o1.gxml", "gen/o1_gen.go"}, [2]string{"o2.gxml", "gen/o2_gen.go"})
	for _, s := range []string{"o1.gxml", "o2.gxml"} {
		os.Remove(filepath.Join(root, s))
	}
	// 注入：o2 的 remove 失败（模拟句柄占用）；o1 正常。
	ops := realCleanOps
	ops.remove = func(path string) error {
		if strings.Contains(path, "o2_gen.go") {
			return errors.New("injected: access denied (handle held)")
		}
		return os.Remove(path)
	}
	_, _, err := cleanOrphansOps(root, map[string]bool{}, ops)
	if err == nil {
		t.Fatal("o2 删除失败必须返回错误")
	}
	var cf *cleanFailure
	if !errors.As(err, &cf) {
		t.Fatalf("应为 *cleanFailure: %v", err)
	}
	if len(cf.deleted) != 1 || !strings.Contains(cf.deleted[0], "o1_gen.go") {
		t.Fatalf("已删除事实必须保留: %v", cf.deleted)
	}
	if len(cf.failed) != 1 || !strings.Contains(cf.failed[0], "o2_gen.go") {
		t.Fatalf("失败项必须记录: %v", cf.failed)
	}
	// 修复后重跑（不注入）→ o2 正常删除。
	deleted2, _, err2 := cleanOrphansOps(root, map[string]bool{}, realCleanOps)
	if err2 != nil {
		t.Fatalf("重跑清理应成功: %v", err2)
	}
	if len(deleted2) != 1 || !strings.Contains(deleted2[0], "o2_gen.go") {
		t.Fatalf("重跑应只删除 o2: %v", deleted2)
	}
	if _, statErr := os.Stat(filepath.Join(genDir, "o1_gen.go")); !os.IsNotExist(statErr) {
		t.Fatal("o1 不应被重复处理（首轮已删）")
	}
}

// 切片 2-C：Manifest 保存失败不丢已删除事实。
func TestCleanSaveFailureKeepsDeletedFacts(t *testing.T) {
	root := ownershipProject(t)
	genDir := filepath.Join(root, "gen")
	writeCLIFile(t, filepath.Join(root, "only.gxml"), []byte(`<Goxml Version="1"><Page><Text Value="o"/></Page></Goxml>`))
	genArtifact(t, filepath.Join(genDir, "only_gen.go"), "only.gxml")
	writeManifest(t, root, [2]string{"only.gxml", "gen/only_gen.go"})
	if err := os.Remove(filepath.Join(root, "only.gxml")); err != nil {
		t.Fatal(err)
	}
	ops := realCleanOps
	ops.saveManifest = func(path string, m *manifest) error {
		return errors.New("injected: manifest save failed")
	}
	_, _, err := cleanOrphansOps(root, map[string]bool{}, ops)
	if err == nil {
		t.Fatal("保存失败必须返回错误")
	}
	var cf *cleanFailure
	if !errors.As(err, &cf) {
		t.Fatalf("应为 *cleanFailure: %v", err)
	}
	if len(cf.deleted) != 1 || !strings.Contains(cf.deleted[0], "only_gen.go") {
		t.Fatalf("已删除事实必须保留在结构化错误中: %v", cf.deleted)
	}
	if !strings.Contains(err.Error(), "injected") {
		t.Fatalf("cause 应可穿透: %v", err)
	}
}
