// Package docgate 校验文档同步：dev-log 是否覆盖了约定的提交范围。
//
// 本包**没有生产代码**，只有测试。它是一道门禁，由 `go test ./...` 触发，
// 与 `internal/compiler/diagdoc` 同构。
//
// # 这个门禁能做什么、不能做什么
//
// 能：机械检查「提交号是否出现在 dev-log 文本中」。
//
// 不能（仍依赖 AGENT.md §4 的文档同步规则与代码审查）：
//   - 判断日志内容是否准确；
//   - 判断 CHANGELOG 是否该有条目（语义判断）；
//   - 判断某文档描述的事实是否已经过期。
//
// 因此它是**下限**：通过 ≠ 文档已同步；不通过 = 一定有提交没记录。
//
// # 自引用问题
//
// Git 提交无法在自己的内容里记录自己的最终 hash。所以门禁**排除 HEAD**——
// 对 HEAD 的日志记录只可能出现在它的子提交里。这是有意的取舍，不是遗漏。
//
// # 为什么之前用 bash 又放弃了
//
// 最初写的是 `scripts/check-doc-sync`（bash）。实测发现两个问题：
//   - 主平台是 Windows，PATH 里不一定有 bash；
//   - WSL 的 bash 里没有 git（Windows git 在 /mnt/c 下，需特判路径）。
//
// 更关键的是第三个问题：初版在 git 不可用时**静默返回 exit 0**，
// 是典型的「假门禁」。改用 Go 实现后，`exec.Command("git")` 失败会直接
// 让测试失败，不会被误当成通过。
